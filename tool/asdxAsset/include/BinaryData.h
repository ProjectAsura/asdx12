#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <vector>

//-----------------------------------------------------------------------------
// Type Alias
//-----------------------------------------------------------------------------
using Binary = std::vector<uint8_t>;

//-----------------------------------------------------------------------------
//! @brief       バイナリデータを保存します.
//! 
//! @param[in]      path        保存先パス.
//! @param[in]      binary      保存するバイナリデータ.
//! @retval true    保存に成功.
//! @retval false   保存に失敗.
//-----------------------------------------------------------------------------
bool SaveBinary(const char* path, const Binary& binary);

//-----------------------------------------------------------------------------
//! @brief       バイナリデータにコピーします.
//! 
//! @param[in]      pSrc        コピー元データ.
//! @param[in]      size        コピーするサイズ.
//! @param[out]     binary      コピー先バイナリデータ.
//-----------------------------------------------------------------------------
void CopyToBinary(const void* pSrc, size_t size, Binary& binary);