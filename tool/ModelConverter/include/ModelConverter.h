#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <string>
#include <map>
#include <assimp/Importer.hpp>
#include <assimp/scene.h>
#include <assimp/postprocess.h>
#include <ModelBinary_generated.h>
#include <fnd/asdxMath.h>


///////////////////////////////////////////////////////////////////////////////
// ModelConverter class
///////////////////////////////////////////////////////////////////////////////
class ModelConverter
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Desc structure
    ///////////////////////////////////////////////////////////////////////////
    struct Desc
    {
        std::string InputPath;      //!< 入力ファイルパス.
        std::string OutputPath;     //!< 出力ファイルパス.
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelConverter() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelConverter() = default;

    //-------------------------------------------------------------------------
    //! @brief      変換処理を行います.
    //! 
    //! @param[in]      desc        変換設定.
    //! @retval true    変換に成功.
    //! @retval false   変換に失敗.
    //-------------------------------------------------------------------------
    bool Convert(const Desc& desc);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    struct BoneInfo
    {
        uint32_t        Index;
        std::string     Name;
        asdx::Matrix    OffsetMatrix;   // Inverse Bind Pose Matrix.
    };
    std::map<std::string, BoneInfo> m_BoneMap;

    //=========================================================================
    // private methods.
    //=========================================================================
    void ParseMesh(
        flatbuffers::FlatBufferBuilder& builder,
        const char* materialTag,
        flatbuffers::Offset<asdx::res::Mesh>& dstMesh, const aiMesh* srcMesh);
};

