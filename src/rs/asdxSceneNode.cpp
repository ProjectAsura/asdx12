#include <cassert>
#include <rs/asdxSceneNode.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// SceneNode class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      親ノードを設定します.
//-----------------------------------------------------------------------------
void SceneNode::SetParent(SceneNode* value)
{ m_pParent = value; }

//-----------------------------------------------------------------------------
//      親ノードを取得します.
//-----------------------------------------------------------------------------
SceneNode* SceneNode::GetParent() const
{ return m_pParent; }

//-----------------------------------------------------------------------------
//      子ノードを追加します.
//-----------------------------------------------------------------------------
void SceneNode::AddChild(SceneNode* child)
{
    assert(child != nullptr);
    if (child == nullptr)
        return;

    m_Children.push_back(child);
}

//-----------------------------------------------------------------------------
//      子ノードを削除します.
//-----------------------------------------------------------------------------
void SceneNode::RemoveChild(SceneNode* child)
{
    assert(child != nullptr);
    if (child == nullptr)
        return;

    auto itr = std::find(m_Children.begin(), m_Children.end(), child);
    if (itr == m_Children.end())
        return;

    m_Children.erase(itr);
    child->m_pParent = nullptr;
}

//-----------------------------------------------------------------------------
//      子ノードリストを取得します.
//-----------------------------------------------------------------------------
const std::vector<SceneNode*>& SceneNode::GetChildren() const
{ return m_Children; }

//-----------------------------------------------------------------------------
//      トランスフォームデータを取得します.
//-----------------------------------------------------------------------------
Transform& SceneNode::GetTransform() 
{ return m_Transform; }

//-----------------------------------------------------------------------------
//      トランスフォームデータを取得します(const版).
//-----------------------------------------------------------------------------
const Transform& SceneNode::GetTransform() const
{ return m_Transform; }

//-----------------------------------------------------------------------------
//      名前を設定します.
//-----------------------------------------------------------------------------
void SceneNode::SetName(const std::string& value)
{ m_Name = value; }

//-----------------------------------------------------------------------------
//      名前を設定します.
//-----------------------------------------------------------------------------
void SceneNode::SetName(const char* value)
{ m_Name = value; }

//-----------------------------------------------------------------------------
//      名前を取得します.
//-----------------------------------------------------------------------------
const std::string& SceneNode::GetName() const
{ return m_Name; }

} // namesapce asdx
