#include <rs/asdxModelComponent.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ModelComponent class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
ModelComponent::~ModelComponent()
{ ResetModel(); }

//-----------------------------------------------------------------------------
//      モデルを設定します.
//-----------------------------------------------------------------------------
void ModelComponent::SetModelHolder(ModelHolder&& value)
{ m_Model = value; }

//-----------------------------------------------------------------------------
//      モデルを取得します.
//-----------------------------------------------------------------------------
const ModelHolder& ModelComponent::GetModelHolder() const
{ return m_Model; }

//-----------------------------------------------------------------------------
//      モデルを解放します.
//-----------------------------------------------------------------------------
void ModelComponent::ResetModel()
{ m_Model.Reset(); }

//-----------------------------------------------------------------------------
//      モデルを保持するかチェックします.
//-----------------------------------------------------------------------------
bool ModelComponent::HasModel() const
{ return m_Model.IsValid(); }

//-----------------------------------------------------------------------------
//      可視フラグを設定します.
//-----------------------------------------------------------------------------
void ModelComponent::SetVisible(bool value)
{ m_Visible = value; }

//-----------------------------------------------------------------------------
//      可視フラグを取得します.
//-----------------------------------------------------------------------------
bool ModelComponent::IsVisible() const
{ return m_Visible; }

//-----------------------------------------------------------------------------
//      シャドウキャストフラグを設定します.
//-----------------------------------------------------------------------------
void ModelComponent::SetCastShadow(bool value)
{ m_CastShadow = value; }

//-----------------------------------------------------------------------------
//      シャドウキャストフラグを取得します.
//-----------------------------------------------------------------------------
bool ModelComponent::IsCastShadow() const
{ return m_CastShadow; }

} // namespace asdx
