{ return m_Color; }

//-----------------------------------------------------------------------------
//      ライト強度を設定します.
//-----------------------------------------------------------------------------
void PointLightComponent::SetIntensity(float value)
{ m_Intensity = value; }

//-----------------------------------------------------------------------------
//      ライト強度を取得します.
