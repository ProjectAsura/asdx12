#include <rs/asdxSpotLightComponent.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// SpotLightComponent class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      ライトの照射方向を設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetForward(const Vector3& value)
{ m_Forward = value; }

//-----------------------------------------------------------------------------
//      ライトの照射方向を返却します.
//-----------------------------------------------------------------------------
const Vector3& SpotLightComponent::GetForward() const
{ return m_Forward; }

//-----------------------------------------------------------------------------
//      カラーを設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetColor(const Vector3& value)
{ m_Color = value; }

//-----------------------------------------------------------------------------
//      カラーを取得します.
//-----------------------------------------------------------------------------
const Vector3& SpotLightComponent::GetColor() const
{ return m_Color; }

//-----------------------------------------------------------------------------
//      ライト強度を設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetIntensity(float value)
{ m_Intensity = value; }

//-----------------------------------------------------------------------------
//      ライト強度を返却します.
//-----------------------------------------------------------------------------
float SpotLightComponent::GetIntensity() const
{ return m_Intensity; }

//-----------------------------------------------------------------------------
//      半径を設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetRadius(float value)
{ m_Radius = value; }

//-----------------------------------------------------------------------------
//      半径を取得します.
//-----------------------------------------------------------------------------
float SpotLightComponent::GetRadius() const
{ return m_Radius; }

//-----------------------------------------------------------------------------
//      内角を設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetInnerAngle(float rad)
{ m_InnerAngle = rad; }

//-----------------------------------------------------------------------------
//      内角を取得します.
//-----------------------------------------------------------------------------
float SpotLightComponent::GetInnerAngle() const
{ return m_InnerAngle; }

//-----------------------------------------------------------------------------
//      外角を設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetOuterAngle(float rad)
{ m_OuterAngle = rad; }

//-----------------------------------------------------------------------------
//      外角を取得します.
//-----------------------------------------------------------------------------
float SpotLightComponent::GetOuterAngle() const
{ return m_OuterAngle; }

//-----------------------------------------------------------------------------
//      シャドウキャストフラグを設定します.
//-----------------------------------------------------------------------------
void SpotLightComponent::SetCastShadow(bool value)
{ m_CastShadow = value; }

//-----------------------------------------------------------------------------
//      シャドウキャストフラグを取得します.
//-----------------------------------------------------------------------------
bool SpotLightComponent::IsCastShadow() const
{ return m_CastShadow; }

} // namespace asdx
