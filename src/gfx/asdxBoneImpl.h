#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <vector>
#include <gfx/asdxModel.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Bone class
///////////////////////////////////////////////////////////////////////////////
class Bone : public IBone
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Bone() 
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Bone() override
    {
        m_pParent = nullptr;
        m_Name    .clear();
        m_Children.clear();
    }

    //-------------------------------------------------------------------------
    //! @brief      ボーン名を取得します.
    //! 
    //! @return     ボーン名を返却します.
    //-------------------------------------------------------------------------
    const std::string& GetName() const override
    { return m_Name; }

    //-------------------------------------------------------------------------
    //! @brief      親ボーンを取得します.
    //! 
    //! @return     親ボーンを返却します.
    //-------------------------------------------------------------------------
    const IBone* GetParent() const override
    { return m_pParent; }

    //-------------------------------------------------------------------------
    //! @brief      オフセット行列を取得します.
    //! 
    //! @return     オフセット行列を返却します.
    //-------------------------------------------------------------------------
    const Matrix& GetOffsetMatrix() const override
    { return m_OffsetMatrix; }

    //-------------------------------------------------------------------------
    //! @brief      子ボーンの数を取得します.
    //! 
    //! @return     子ボーンの数を返却します.
    //-------------------------------------------------------------------------
    size_t GetChildCount() const override
    { return m_Children.size(); }

    //-------------------------------------------------------------------------
    //! @brief      子ボーンを取得します.
    //! 
    //! @return     子ボーンを返却します.
    //-------------------------------------------------------------------------
    const IBone* GetChild(size_t index) const override
    { return m_Children.at(index); }

    //-------------------------------------------------------------------------
    //! @brief      ボーン名を設定します.
    //! 
    //! @param[in]      value       設定する名前です.
    //-------------------------------------------------------------------------
    void SetName(const std::string& value)
    { m_Name = value; }

    //-------------------------------------------------------------------------
    //! @brief      親ボーンを設定します.
    //! 
    //! @param[in]      value       設定する親ボーンです.
    //-------------------------------------------------------------------------
    void SetParent(Bone* value)
    { m_pParent = value; }

    //-------------------------------------------------------------------------
    //! @brief      オフセットを行列を設定します.
    //! 
    //! @param[in]      value       設定するオフセット行列です.
    //-------------------------------------------------------------------------
    void SetOffsetMatrix(const Matrix& value)
    { m_OffsetMatrix = value; }

    //-------------------------------------------------------------------------
    //! @brief      子ボーンを取得します.
    //! 
    //! @return     子ボーンを返却します.
    //-------------------------------------------------------------------------
    std::vector<Bone*>& GetChildren() { return m_Children; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::string         m_Name          = {};
    Bone*               m_pParent       = nullptr;
    Matrix              m_OffsetMatrix  = Matrix::CreateIdentity();
    std::vector<Bone*>  m_Children      = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
