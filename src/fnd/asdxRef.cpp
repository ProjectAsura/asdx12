#include <fnd/asdxRef.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// RefBase class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
RefBase::RefBase()
: m_RefCount(1)
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
RefBase::~RefBase()
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      参照カウントを上げます.
//-----------------------------------------------------------------------------
void RefBase::AddRef()
{ m_RefCount++; }

//-----------------------------------------------------------------------------
//      解放処理を行います.
//-----------------------------------------------------------------------------
void RefBase::Release()
{
    m_RefCount--;
    if (m_RefCount == 0)
    { OnRelease(); }
}

//-----------------------------------------------------------------------------
//      参照カウントを取得します.
//-----------------------------------------------------------------------------
uint32_t RefBase::GetRefCount() const
{ return m_RefCount; }


///////////////////////////////////////////////////////////////////////////////
// WeakRef class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
WeakRef::WeakRef(IReference* pStrong)
: m_RefCount(1)
, m_pStrongRef(pStrong)
{
    if (m_pStrongRef)
        m_pStrongRef->AddRef();
}

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
WeakRef::~WeakRef()
{
    if (m_pStrongRef)
        m_pStrongRef->Release();
}

//-----------------------------------------------------------------------------
//      参照カウンタを上げます.
//-----------------------------------------------------------------------------
void WeakRef::AddRef()
{ m_RefCount++; }

//-----------------------------------------------------------------------------
//      解放処理を行います.
//-----------------------------------------------------------------------------
void WeakRef::Release()
{
    m_RefCount--;
    if (m_RefCount == 0)
    { delete this; }
}

//-----------------------------------------------------------------------------
//      参照カウンタを取得します.
//-----------------------------------------------------------------------------
uint32_t WeakRef::GetRefCount() const
{ return m_RefCount; }

//-----------------------------------------------------------------------------
//      監視対象のオブジェクトを取得します.
//-----------------------------------------------------------------------------
bool WeakRef::Resolve(IReference** ppOutRef)
{
    if (!ppOutRef)
        return false;

    IReference* pRef = m_pStrongRef;
    if (!pRef)
    {
        (*ppOutRef) = nullptr;
        return false;
    }

    pRef->AddRef();
    (*ppOutRef) = pRef;
    return true;
}


///////////////////////////////////////////////////////////////////////////////
// WeakRefSrcBase class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
WeakRefSrcBase::WeakRefSrcBase()
: m_pWeakRef(nullptr)
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
WeakRefSrcBase::~WeakRefSrcBase()
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      弱参照オブジェクトを取得します.
//-----------------------------------------------------------------------------
void WeakRefSrcBase::GetWeakReference(IWeakReference** ppOutWeakRef)
{
    if (!ppOutWeakRef)
        return;

    if (!m_pWeakRef)
        m_pWeakRef = new WeakRef(this);

    m_pWeakRef->AddRef();
    (*ppOutWeakRef) = m_pWeakRef;
}

//-----------------------------------------------------------------------------
//      解放処理です.
//-----------------------------------------------------------------------------
void WeakRefSrcBase::OnRelease()
{
    ReleaseWeakRef();
    delete this;
}

//-----------------------------------------------------------------------------
//      弱参照オブジェクトを解放します.
//-----------------------------------------------------------------------------
void WeakRefSrcBase::ReleaseWeakRef()
{
    if (m_pWeakRef)
    {
        m_pWeakRef->Release();
        m_pWeakRef = nullptr;
    }
}

} // namespace asdx
