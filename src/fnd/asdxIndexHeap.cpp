#include <fnd/asdxIndexHeap.h>


namespace asdx {

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
IndexHeap::IndexHeap()
: m_pNodes   (nullptr)
, m_Capacity (0)
, m_FreeCount(0)
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
IndexHeap::~IndexHeap()
{ Term(); }

//-----------------------------------------------------------------------------
//      初期化処理を行います.
//-----------------------------------------------------------------------------
bool IndexHeap::Init(uint32_t count)
{
    uint32_t allocCount = (count + 31) / 32;

    m_pNodes = new(std::nothrow) IndexNode[allocCount];
    if (m_pNodes == nullptr)
    { return false; }

    for(auto i=0u; i<allocCount; ++i)
    {
        m_pNodes[i].Offset = 32u * i;

        // 1ノードは32個のインデックスを管理するため、このノードで有効なビット数を求めます。
        // 最後のノードでは、count を超えた分のインデックスが存在しない場合があります.
        auto validBits = count - m_pNodes[i].Offset;
        if (validBits > 32u)
        { validBits = 32u; }

        // 有効なビットが32個未満の場合は、存在しないインデックスを使用済みにして
        // Alloc()から返されないようにします.
        m_pNodes[i].Flags = (validBits == 32u) ? 0u : UINT32_MAX << validBits;

        m_FreeList.push_back(&m_pNodes[i]);
    }
    m_FreeCount = count;
    m_Capacity  = count;

    return true;
}

//-----------------------------------------------------------------------------
//      終了処理を行います.
//-----------------------------------------------------------------------------
void IndexHeap::Term()
{
    m_FreeList.clear();
    if (m_pNodes != nullptr)
    {
        delete [] m_pNodes;
        m_pNodes = nullptr;
    }
    m_Capacity  = 0;
    m_FreeCount = 0;
}

//-----------------------------------------------------------------------------
//      インデックスを確保します.
//-----------------------------------------------------------------------------
uint32_t IndexHeap::Alloc()
{
    if (m_FreeList.empty())
        return UINT32_MAX;

    auto& head = m_FreeList.front();
    auto  bit  = FindZeroR(head.Flags);
    assert(bit > 0);

    head.Flags |= (0x1u << (bit - 1));
    if (head.Flags == UINT32_MAX)
    { m_FreeList.pop_front(); }
    m_FreeCount--;
    return head.Offset + (bit - 1);
}

//-----------------------------------------------------------------------------
//      インデックスを解放します.
//-----------------------------------------------------------------------------
void IndexHeap::Free(uint32_t value)
{
    auto nodeId = value / 32;
    auto bitsId = value % 32;
    assert(nodeId < m_Capacity);
    auto full = (m_pNodes[nodeId].Flags == UINT32_MAX);
    m_pNodes[nodeId].Flags &= ~(0x1u << bitsId);

    if (full)
    { m_FreeList.push_back(&m_pNodes[nodeId]); }
    m_FreeCount++;
}

//-----------------------------------------------------------------------------
//      使用数を取得します.
//-----------------------------------------------------------------------------
uint32_t IndexHeap::GetUsedCount() const
{ return m_Capacity - m_FreeCount; }

//-----------------------------------------------------------------------------
//      未割当数を取得します.
//-----------------------------------------------------------------------------
uint32_t IndexHeap::GetFreeCount() const
{ return m_FreeCount; }

//-----------------------------------------------------------------------------
//      最大数を取得します.
//-----------------------------------------------------------------------------
uint32_t IndexHeap::GetCapacity() const
{ return m_Capacity; }

//-----------------------------------------------------------------------------
//      フリーリストをソートします.
//-----------------------------------------------------------------------------
void IndexHeap::Sort()
{ m_FreeList.sort(); }

//-----------------------------------------------------------------------------
//      使用中かどうかチェックします.
//-----------------------------------------------------------------------------
bool IndexHeap::IsUsed(uint32_t value) const
{
    auto node = value / 32;
    auto bits = value % 32;
    return !!(m_pNodes[node].Flags & (0x1 << bits));
}

//-----------------------------------------------------------------------------
//      満杯であるかチェックします.
//-----------------------------------------------------------------------------
bool IndexHeap::IsFull() const
{ return m_FreeCount == 0; }

//-----------------------------------------------------------------------------
//      空であるかチェックします.
//-----------------------------------------------------------------------------
bool IndexHeap::IsEmpty() const
{ return m_FreeCount == m_Capacity; }

} // namespace asdx
