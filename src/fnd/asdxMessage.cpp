#include <cassert>
#include <fnd/asdxMessage.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Message class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      引数付きコンストラクタです.
//-----------------------------------------------------------------------------
Message::Message(uint32_t type, const void* buffer, uint64_t size)
: m_Type(type)
, m_pBuffer(buffer)
, m_Size(size)
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      メッセージタイプを取得します.
//-----------------------------------------------------------------------------
uint32_t Message::GetType() const
{ return m_Type; }

//-----------------------------------------------------------------------------
//      バッファサイズを取得します.
//-----------------------------------------------------------------------------
uint64_t Message::GetSize() const
{ return m_Size; }

//-----------------------------------------------------------------------------
//      バッファを返却します.
//-----------------------------------------------------------------------------
const void* Message::GetBuffer() const
{ return m_pBuffer; }


///////////////////////////////////////////////////////////////////////////////
// MessageHandler class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
MessageHandler::~MessageHandler()
{ m_Listeners.clear(); }

//-----------------------------------------------------------------------------
//      メッセージを送ります.
//-----------------------------------------------------------------------------
void MessageHandler::Send(const Message& msg)
{
    for(auto& itr : m_Listeners)
    { itr->OnMessage(msg); }
}

//-----------------------------------------------------------------------------
//      メッセージリスナーを追加します.
//-----------------------------------------------------------------------------
MessageHandler& MessageHandler::operator += (IMessageListener* listener)
{
    assert(listener != nullptr);
    m_Listeners.push_back(listener);
    return *this;
}
//-----------------------------------------------------------------------------
//      メッセージリスナーを削除します.
//-----------------------------------------------------------------------------
MessageHandler& MessageHandler::operator -= (IMessageListener* listener)
{
    assert(listener != nullptr);
    m_Listeners.remove(listener);
    return *this;
}


} // namespace asdx
