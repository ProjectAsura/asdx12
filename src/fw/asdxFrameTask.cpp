#include <fw/asdxFrameTask.h>

namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// FrameTaskManager class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
FrameTaskManager::FrameTaskManager()
: TaskManagerBase()
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
FrameTaskManager::~FrameTaskManager()
{ Term(); }

//-----------------------------------------------------------------------------
//      初期化処理を行います.
//-----------------------------------------------------------------------------
bool FrameTaskManager::Init(size_t size)
{ return m_Heap.Init(size); }

//-----------------------------------------------------------------------------
//      終了処理を行います.
//-----------------------------------------------------------------------------
void FrameTaskManager::Term()
{
    for(auto& task : m_TaskList)
    { task.OnRemove(); }

    m_TaskList.clear();
    m_Heap.Term();
}

//-----------------------------------------------------------------------------
//      メモリをリセットします.
//-----------------------------------------------------------------------------
void FrameTaskManager::Reset()
{
    for(auto& task : m_TaskList)
    { task.OnRemove(); }

    m_TaskList.clear();
    m_Heap.Reset();
}

//-----------------------------------------------------------------------------
//      メモリを確保します.
//-----------------------------------------------------------------------------
void* FrameTaskManager::Alloc(size_t size)
{ return m_Heap.Alloc(size); }

//-----------------------------------------------------------------------------
//      メモリを解放します.
//-----------------------------------------------------------------------------
void FrameTaskManager::Free(void*)
{ /* DO_NOTHING */ }

} // namespace asdx
