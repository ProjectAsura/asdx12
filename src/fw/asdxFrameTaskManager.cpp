#include <fw/asdxFrameTaskManager.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// FrameTaskManager class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
FrameTaskManager::FrameTaskManager()
: TaskManagerBase()
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
FrameTaskManager::~FrameTaskManager()
{ Term(); }

//-----------------------------------------------------------------------------
//      初期化処理を行います.
//-----------------------------------------------------------------------------
bool FrameTaskManager::Init(size_t size)
{ return m_Heap.Init(size); }

//-----------------------------------------------------------------------------
//      終了処理を行います.
//-----------------------------------------------------------------------------
void FrameTaskManager::Term()
{
    auto itr = m_TaskList.begin();
    while(itr != m_TaskList.end())
    {
        itr->OnRemove();
        itr = m_TaskList.erase(itr);
    }

    m_Heap.Term();
}

//-----------------------------------------------------------------------------
//      メモリをリセットします.
//-----------------------------------------------------------------------------
void FrameTaskManager::Reset()
{
    auto itr = m_TaskList.begin();
    while(itr != m_TaskList.end())
    {
        itr->OnRemove();
        itr = m_TaskList.erase(itr);
    }

    m_Heap.Reset();
}

//-----------------------------------------------------------------------------
//      メモリを確保します.
//-----------------------------------------------------------------------------
void* FrameTaskManager::Alloc(size_t size)
{ return m_Heap.Alloc(size); }

//-----------------------------------------------------------------------------
//      メモリを解放します.
//-----------------------------------------------------------------------------
void FrameTaskManager::Free(void*)
{ /* DO_NOTHING */ }

} // namespace asdx
