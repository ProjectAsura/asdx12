#include <fw/asdxFrameTaskManager.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// FrameTaskManager class
///////////////////////////////////////////////////////////////////////////////

//-----------------------------------------------------------------------------
//      コンストラクタです.
//-----------------------------------------------------------------------------
FrameTaskManager::FrameTaskManager()
: TaskManagerBase()
{ /* DO_NOTHING */ }

//-----------------------------------------------------------------------------
//      デストラクタです.
//-----------------------------------------------------------------------------
FrameTaskManager::~FrameTaskManager()
{ Term(); }

//-----------------------------------------------------------------------------
//      初期化処理を行います.
//-----------------------------------------------------------------------------
bool FrameTaskManager::Init(size_t size)
{
    m_UsedCount = 0;
    return m_Heap.Init(size);
}

//-----------------------------------------------------------------------------
//      終了処理を行います.
//-----------------------------------------------------------------------------
void FrameTaskManager::Term()
{
    auto itr = m_TaskList.begin();
    while(itr != m_TaskList.end())
    {
        itr->OnRemove();
        itr = m_TaskList.erase(itr);
    }

    m_Heap.Term();
    m_UsedCount = 0;
}

//-----------------------------------------------------------------------------
//      メモリをリセットします.
//-----------------------------------------------------------------------------
void FrameTaskManager::Reset()
{
    auto itr = m_TaskList.begin();
    while(itr != m_TaskList.end())
    {
        itr->OnRemove();
        itr = m_TaskList.erase(itr);
    }

    m_Heap.Reset();
    m_UsedCount = 0;
}

//-----------------------------------------------------------------------------
//      メモリを確保します.
//-----------------------------------------------------------------------------
void* FrameTaskManager::Alloc(size_t size)
{
    auto ptr = m_Heap.Alloc(size);
    if (ptr) { m_UsedCount++; }
    return ptr;
}

//-----------------------------------------------------------------------------
//      メモリを解放します.
//-----------------------------------------------------------------------------
void FrameTaskManager::Free(void*)
{ /* DO_NOTHING */ } // フレームヒープは解放処理をサポートしていない為, Reset()のみ.

//-----------------------------------------------------------------------------
//      割り当て済みタスク数を取得します.
//-----------------------------------------------------------------------------
uint32_t FrameTaskManager::GetUsedCount() const
{ return m_UsedCount; }

} // namespace asdx
