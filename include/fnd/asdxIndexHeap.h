namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// IndexHeap class
///////////////////////////////////////////////////////////////////////////////
class IndexHeap
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    IndexHeap();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~IndexHeap();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //-------------------------------------------------------------------------
    bool Init(uint32_t count);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      インデックスを確保します.
    //! 
    //! @return     インデックス番号を返却します.
    //! @note       インデックスが割り当てられない場合はUINT32_MAXを返却します.
    //-------------------------------------------------------------------------
    uint32_t Alloc();

    //-------------------------------------------------------------------------
    //! @brief      インデックスを解放します.
    //! 
    //! @param[in]      value       解放するインデックス.
    //-------------------------------------------------------------------------
    void Free(uint32_t value);

    //-------------------------------------------------------------------------
    //! @brief      全インデックスを解放します.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      使用数を取得します.
    //! 
    //! @return     使用しているインデックス数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetUsedCount() const;

    //-------------------------------------------------------------------------
    //! @brief      未割り当て数を取得します.
    //! 
    //! @return     未使用のインデックス数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetFreeCount() const;

    //-------------------------------------------------------------------------
    //! @brief      最大数を取得します.
    //! 
    //! @return     最大数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetCapacity() const;

    //-------------------------------------------------------------------------
    //! @brief      フリーリストをソートします.
    //-------------------------------------------------------------------------
    void Sort();

    //-------------------------------------------------------------------------
    //! @brief      使用中かどうかチェックします.
    //! 
    //! @param[in]      value       インデックス.
    //! @retval true    使用中です.
    //! @retval false   未使用です.
    //-------------------------------------------------------------------------
    bool IsUsed(uint32_t value) const;

    //-------------------------------------------------------------------------
    //! @brief      満杯であるかチェックします.
    //! 
    //! @return     満杯であれば true を返却します.
    //-------------------------------------------------------------------------
    bool IsFull() const;

    //-------------------------------------------------------------------------
    //! @brief      空であるかチェックします.
    //! 
    //! @return     空であれば true を返却します.
    //-------------------------------------------------------------------------
    bool IsEmpty() const;

private:
    ///////////////////////////////////////////////////////////////////////////
    // IndexNode structure
    ///////////////////////////////////////////////////////////////////////////
    struct IndexNode : List<IndexNode>::Node
    {
        uint32_t   Offset;
        uint32_t   Flags;

        bool operator < (const IndexNode& value) const
        { return Offset < value.Offset; }

        bool operator <= (const IndexNode& value) const
        { return Offset <= value.Offset; }

        bool operator > (const IndexNode& value) const
        { return Offset > value.Offset; }

        bool operator >= (const IndexNode& value) const
        { return Offset >= value.Offset; }

        bool operator == (const IndexNode& value) const
        { return Offset == value.Offset && Flags == value.Flags; }
    };

    //=========================================================================
    // private variables.
    //=========================================================================
    IndexNode*      m_pNodes      = nullptr;
    uint32_t        m_Capacity    = 0;
    uint32_t        m_FreeCount   = 0;
    List<IndexNode> m_FreeList    = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// ThreadSafeIndexHeap class
///////////////////////////////////////////////////////////////////////////////
class ThreadSafeIndexHeap
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ThreadSafeIndexHeap()
    : m_Heap()
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ThreadSafeIndexHeap()
    { Term(); }

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //-------------------------------------------------------------------------
    bool Init(uint32_t count)
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        return m_Heap.Init(count);
    }

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term()
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        m_Heap.Term();
    }

    //-------------------------------------------------------------------------
    //! @brief      インデックスを確保します.
    //! 
    //! @return     インデックス番号を返却します.
    //! @note       インデックスが割り当てられない場合はUINT32_MAXを返却します.
    //-------------------------------------------------------------------------
    uint32_t Alloc()
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        return m_Heap.Alloc();
    }

    //-------------------------------------------------------------------------
    //! @brief      インデックスを解放します.
    //! 
    //! @param[in]      value       解放するインデックス.
    //-------------------------------------------------------------------------
    void Free(uint32_t value)
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        m_Heap.Free(value);
    }

    //-------------------------------------------------------------------------
    //! @brief      使用数を取得します.
    //! 
    //! @return     使用しているインデックス数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetUsedCount() const
    { return m_Heap.GetUsedCount(); }

    //-------------------------------------------------------------------------
    //! @brief      未割り当て数を取得します.
    //! 
    //! @return     未使用のインデックス数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetFreeCount() const
    { return m_Heap.GetFreeCount(); }

    //-------------------------------------------------------------------------
    //! @brief      最大数を取得します.
    //! 
    //! @return     最大数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetCapacity() const
    { return m_Heap.GetCapacity(); }

    //-------------------------------------------------------------------------
    //! @brief      フリーリストをソートします.
    //-------------------------------------------------------------------------
    void Sort()
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        m_Heap.Sort();
    }

    //-------------------------------------------------------------------------
    //! @brief      使用中かどうかチェックします.
    //! 
    //! @param[in]      value       インデックス.
    //! @retval true    使用中です.
    //! @retval false   未使用です.
    //-------------------------------------------------------------------------
    bool IsUsed(uint32_t value)
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        return m_Heap.IsUsed(value);
    }

    //-------------------------------------------------------------------------
    //! @brief      満杯であるかチェックします.
    //! 
    //! @return     満杯であれば true を返却します.
    //-------------------------------------------------------------------------
    bool IsFull()
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        return m_Heap.IsFull();
    }

    //-------------------------------------------------------------------------
    //! @brief      空であるかチェックします.
    //! 
    //! @return     空であれば true を返却します.
    //-------------------------------------------------------------------------
    bool IsEmpty()
    {
        ScopedLock<SpinLock> locker(m_SpinLock);
        return m_Heap.IsEmpty();
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    SpinLock    m_SpinLock;
    IndexHeap   m_Heap;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
