#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <unordered_map>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// StateMachine class
///////////////////////////////////////////////////////////////////////////////
class StateMachine
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // IStateListener class
    ///////////////////////////////////////////////////////////////////////////
    struct IStateListener
    {
        //---------------------------------------------------------------------
        //! @brief      デストラクタです.
        //---------------------------------------------------------------------
        virtual ~IStateListener() {}

        //---------------------------------------------------------------------
        //! @brief      ステート開始時の処理です.
        //---------------------------------------------------------------------
        virtual void OnEnter() = 0;

        //---------------------------------------------------------------------
        //! @brief      ステート終了時の処理です.
        //---------------------------------------------------------------------
        virtual void OnLeave() = 0;

        //---------------------------------------------------------------------
        //! @brief      ステート更新の処理です.
        //---------------------------------------------------------------------
        virtual void OnUpdate(float deltaSec) = 0;

        //---------------------------------------------------------------------
        //! @brief      ステート名を取得します.
        //---------------------------------------------------------------------
        virtual const char* GetName() const = 0;
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    static const uint32_t kInvalidState = 0xffffffff;

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    StateMachine();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~StateMachine();

    //-------------------------------------------------------------------------
    //! @brief      ステートを登録します.
    //! 
    //! @param[in]      state       ステート.
    //! @param[in]      pListener   ステートリスナー.
    //! @retval true    登録に成功.
    //! @retval false   登録に失敗.
    //-------------------------------------------------------------------------
    bool RegisterState(uint32_t state, IStateListener* pListener);

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      ステートを変更します.
    //! 
    //! @param[in]      nextState       次のステート,
    //-------------------------------------------------------------------------
    void ChangeState(uint32_t nextState);

    //-------------------------------------------------------------------------
    //! @brief      現在のステートを取得します.
    //-------------------------------------------------------------------------
    uint32_t GetState() const;

private:
    ///////////////////////////////////////////////////////////////////////////
    // StateHolder structure
    ///////////////////////////////////////////////////////////////////////////
    struct StateHolder
    {
        uint32_t        State       = kInvalidState;    //!< ステート.
        IStateListener* pListener   = nullptr;          //!< リスナー.
    };

    //=========================================================================
    // private variables.
    //=========================================================================
    StateHolder                                     m_Holder;       //!< ステートホルダー.
    std::unordered_map<uint32_t, IStateListener*>   m_Listeners;    //!< リスナーリスト.
};

} // namespace asdx
