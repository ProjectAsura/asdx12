#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResHolder class
///////////////////////////////////////////////////////////////////////////////
template<typename T, typename Manager>
class ResHolder
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend Manager;

public:
    //=========================================================================
    // private variables.
    //=========================================================================

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ResHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ResHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //-------------------------------------------------------------------------
    void Reset()
    { Manager::Instance().Remove(*this); }

    //-------------------------------------------------------------------------
    //! @brief      有効かどうかチェックします.
    //! 
    //! @retval true    有効です.
    //! @retval false   無効です.
    //-------------------------------------------------------------------------
    bool IsValid() const
    { return (m_pRes != nullptr) && (m_Hash != 0); }

    //-------------------------------------------------------------------------
    //! @brief      リソースを取得します.
    //! 
    //! @return     リソースを返却します.
    //-------------------------------------------------------------------------
    const T* GetResource() const
    { return m_pRes; }

    //-------------------------------------------------------------------------
    //! @brief      アロー演算子です.
    //! 
    //! @return     リソースを返却します.
    //-------------------------------------------------------------------------
    const T* operator -> () const
    { return m_pRes; }

    //-------------------------------------------------------------------------
    //! @brief      等価比較演算子です.
    //! 
    //! @retval true    等価です.
    //! @retval false   非等価です.
    //-------------------------------------------------------------------------
    bool operator == (const ResHolder& value) const
    {
        return (m_pRes == value.m_pResource)
            && (m_Hash == value.m_Hash);
    }

    //-------------------------------------------------------------------------
    //! @brief      非等価比較演算子です.
    //! 
    //! @retval true    非等価です.
    //! @retval false   等価です.
    //-------------------------------------------------------------------------
    bool operator != (const ResHolder& value) const
    {
        return (m_pRes != value.m_pResource)
            || (m_Hash != value.m_Hash);
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    T*       m_pRes = nullptr;      //!< リソースです.
    uint64_t m_Hash = 0;            //!< ファイルハッシュです.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      pRes        リソースです.
    //! @param[in]      hash        ファイルハッシュです.
    //-------------------------------------------------------------------------
    ResHolder(T* pRes, uint64_t hash)
    : m_pRes(pRes)
    , m_Hash(hash)
    { /* DO_NOTHING */ }
};

} // namespace asdx
