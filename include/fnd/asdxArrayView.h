#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cassert>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ArrayView class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class ArrayView
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ArrayView()
    : m_pValues (nullptr)
    , m_Size    (0)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    ArrayView(const T* pValues, size_t size)
    : m_pValues (pValues)
    , m_Size    (size)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      指定された要素を取得します.
    //! 
    //! @param[in]      index       要素番号です.
    //! @return     指定された要素を返却します.
    //-------------------------------------------------------------------------
    const T& at(size_t index) const
    {
        assert(index < m_Size);
        assert(m_pValues != nullptr);
        return m_pValues[index];
    }

    //-------------------------------------------------------------------------
    //! @brief      インデクサです.
    //! 
    //! @param[in]      index       要素番号です.
    //! @return     指定された要素を返却します.
    //-------------------------------------------------------------------------
    const T& operator[](size_t index) const
    {
        assert(index < m_Size);
        assert(m_pValues != nullptr);
        return m_pValues[index];
    }

    //------------------------------------------------------------------------
    //! @brief      要素数を取得します.
    //! 
    //! @return     要素数を返却します.
    //------------------------------------------------------------------------
    size_t size() const
    { return m_Size; }

    //------------------------------------------------------------------------
    //! @brief      データを取得します.
    //! 
    //! @return     データを返却します.
    //------------------------------------------------------------------------
    const T* data() const
    { return m_pValues; }

    //-------------------------------------------------------------------------
    //! @brief      データが空かどうかチェックします.
    //! 
    //! @retval true    空です.
    //! @retval false   空ではないです.
    //-------------------------------------------------------------------------
    bool empty() const
    { return m_pValues == nullptr || m_Size == 0; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    const T*    m_pValues = nullptr;        //!< データです.
    size_t      m_Size    = 0;              //!< 要素数です.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
