#include <cstdint>
#include <list>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Message class
///////////////////////////////////////////////////////////////////////////////
class Message
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      type        メッセージタイプです.
    //! @param[in]      buffer      バッファです.
    //! @param[in]      size        バッファサイズです.
    //-------------------------------------------------------------------------
    explicit Message(uint32_t type, const void* buffer = nullptr, uint64_t size = 0);

    //-------------------------------------------------------------------------
    //! @brief      メッセージタイプを取得します.
    //! 
    //! @return     メッセージタイプを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetType() const;

    //-------------------------------------------------------------------------
    //! @brief      バッファサイズを取得します.
    //! 
    //! @return     バッファサイズを返却します.
    //-------------------------------------------------------------------------
    uint64_t GetSize() const;

    //-------------------------------------------------------------------------
    //! @brief      バッファを取得します.
    //! 
    //! @return     バッファを返却します.
    //-------------------------------------------------------------------------
    const void* GetBuffer() const;

    //-------------------------------------------------------------------------
    //! @brief      データ型を指定してバッファを取得します.
    //! 
    //! @return     データ型にキャストしたバッファを返却します.
    //-------------------------------------------------------------------------
    template<typename T>
    const T* GetAs() const
    { return reinterpret_cast<const T*>(GetBuffer()); }

protected:
    //=========================================================================
    // protected variables.
    //=========================================================================
    uint32_t    m_Type    = 0;
    uint64_t    m_Size    = 0;
    const void* m_pBuffer = nullptr;

    //=========================================================================
    // protected methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// IMessageListener interface
///////////////////////////////////////////////////////////////////////////////
struct IMessageListener
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~IMessageListener() = default;

    //-------------------------------------------------------------------------
    //! @brief      メッセージ受信時の処理です.
    //! 
    //! @param[in]      msg     通知メッセージです.
    //-------------------------------------------------------------------------
    virtual void OnMessage(const Message& msg) = 0;
};

///////////////////////////////////////////////////////////////////////////////
// TypedMessage class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class TypedMessage : public Message
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      type        メッセージタイプです.
    //! @param[in]      data        送信データ.
    //-------------------------------------------------------------------------
    explicit TypedMessage(uint32_t type, const T& data)
    : Message(type, &m_Data, sizeof(T))
    , m_Data (data)
    { /* DO_NOTHING */ }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    T m_Data = {};  //!< 送信データです.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// MessageHandler class
///////////////////////////////////////////////////////////////////////////////
class MessageHandler
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================

public:
    //=========================================================================
    // public variables.
    //=========================================================================

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MessageHandler() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MessageHandler();

    //-------------------------------------------------------------------------
    //! @brief      メッセージを送信します.
    //-------------------------------------------------------------------------
    void Send(const Message& msg);

    //-------------------------------------------------------------------------
    //! @brief      メッセージリスナーを追加します.
    //! 
    //! @param[in]      listiner        追加するメッセージリスナーです.
    //! @return     リスナー登録後のメッセージハンドラーを返却します.
    //-------------------------------------------------------------------------
    MessageHandler& operator += (IMessageListener* listener);

    //-------------------------------------------------------------------------
    //! @brief      メッセージリスナーを削除します.
    //! 
    //! @param[in]      listener        削除するメッセージリスナーです.
    //! @return     リスナー削除後のメッセージハンドラーを返却します.
    //-------------------------------------------------------------------------
    MessageHandler& operator -= (IMessageListener* listener);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::list<IMessageListener*> m_Listeners;   //!< メッセージリスナー.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx

