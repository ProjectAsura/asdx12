#include <cassert>
#include <cstdint>
#include <utility>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// StackAllocator class
///////////////////////////////////////////////////////////////////////////////
template<size_t MaxSize>
class StackAllocator
{
    // ※デストラクタは呼び出されない仕様なので注意してください.

    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    StackAllocator() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~StackAllocator() = default;

    //-------------------------------------------------------------------------
    //! @brief      メモリを確保します.
    //-------------------------------------------------------------------------
    void* Alloc(size_t size)
    {
        if (size >= GetFreeSize())
            return nullptr;

        return reinterpret_cast<void*>(&m_Buffer[m_Size += size]);
    }

    //-------------------------------------------------------------------------
    //! @brief      new演算子を利用した確保処理を行います.
    //! 
    //! @param[in]      args        可変テンプレート引数.
    //! @return     メモリを返却します.
    //-------------------------------------------------------------------------
    template<typename T, class... Args>
    T* New(Args&&... args)
    {
        assert(sizeof(T) <= (MaxSize - m_Size));
        auto buf = Alloc(sizeof(T), alignof(T));
        if (buf == nullptr)
            return nullptr;

        return new(buf) T(std::forward<Args>(args)...);
    }

    //-------------------------------------------------------------------------
    //! @brief      確保サイズを取得します.
    //! 
    //! @return     確保サイズを返却します.
    //-------------------------------------------------------------------------
    size_t GetSize() const
    { return m_Size; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    uint8_t  m_Buffer[MaxSize] = {};    //!< バッファメモリ.
    size_t   m_Size            = 0;     //!< 確保サイズ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespcae asdx
