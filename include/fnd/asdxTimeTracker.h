#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <fnd/asdxMath.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// TimeTracker class
///////////////////////////////////////////////////////////////////////////////
class TimeTracker
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    TimeTracker() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~TimeTracker() = default;

    //-------------------------------------------------------------------------
    //! @brief      リセット処理を行います.
    //-------------------------------------------------------------------------
    void Reset()
    {
        m_ElapsedSec  = 0.0f;
        m_DurationSec = 0.0f;
        m_Speed       = 1.0f;
    }

    //-------------------------------------------------------------------------
    //! @brief      所要時間を設定します.
    //! 
    //! @param[in]      sec     所要時間(単位：秒).
    //-------------------------------------------------------------------------
    void SetDuration(float sec)
    {
        m_ElapsedSec  = 0.0f;
        m_DurationSec = sec;
    }

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを設定します.
    //! 
    //! @param[in]      value   再生スピード.
    //-------------------------------------------------------------------------
    void SetSpeed(float value)
    { m_Speed = value; }

    //-------------------------------------------------------------------------
    //! @brief      経過時間を取得します.
    //!
    //! @return     経過時間を返却します.
    //-------------------------------------------------------------------------
    float GetElapsedSec() const
    { return m_ElapsedSec; }

    //-------------------------------------------------------------------------
    //! @brief      所要時間を取得します.
    //! 
    //! @return     所要時間を返却します.
    //--------------------------------------------------------------------------
    float GetDurationSec() const
    { return m_DurationSec; }

    //-------------------------------------------------------------------------
    //! @brief      再生速度を取得します.
    //!
    //! @return     再生速度を返却します.
    //-------------------------------------------------------------------------
    float GetSpeed() const
    { return m_Speed; }

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec   差分時間(単位：秒).
    //--------------------------------------------------------------------------
    void Update(float deltaSec)
    {
        if (m_DurationSec <= 0.0f)
            return;

        m_ElapsedSec += deltaSec * m_Speed;
        if (m_ElapsedSec > m_DurationSec)
            m_ElapsedSec = m_DurationSec;
    }

    //-------------------------------------------------------------------------
    //! @brief      完了したかどうかチェックします.
    //! 
    //! @retval true    完了済み.
    //! @retval false   未完了.
    //-------------------------------------------------------------------------
    bool IsComplete() const
    {
        if (m_DurationSec <= 0.0f)
            return false;

        return m_ElapsedSec >= m_DurationSec;
    }

    //-------------------------------------------------------------------------
    //! @brief      相対値を取得します.
    //! 
    //! @return     相対値を[0, 1]で返却します.
    //-------------------------------------------------------------------------
    float GetValue() const
    {
        if (m_DurationSec <= 0.0f)
            return 0.0f;

        return Saturate(m_ElapsedSec / m_DurationSec);
    }

    //-------------------------------------------------------------------------
    //! @brief      経過時間をリセットします.
    //-------------------------------------------------------------------------
    void Cue()
    { m_ElapsedSec = 0.0f; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    float   m_ElapsedSec    = 0.0f;     //!< 経過時間.
    float   m_DurationSec   = 0.0f;     //!< 所要時間.
    float   m_Speed         = 1.0f;     //!< 再生速度.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
