///////////////////////////////////////////////////////////////////////////////
// RefPtr class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class RefPtr
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    template<typename U> friend class RefPtr;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    RefPtr() noexcept
    : m_pPtr(nullptr)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    explicit RefPtr(std::nullptr_t) noexcept
    : m_pPtr(nullptr)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    explicit RefPtr(T* pInterface) noexcept
    : m_pPtr(pInterface)
    { AddRef(); }

    //-------------------------------------------------------------------------
    //! @brief      コピーコンストラクタです.
    //-------------------------------------------------------------------------
    RefPtr(const RefPtr& value) noexcept
    : m_pPtr( value.m_pPtr )
    { AddRef(); }

    //-------------------------------------------------------------------------
    //! @brief      ムーブコンストラクタです.
    //-------------------------------------------------------------------------
    RefPtr(RefPtr&& value) noexcept
    : m_pPtr( nullptr )
    {
        if ( this != reinterpret_cast<RefPtr*>(&reinterpret_cast<uint8_t&>(value)) )
        { Swap(value); }
    }

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    template<typename U>
    explicit RefPtr(U* value) noexcept
    : m_pPtr( value )
    { AddRef(); }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~RefPtr() noexcept
    { Release(); }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    RefPtr& operator = (T* value) noexcept
    {
        if ( m_pPtr != value )
        { RefPtr(value).Swap(*this); }
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    RefPtr& operator = (const RefPtr& value) noexcept
    {
        if ( m_pPtr != value.m_pPtr )
        { RefPtr(value).Swap(*this); }
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      ムーブ代入演算子です.
    //-------------------------------------------------------------------------
    RefPtr& operator = (RefPtr&& value) noexcept
    {
        RefPtr(static_cast<RefPtr&&>(value)).Swap(*this);
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    template<typename U>
    RefPtr& operator = (U* value) noexcept
    {
        RefPtr(value).Swap(*this);
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    template<typename U>
    RefPtr& operator = (const RefPtr<U>& value) noexcept
    {
        RefPtr(value).Swap(*this);
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      ムーブ代入演算子です.
    //-------------------------------------------------------------------------
    template<typename U>
    RefPtr& operator = (RefPtr<U>&& value) noexcept
    {
        RefPtr(static_cast<RefPtr&&>(value)).Swap(*this);
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    RefPtr& operator = (std::nullptr_t) noexcept
    {
        Release();
        return (*this);
    }

    //-------------------------------------------------------------------------
    //! @brief      アタッチします.
    //-------------------------------------------------------------------------
    void Attach(T* value) noexcept
    {
        if ( m_pPtr != nullptr )
        { m_pPtr->Release(); }
        m_pPtr = value;
    }

    //-------------------------------------------------------------------------
    //! @brief      デタッチします.
    //-------------------------------------------------------------------------
    T* Detach() noexcept
    {
        T* ptr = m_pPtr;
        m_pPtr = nullptr;
        return ptr;
    }

    //-------------------------------------------------------------------------
    //! @brief      値を入れ替えます.
    //-------------------------------------------------------------------------
    void Swap(RefPtr& value) noexcept
    {
        T* temp = m_pPtr;
        m_pPtr  = value.m_pPtr;
        value.m_pPtr = temp;
    }

    //-------------------------------------------------------------------------
    //! @brief      値を入れ替えます.
    //-------------------------------------------------------------------------
    void Swap(RefPtr&& value) noexcept
    {
        T* temp = m_pPtr;
        m_pPtr  = value.m_pPtr;
        value.m_pPtr = temp;
    }

    //-------------------------------------------------------------------------
    //! @brief      ポインタを取得します.
    //-------------------------------------------------------------------------
    T* GetPtr() const noexcept
    { return m_pPtr; }

    //-------------------------------------------------------------------------
    //! @brief      アドレスを取得します.
    //-------------------------------------------------------------------------
    T* const* GetAddress() const noexcept
    { return &m_pPtr; }

    //-------------------------------------------------------------------------
    //! @brief      アドレスを取得します.
    //-------------------------------------------------------------------------
    T** GetAddress() noexcept
    { return &m_pPtr; }

    //-------------------------------------------------------------------------
    //! @brief      参照カウントを減らしてからアドレスを取得します.
    //-------------------------------------------------------------------------
    T** ReleaseAndGetAddress() noexcept
    {
        Release();
        return &m_pPtr;
    }

    //-------------------------------------------------------------------------
    //! @brief      リセットします.
    //-------------------------------------------------------------------------
    void Reset() noexcept
    { Release(); }

    //-------------------------------------------------------------------------
    //! @brief      指定された値にコピーを行います.
    //-------------------------------------------------------------------------
    void CopyTo(T** ptr) noexcept
    {
        AddRef();
        (*ptr) = m_pPtr;
    }

    //-------------------------------------------------------------------------
    //! @brief      アロー演算子です.
    //-------------------------------------------------------------------------
    T* operator -> () const noexcept
    { return m_pPtr; }

    //-------------------------------------------------------------------------
    //! @brief      bool型へのキャストです.
    //-------------------------------------------------------------------------
    operator bool () const noexcept
    { return m_pPtr != nullptr; }

protected:
    //=========================================================================
    // protected variables.
    //=========================================================================
    T*  m_pPtr;     //!< 参照カウントインタフェースを実装するオブジェクトのポインタです.

    //=========================================================================
    // protected methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      参照カウントを増やします.
    //-------------------------------------------------------------------------
    void AddRef()
    {
        if ( m_pPtr != nullptr )
        { m_pPtr->AddRef(); }
    }

    //-------------------------------------------------------------------------
    //! @brief      参照カウントを減らします.
    //-------------------------------------------------------------------------
    void Release()
    {
        T* ptr = m_pPtr;
        if ( ptr != nullptr )
        {
            m_pPtr = nullptr;
            ptr->Release();
        }
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

template<typename T> inline
bool operator == ( const RefPtr<T>& value, const T* ptr )
{ return ( value.GetPtr() == ptr ); }

template<typename T> inline
bool operator == ( const T* ptr, const RefPtr<T>& value )
{ return ( value.GetPtr() == ptr ); }

template<typename T> inline
bool operator == ( const RefPtr<T>& a, const RefPtr<T>& b )
{ return a.GetPtr() == b.GetPtr(); }

template<typename T, typename U> inline
bool operator == ( const RefPtr<T>& a, const RefPtr<U>& b )
{ return a.GetPtr() == b.GetPtr(); }

template<typename T> inline
bool operator != ( const RefPtr<T>& value, const T* ptr )
{ return ( value.GetPtr() != ptr ); }

template<typename T> inline
bool operator != ( const T* ptr, const RefPtr<T>& value )
{ return ( value.GetPtr() != ptr ); }

template<typename T> inline
bool operator != ( const RefPtr<T>& a, const RefPtr<T>& b )
{ return a.GetPtr() != b.GetPtr(); }

template<typename T, typename U> inline
bool operator != ( const RefPtr<T>& a, const RefPtr<U>& b )
{ return a.GetPtr() != b.GetPtr(); }

template<typename T> inline
bool operator == ( const RefPtr<T>& value, std::nullptr_t )
{ return ( value.GetPtr() == nullptr ); }

template<typename T> inline
bool operator == ( std::nullptr_t, const RefPtr<T>& value )
{ return ( value.GetPtr() == nullptr ); }

template<typename T> inline
bool operator != ( const RefPtr<T>& value, std::nullptr_t )
{ return ( value.GetPtr() != nullptr ); }

template<typename T> inline
bool operator != ( std::nullptr_t, const RefPtr<T>& value )
{ return ( value.GetPtr() != nullptr ); }


///////////////////////////////////////////////////////////////////////////////
// WeakRefPtr class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class WeakRefPtr
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    WeakRefPtr() noexcept
    : m_pWeak(nullptr)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    explicit WeakRefPtr(IWeakReference* pWeak) noexcept
    : m_pWeak(pWeak)
    { AddRef(); }

    //-------------------------------------------------------------------------
    //! @brief      コピーコンストラクタです.
    //-------------------------------------------------------------------------
    WeakRefPtr(const WeakRefPtr& value) noexcept
    : m_pWeak(value.m_pWeak)
    { AddRef(); }

    //-------------------------------------------------------------------------
    //! @brief      ムーブコンストラクタです.
    //-------------------------------------------------------------------------
    WeakRefPtr(WeakRefPtr&& value) noexcept
    : m_pWeak(nullptr)
    { Swap(value); }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~WeakRefPtr() noexcept
    { Release(); }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    WeakRefPtr& operator = (const WeakRefPtr& value) noexcept
    {
        if (this != &value)
        {
            WeakRefPtr tmp(value);
            Swap(tmp);
        }
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      ムーブ代入演算子です.
    //-------------------------------------------------------------------------
    WeakRefPtr& operator = (WeakRefPtr&& value) noexcept
    {
        if (this != &value)
        {
            Release();
            Swap(value);
        }
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      監視対象の RefPtr オブジェクトを取得します.
    //-------------------------------------------------------------------------
    bool Resolve(RefPtr<T>& out) const noexcept
    {
        if (!m_pWeak)
            return false;

        IReference* pRef = nullptr;
        if (!m_pWeak->Resolve(&pRef))
            return false;

        out = RefPtr<T>(static_cast<T*>(pRef));
        return true;
    }

    //-------------------------------------------------------------------------
    //! @brief      値を入れ替えます.
    //-------------------------------------------------------------------------
    void Swap(WeakRefPtr& other) noexcept
    {
        IWeakReference* tmp = m_pWeak;
        m_pWeak = other.m_pWeak;
        other.m_pWeak = tmp;
    }

    //-------------------------------------------------------------------------
    //! @brief      値を入れ替えます.
    //-------------------------------------------------------------------------
    void Swap(WeakRefPtr&& other) noexcept
    {
        IWeakReference* tmp = m_pWeak;
        m_pWeak = other.m_pWeak;
        other.m_pWeak = tmp;
    }

    //-------------------------------------------------------------------------
    //! @brief      参照カウントを上げます.
    //-------------------------------------------------------------------------
    void AddRef()
    {
        if (m_pWeak)
            m_pWeak->AddRef();
    }

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //-------------------------------------------------------------------------
    void Release()
    {
        if (m_pWeak)
        {
            IWeakReference* tmp = m_pWeak;
            m_pWeak = nullptr;
            tmp->Release();
        }
    }

    //-------------------------------------------------------------------------
    //! @brief      リセット処理を行います.
    //-------------------------------------------------------------------------
    void Reset()
    { Release(); }

    //-------------------------------------------------------------------------
    //! @brief      監視している RefPtr オブジェクトを取得します.
    //-------------------------------------------------------------------------
    RefPtr<T> Lock() const noexcept
    {
        if (!m_pWeak)
            return nullptr;

        IReference* pStrong = nullptr;
        if (m_pWeak->Resolve(&pStrong))
            return RefPtr<T>(static_cast<T*>(pStrong));

        return nullptr;
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    IWeakReference* m_pWeak;    //!< 弱参照カウンタ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

//-----------------------------------------------------------------------------
//! @brief      弱参照ポインタを取得します.
//-----------------------------------------------------------------------------
template<typename T>
inline WeakRefPtr<T> GetWeakPtr(T* ptr)
{
    WeakRefPtr<T> result;
    if (ptr == nullptr)
        return result;

    IWeakReference* weakRef = nullptr;
    ptr->GetWeakReference(&weakRef);
    result = WeakRefPtr<T>(weakRef);
    weakRef->AddRef();  // resultがAddRef()しているので解放する.
    return result;
}

