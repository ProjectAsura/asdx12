namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// BasicString class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class BasicString
{
    // std::string は 40 bytes 使用するので、消費メモリを抑えたい場合に使用します.
    // 文字列操作は基本的に出来ないので、動的文字列を保持する役割としてのみ使用してください.

    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    BasicString() = default;

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    BasicString(const T* value)
    { assign(value, count(value)); }

    //-------------------------------------------------------------------------
    //! @brief      コピーコンストラクタです.
    //-------------------------------------------------------------------------
    BasicString(const BasicString& value)
    { assign(value.c_str(), value.size()); }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~BasicString()
    { clear(); }

    //-------------------------------------------------------------------------
    //! @brief      メモリを解放します.
    //-------------------------------------------------------------------------
    void clear()
    {
        if (m_Ptr != nullptr)
        {
            delete[] m_Ptr;
            m_Ptr = nullptr;
        }
        m_Size = 0;
    }

    //-------------------------------------------------------------------------
    //! @brief      文字列を取得します.
    //-------------------------------------------------------------------------
    const T* c_str() const
    { return m_Ptr; }

    //-------------------------------------------------------------------------
    //! @brief      文字数を取得します.
    //-------------------------------------------------------------------------
    size_t size() const
    { return m_Size; }

    //-------------------------------------------------------------------------
    //! @brief      空かどうかチェックします.
    //-------------------------------------------------------------------------
    bool empty() const
    { return m_Ptr == nullptr; }

    //-------------------------------------------------------------------------
    //! @brief      等価比較演算子です.
    //-------------------------------------------------------------------------
    bool operator == (const BasicString& value) const
    { return compare(c_str(), value.c_str()) == 0; }

    //-------------------------------------------------------------------------
    //! @brief      非等価比較演算子です.
    //-------------------------------------------------------------------------
    bool operator != (const BasicString& value) const
    { return compare(c_str(), value.c_str()) != 0; }

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //-------------------------------------------------------------------------
    BasicString& operator = (const BasicString& value)
    {
        assign(value.c_str(), value.size());
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      ムーブ代入演算子です.
    //-------------------------------------------------------------------------
    BasicString& operator = (BasicString&& value)
    {
        swap(value);
        return *this;
    }

    //-------------------------------------------------------------------------
    //! @brief      nullptr あるいは 空文字かどうかをチェックします.
    //-------------------------------------------------------------------------
    bool is_null_or_empty() const
    {
        if (m_Ptr == nullptr)
            return true;

        return (m_Ptr[0] == T{});
    }

    //-------------------------------------------------------------------------
    //! @brief      文字列を割り当てます.
    //-------------------------------------------------------------------------
    void assign(const T* value, size_t size)
    {
        clear();

        m_Size = size;
        m_Ptr  = new T[m_Size + 1];
        for(size_t i=0; i<size; ++i)
        { m_Ptr[i] = value[i]; }
        m_Ptr[m_Size] = T{};
    }

    //-------------------------------------------------------------------------
    //! @brief      入れ替えます.
    //-------------------------------------------------------------------------
    void swap(BasicString& value)
    {
        auto ptr  = m_Ptr;
        auto size = m_Size;
        m_Ptr  = value.m_Ptr;
        m_Size = value.m_Size;
        value.m_Ptr  = ptr;
        value.m_Size = size;
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    T*      m_Ptr  = nullptr;
    size_t  m_Size = 0;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      比較処理を行います.
    //-------------------------------------------------------------------------
    static int compare(const T* lhs, const T* rhs)
    {
        while(*lhs && *rhs)
        {
            if (*lhs < *rhs) return -1;
            if (*lhs > *rhs) return 1;
            ++lhs;
            ++rhs;
        }

        if (*lhs) return 1;
        if (*rhs) return -1;
        return 0;
    }

    //-------------------------------------------------------------------------
    //! @brief      文字数を数え上げます.
    //-------------------------------------------------------------------------
    static size_t count(const T* value)
    {
        const T* p = value;
        const auto empty = T{};
        while(*p != empty){ ++p; }
        return static_cast<size_t>(p - value);
    }
};

using String    = BasicString<char>;
using WString   = BasicString<wchar_t>;
using U8String  = BasicString<char8_t>;
using U16String = BasicString<char16_t>;
using U32String = BasicString<char32_t>;

} // namespace
