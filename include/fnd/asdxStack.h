#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cassert>
#include <fnd/asdxDummyTemplate.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Stack class
///////////////////////////////////////////////////////////////////////////////
template<typename T, typename R = DefaultTag>
class Stack
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Node class
    ///////////////////////////////////////////////////////////////////////////
    class Node : public DummyTemplate<R>
    {
        //=====================================================================
        // list of friend classes and methods.
        //=====================================================================
        friend class Stack<T, R>;

    public:
        //=====================================================================
        // public variables.
        //=====================================================================
        /* NOTHING */

        //---------------------------------------------------------------------
        //! @brief      コンストラクタです.
        //---------------------------------------------------------------------
        Node()
        : m_Next(nullptr)
        , m_Prev(nullptr)
        { /* DO_NOTHING */ }

        //---------------------------------------------------------------------
        //! @brief      デストラクタです.
        //---------------------------------------------------------------------
        virtual ~Node()
        {
            auto prev = m_Prev;
            auto next = m_Next;

            if (prev != nullptr)
            { prev->Stack::Node::m_Next = next; }

            if (next != nullptr)
            { next->Stack::Node::m_Prev = prev; }

            m_Prev = nullptr;
            m_Next = nullptr;
        }

    private:
        //=====================================================================
        // private variables.
        //=====================================================================
        T*  m_Next = nullptr;   //!< 次のノードです.
        T*  m_Prev = nullptr;   //!< 前のノードです.

        //---------------------------------------------------------------------
        //! @brief      リンクを設定します.
        //---------------------------------------------------------------------
        static void Link(T* lhs, T* rhs)
        {
            if (lhs == nullptr || rhs == nullptr)
            { return; }

            lhs->Stack::Node::m_Next = rhs;
            rhs->Stack::Node::m_Prev = lhs;
        }

        //---------------------------------------------------------------------
        //! @brief      リンクを解除します.
        //---------------------------------------------------------------------
        static void Unlink(T* node)
        {
            if (node == nullptr)
            { return; }

            auto prev = node->Stack::Node::m_Prev;
            auto next = node->Stack::Node::m_Next;

            if (prev != nullptr)
            { prev->Stack::Node::m_Next = next; }

            if (next != nullptr)
            { next->Stack::Node::m_Prev = prev; }

            node->Stack::Node::m_Prev = nullptr;
            node->Stack::Node::m_Next = nullptr;
        }
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Stack()
    : m_Head(nullptr)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Stack()
    { clear(); }

    //-------------------------------------------------------------------------
    //! @brief      ノードを追加します.
    //-------------------------------------------------------------------------
    void push(T* node)
    {
        if (node == nullptr)
        { return; }

        // 継承チェック.
        assert(static_cast<Stack<T>::Node*>(node) != nullptr);

        if (m_Head == nullptr)
        {
            m_Head = node;
        }
        else
        {
            Stack::Node::Link(m_Head, node);
            m_Head = node;
        }
        m_Count++;
    }

    //-------------------------------------------------------------------------
    //! @brief      ノードを取り出します.
    //-------------------------------------------------------------------------
    T* pop()
    {
        if (m_Head == nullptr)
        { return nullptr; }

        auto head = m_Head;
        auto prev = m_Head->Stack::Node::m_Prev;
        Stack::Node::Unlink(head);
        m_Head = prev;
        m_Count--;

        return head;
    }

    //-------------------------------------------------------------------------
    //! @brief      クリアします.
    //-------------------------------------------------------------------------
    void clear()
    {
        auto itr = m_Head;
        while(itr != nullptr)
        {
            auto node = itr;
            itr = itr->Stack::Node::m_Prev;
            Stack::Node::Unlink(node);
        }

        m_Count = 0;
        m_Head  = nullptr;
    }

    //-------------------------------------------------------------------------
    //! @brief      空かどうかチェックします.
    //-------------------------------------------------------------------------
    bool empty() const
    { return m_Count == 0; }

    //-------------------------------------------------------------------------
    //! @brief      格納されている要素数を取得します.
    //-------------------------------------------------------------------------
    size_t size() const
    { return m_Count; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    T*     m_Head  = nullptr;   //!< スタック先頭ポインタ.
    size_t m_Count = 0;         //!< 格納数.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
