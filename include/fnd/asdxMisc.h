//-----------------------------------------------------------------------------
//! @brief      指定された値で切り上げを考慮した除算を行います.
//! 
//! @param[in]      val     数値
//! @param[in]      div     割る数.
//! @return     val を div で除算して切り上げた結果を返却します.
//-----------------------------------------------------------------------------
inline
uint32_t RoundDiv(uint32_t val, uint32_t div)
{ return (val + (div - 1)) / div; }

//-----------------------------------------------------------------------------
//! @brief      指定された値で切り上げを考慮した除算を行います.
//! 
//! @param[in]      val     数値
//! @param[in]      div     割る数.
