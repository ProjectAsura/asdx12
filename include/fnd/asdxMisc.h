//-----------------------------------------------------------------------------
//! @brief      2のべき乗かどうかをチェックします.
//! 
//! @param[in]      val     チェックする値.
//! @retval true    2のべき乗です.
//! @retval false   2のべき乗ではありません.
//-----------------------------------------------------------------------------
template<typename T>
inline bool IsPowerOf2(T val)
{ return ((val != 0) && !(val & (val - 1))); }

