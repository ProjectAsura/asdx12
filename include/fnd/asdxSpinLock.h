#include <cassert>
#include <cstdint>
#include <atomic>
#include <thread>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// SpinLock class
///////////////////////////////////////////////////////////////////////////////
class SpinLock
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      ロックします.
    //-------------------------------------------------------------------------
    void lock()
    {
        uint32_t old = 0;
        while(!m_State.compare_exchange_weak(old, 1u, std::memory_order_acquire))
        {
            old = 0; // 失敗したら戻しておく.
            _mm_pause();
        }
    }

    //-------------------------------------------------------------------------
    //! @brief      ロックを解除します.
    //-------------------------------------------------------------------------
    void unlock()
    { m_State.store(0, std::memory_order_release); }

    //-------------------------------------------------------------------------
    //! @brief      ロックを試みます.
    //! 
    //! @retval true    ロックに成功.
    //! @retval false   ロックに失敗.
    //-------------------------------------------------------------------------
    bool try_lock()
    {
        uint32_t old = 0;
        return m_State.compare_exchange_weak(old, 1u);
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::atomic<uint32_t>   m_State = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// RecursiveSpinLock class
///////////////////////////////////////////////////////////////////////////////
class RecursiveSpinLock
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      ロックします.
    //-------------------------------------------------------------------------
    void lock()
    {
        std::hash<std::thread::id> hasher;
        auto hashId = hasher(std::this_thread::get_id());

        while(!acquire(hashId))
        { _mm_pause(); }

        assert(m_Counter + 1 <= UINT64_MAX);
        m_Counter++;
    }

    //-------------------------------------------------------------------------
    //! @brief      ロックを解除します.
    //-------------------------------------------------------------------------
    void unlock()
    {
        std::hash<std::thread::id> hasher;
        auto hashId = hasher(std::this_thread::get_id());
        assert(m_Owner == hashId);

        // 再起カウントを減らす.
        m_Counter--;

        // ゼロになったらロック解除.
        if (m_Counter == 0)
        {
            size_t defaultId = 0;
            m_Owner.store(defaultId, std::memory_order_relaxed);
            m_State.store(0, std::memory_order_release);
        }
    }

    //-------------------------------------------------------------------------
    //! @brief      ロックを試みます.
    //! 
    //! @retval true    ロックに成功.
    //! @retval false   ロックに失敗.
    //-------------------------------------------------------------------------
    bool try_lock()
    {
        std::hash<std::thread::id> hasher;
        auto hashId = hasher(std::this_thread::get_id());

        // 先にロック済みなら，所有者と同じスレッドじゃないとロックできない.
        auto lockHashId = m_Owner.load();
        if (lockHashId > 0 && m_Counter > 0 && hashId != lockHashId)
        {
            // ダメでした.
            return false;
        }

        if (acquire(hashId))
        {
            assert(m_Counter + 1 <= UINT64_MAX);
            m_Counter++;
            return true;    // ロックしたよ.
        }

        // ダメでした.
        return false;
    }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::atomic<uint32_t>   m_State   = {};
    std::atomic<size_t>     m_Owner   = {};
    uint64_t                m_Counter = 0;

    //-------------------------------------------------------------------------
    //! @brief      ロックを取得します.
    //-------------------------------------------------------------------------
    bool acquire(size_t hashId)
    {
        // フラグ取得と設定.
        uint32_t old = 0;
        m_State.compare_exchange_weak(old, 1u, std::memory_order_acquire);

        // ロックが未取得なら所有者に設定.
        if (old == 0)
        {
            assert(m_Counter == 0); // 未設定のはず.
            m_Owner.store(hashId, std::memory_order_relaxed);
            return true;    // ロックしたよ.
        }

        // ロックが取得済みで，同一スレッドなら再起カウントをあげて終了.
        if (old == 1u && m_Owner.load(std::memory_order_relaxed) == hashId)
        {
            assert(m_Counter > 0);
            return true;    // ロックしたよ.
        }

        // ダメでした.
        return false;
    }
};

///////////////////////////////////////////////////////////////////////////////
// ScopedLock class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class ScopedLock
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    explicit ScopedLock(T& value)
    : m_LockObject(value)
    { m_LockObject.lock(); }

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ScopedLock()
    { m_LockObject.unlock(); }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    T&   m_LockObject;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
