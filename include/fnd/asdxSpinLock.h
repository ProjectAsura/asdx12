///////////////////////////////////////////////////////////////////////////////
// RwSpinLock class
///////////////////////////////////////////////////////////////////////////////
template<typename T>
class RwSpinLock
{
    // 状態値の下位16ビットでリーダー数を，上位側のビットでライターの待機数と活動状態を管理します.
    // リーダーは同時に取得できますが，ライター取得中または待機中は新しいリーダーを受け付けません.

    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //========================================================================= 
    // public methods.
    //========================================================================= 

    //-------------------------------------------------------------------------
    //! @brief      デフォルトコンストラクタです.
    //-------------------------------------------------------------------------
    RwSpinLock() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~RwSpinLock() = default;

    //-------------------------------------------------------------------------
    //! @brief      リーダーロックを取得します.
    //!
    //! ライターが活動中または待機中の場合，あるいはリーダー数が上限に達した場合は，
    //! 別のスレッドが状態を変更するまでスピン待機します.
    //-------------------------------------------------------------------------
    void read_lock()
    {
        for(;;)
        {
            auto state = m_State.load(std::memory_order_acquire);

            // ライターを優先するため，活動中・待機中はリーダーを追加しない.
            if (state & (kWriterActive | kWriterMask))
            {
                _mm_pause();
                continue;
            }

            // リーダー数は下位ビットに格納されるため，オーバーフローを防ぐ.
            if ((m_State & kReaderMask) == kReaderMask)
            {
                _mm_pause();
                continue;
            }

            // 他のスレッドと競合しなければ，リーダー数を1つ増やして取得する.
            if (m_State.compare_exchange_weak(
                state,
                state + 1,
                std::memory_order_acquire,
                std::memory_order_relaxed))
            { return; }

            _mm_pause();
        }
    }

    //-------------------------------------------------------------------------
    //! @brief      リーダーロックを解除します.
    //-------------------------------------------------------------------------
    void read_unlock()
    { m_State.fetch_sub(1, std::memory_order_release); }

    //-------------------------------------------------------------------------
    //! @brief      リーダーロックを試みます.
    //!
    //! @retval true    ロックに成功.
    //! @retval false   ロックに失敗.
    //! @note 待機せず，ライターが活動中または待機中でなく，リーダー数にも空きがある場合だけロックを取得します.
    //-------------------------------------------------------------------------
    bool try_read_lock()
    {
        auto state = m_State.load(std::memory_order_acquire);

        if ((state & (kWriterActive | kWriterMask)) != 0)
            return false;

        if ((state & kReaderMask) == kReaderMask)
            return false;

        auto desired = state + 1;
        return m_State.compare_exchange_strong(
            state,
            desired,
            std::memory_order_acquire,
            std::memory_order_relaxed);
    }

    //-------------------------------------------------------------------------
    //! @brief      ライターロックを取得します.
    //-------------------------------------------------------------------------
    void write_lock()
    {
        for(;;)
        {
            auto state = m_State.load(std::memory_order_relaxed);

            // ライター待機数が上限の場合は予約できるまで待機する.
            if ((state & kWriterMask) == kWriterMask)
            {
                _mm_pause();
                continue;
            }

            // ライター待機数を予約する. 予約により新規リーダーを停止させる.
            auto desired = state + kWriterOne;
            if (m_State.compare_exchange_weak(
                state,
                desired,
                std::memory_order_acquire,
                std::memory_order_relaxed))
            { break; }

            _mm_pause();
        }

        // リーダーが全員退出し，現在のライターがいなくなるまで待機する.
        for(;;)
        {
            auto state = m_State.load(std::memory_order_acquire);

            if ((state & kReaderMask) == 0 && (state & kWriterActive) == 0)
            {
                // 予約した待機数を1つ減らし，自分を活動中のライターにする.
                auto desired = (state - kWriterOne) | kWriterActive;

                if (m_State.compare_exchange_weak(
                    state,
                    desired,
                    std::memory_order_acquire,
                    std::memory_order_relaxed))
                { return; }
            }

            _mm_pause();
        }
    }

    //-------------------------------------------------------------------------
    //! @brief      ライターロックを試みます.
    //!
    //! @retval true    ロックに成功.
    //! @retval false   ロックに失敗.
    //! @note 待機せず，リーダーもライター待機者も存在しない場合だけロックを取得します.
    //-------------------------------------------------------------------------
    bool try_write_lock()
    {
        auto state = m_State.load(std::memory_order_acquire);

        if (state != 0)
            return false;

        return m_State.compare_exchange_strong(
            state,
            kWriterActive,
            std::memory_order_acquire,
            std::memory_order_relaxed);
    }

    //-------------------------------------------------------------------------
    //! @brief      ライターロックを解除します.
    //-------------------------------------------------------------------------
    void write_unlock()
    { m_State.fetch_and(~kWriterActive, std::memory_order_release); }

    // ラッパー関数.
    void lock           () { write_lock  (); }
    void unlock         () { write_unlock(); }
    void lock_shared    () { read_lock   (); }
    void unlock_shared  () { read_unlock (); }
    bool try_lock       () { return try_write_lock(); }
    bool try_lock_shared() { return try_read_lock (); }

private:
    //========================================================================= 
    // private variables.
    //========================================================================= 
    static constexpr uint32_t kReaderMask   = 0x0000FFFFu;  //!< リーダー数のマスク.
    static constexpr uint32_t kWriterMask   = 0x7FFF0000u;  //!< ライター待機数のマスク.
    static constexpr uint32_t kWriterActive = 0x80000000u;  //!< ライター活動状態のマスク.
    static constexpr uint32_t kWriterOne    = 0x00010000u;  //!< ライター待機数1のマスク.

    std::atomic<uint32_t> m_State = {}; //!< 状態値.

    //=========================================================================
    // private variables.
    //=========================================================================
    RwSpinLock           (const RwSpinLock&) = delete;  // アクセス禁止.
    RwSpinLock& operator=(const RwSpinLock&) = delete;  // アクセス禁止.
};

