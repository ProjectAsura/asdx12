#include <fnd/asdxMath.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// DragTracker class
///////////////////////////////////////////////////////////////////////////////
class DragTracker
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    DragTracker() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~DragTracker() = default;

    //-------------------------------------------------------------------------
    //! @brief      マウスドラッグ中か判定します.
    //! 
    //! @param[in]      x       マウスカーソルX座標.
    //! @param[in]      y       マウスカーソルY座標.
    //! @param[in]      isDown  ボタン押下してたら true.
    //! @retval true    ドラッグ状態です.
    //! @retval false   非ドラッグ状態です.
    //-------------------------------------------------------------------------
    inline bool IsDrag(int x, int y, bool isDown)
    {
        bool drag = m_IsDown && isDown;

        // ボタン押下開始時に記録.
        if (!m_IsDown && isDown)
            m_Curr = m_Prev = asdx::Vector2(float(x), float(y));

        // ドラッグ中のみカレントを更新.
        if (drag)
        {
            m_Prev = m_Curr;
            m_Curr = asdx::Vector2(float(x), float(y));
        }

        // ボタンが離されたらリセット.
        if (m_IsDown && !isDown)
            m_Curr = m_Prev = asdx::Vector2(0.0f, 0.0f);

        // ステート更新.
        m_IsDown = isDown;

        return drag;
    }

    //-------------------------------------------------------------------------
    //! @brief      差分量を取得します.
    //! 
    //! @return     ドラッグによる差分量を返却します.
    //-------------------------------------------------------------------------
    inline Vector2 GetDiff() const
    { return m_Curr - m_Prev; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    bool    m_IsDown = false;
    Vector2 m_Curr   = {};
    Vector2 m_Prev   = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
