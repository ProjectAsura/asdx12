#include <cstdint>
#include <vector>
#include <fnd/asdxArrayView.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// TEXTURE_DIMENSION enum
///////////////////////////////////////////////////////////////////////////////
enum TEXTURE_DIMENSION
{
    TEXTURE_DIMENSION_UNKNOWN,  //!< 未知の次元(エラー用).
    TEXTURE_DIMENSION_1D,       //!< 1次元.
    TEXTURE_DIMENSION_2D,       //!< 2次元.
    TEXTURE_DIMENSION_3D,       //!< 3次元.
    TEXTURE_DIMENSION_CUBE      //!< キューブマップ.
};

///////////////////////////////////////////////////////////////////////////////
// ResSubResource structure
///////////////////////////////////////////////////////////////////////////////
struct ResSubResource
{
    uint32_t        Width       = 0;            //!< 横幅.
    uint32_t        Height      = 0;            //!< 縦幅.
    uint64_t        RowPitch    = 0;            //!< 1行あたりのデータサイズ.
    uint64_t        SlicePitch  = 0;            //!< 1スライスあたりのデータサイズ.
    uint64_t        PixelOffset = 0;            //!< ピクセルオフセット.
};

///////////////////////////////////////////////////////////////////////////////
// ResTexture structure
///////////////////////////////////////////////////////////////////////////////
struct ResTexture
{
    TEXTURE_DIMENSION           Dimension;          //!< 次元です.
    uint32_t                    Width;              //!< 横幅.
    uint32_t                    Height;             //!< 縦幅
    uint16_t                    DepthOrArraySize;   //!< 奥行 または 配列数.
    uint32_t                    Format;             //!< フォーマット.
    uint16_t                    MipLevels;          //!< ミップレベル数.
    ArrayView<ResSubResource>   SubResources;       //!< サブリソース.
    ArrayView<uint8_t>          Pixels;             //!< ピクセルデータ.
};


///////////////////////////////////////////////////////////////////////////////
// TextureBinary structure
///////////////////////////////////////////////////////////////////////////////
class TextureBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    TextureBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~TextureBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      リソースを取得します.
    //!
    //! @return     リソースを返却します.
    //-------------------------------------------------------------------------
    ResTexture GetResource() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>    m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
