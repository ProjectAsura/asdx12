#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxStringView.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// AlphaMode enum
///////////////////////////////////////////////////////////////////////////////
enum AlphaMode : uint8_t
{
    Opaque, //!< 不透明.
    Mask,   //!< マスク.
    Blend,  //!< ブレンド.
};

///////////////////////////////////////////////////////////////////////////////
// CullMode enum
///////////////////////////////////////////////////////////////////////////////
enum CullMode : uint8_t
{
    Back,       //!< 背面カリング（前面表示).
    Front,      //!< 前面カリング (背面表示).
    None,       //!< カリングなし (両面描画).
};

///////////////////////////////////////////////////////////////////////////////
// ResMaterial structure
///////////////////////////////////////////////////////////////////////////////
struct ResMaterial
{
    StringView              Shader;     //!< シェーダ名.
    ArrayView<uint8_t>      Buffer;     //!< 定数バッファ.
    ArrayView<StringView>   Textures;   //!< テクスチャ.
    AlphaMode               AlphaMode;  //!< アルファモード.
    CullMode                CullMode;   //!< カリングモード.
};


///////////////////////////////////////////////////////////////////////////////
// MaterialBinary class
///////////////////////////////////////////////////////////////////////////////
class MaterialBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MaterialBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MaterialBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      マテリアルリソースを取得します.
    //! 
    //! @return     マテリアルリソースを返却します.
    //-------------------------------------------------------------------------
    ResMaterial GetResource() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>    m_Blob;
    std::vector<StringView> m_Textures;

    //=========================================================================
    // private method.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
