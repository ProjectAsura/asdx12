///////////////////////////////////////////////////////////////////////////////
// ModelBinary class
///////////////////////////////////////////////////////////////////////////////
class ModelBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリア数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号.
    //! @return     メッシュを返却します.
    //-------------------------------------------------------------------------
    const res::Mesh& GetMesh(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを取得します.
    //! 
    //! @return     ボーンを返却します.
    //-------------------------------------------------------------------------
    const res::Bone& GetBone(uint32_t boneIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル名を取得します.
    //! 
    //! @param[in]      materialIndex       マテリアル番号.
    //! @return     マテリアル名を返却します.
    //-------------------------------------------------------------------------
    const char* GetMaterial(uint32_t materialIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      バウンディングスフィアを取得します.
    //! 
    //! @return     バウンディングスフィアを返却します.
    //-------------------------------------------------------------------------
    BoundingSphere3 GetBoundingSphere() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを検索します.
    //! 
    //! @param[in]      name            ボーン名です.
    //! @param[out]     index           ボーンの格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindBone(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを検索します.
    //! 
    //! @param[in]      name            マテリアル名です.
    //! @param[out]     index           マテリアル番号の格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindMaterial(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを検索します.
    //! 
    //! @param[in]      name            メッシュ名です.
    //! @param[out]     index           メッシュ番号の格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindMesh(const char* name, uint32_t& index) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>    m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// MeshProxy class
///////////////////////////////////////////////////////////////////////////////
class MeshProxy
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      メッシュ名を取得します.
    //-------------------------------------------------------------------------
    static StringView GetName(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      マテリアルIDを取得します.
    //-------------------------------------------------------------------------
    static uint32_t GetMaterialId(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      位置座標配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Vector3> GetPositions(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      法線配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Vector3> GetNormals(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      接線配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Vector4> GetTangents(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      頂点カラー配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Unorm4> GetColors(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      テクスチャ座標配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Vector2> GetTexCoords(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      ボーンインデックス配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Uint4> GetBoneIndices(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      ボーンウェイト配列を取得します.
    //-------------------------------------------------------------------------
    static ArrayView<Vector4> GetBoneWeights(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      頂点インデックスを取得します.
    //-------------------------------------------------------------------------
    static ArrayView<uint32_t> GetVerexIndices(const res::Mesh& mesh);

    //-------------------------------------------------------------------------
    //! @brief      バウンディングスフィアを取得します.
    //-------------------------------------------------------------------------
    static BoundingSphere3 GetBounds(const res::Mesh& mesh);
};


