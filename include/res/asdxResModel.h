#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>
#include <fnd/asdxMath.h>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxStringView.h>
#include <res/asdxResBone.h>
#include <res/asdxResMesh.h>
#include <res/asdxResHashString.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResMeshInstance structure
///////////////////////////////////////////////////////////////////////////////
struct ResMeshInstance
{
    uint64_t    Hash;       //!< インスタンス名ハッシュ.
    Matrix4x3   Transform;  //!< 変換行列.
};

///////////////////////////////////////////////////////////////////////////////
// ResMeshBatch structure
///////////////////////////////////////////////////////////////////////////////
struct ResMeshBatch
{
    ArrayView<uint32_t>         Meshes;     //!< 描画に使用するメッシュ番号.
    ArrayView<ResMeshInstance>  Instances;  //!< インスタンス情報.
};

///////////////////////////////////////////////////////////////////////////////
// ResModel structure
///////////////////////////////////////////////////////////////////////////////
struct ResModel
{
    ArrayView<ResMesh>          Meshes;             //!< メッシュ情報.
    ArrayView<uint64_t>         Materials;          //!< マテリアル名ハッシュ.
    ArrayView<ResBone>          Bones;              //!< ボーン情報.
    ArrayView<ResMeshBatch>     Bathces;            //!< メッシュバッチ.
    ArrayView<ResHashString>    HashTable;          //!< 名前ハッシュテーブル.
};


///////////////////////////////////////////////////////////////////////////////
// ModelBinary class
///////////////////////////////////////////////////////////////////////////////
class ModelBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュリソースを取得します.
    //! 
    //! @param[in]      index       メッシュ番号.
    //! @return     メッシュリソースを返却します.
    //-------------------------------------------------------------------------
    ResMesh GetMesh(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリアル数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル名ハッシュを取得します.
    //! 
    //! @param[in]      index       マテリアル番号.
    //! @return     マテリアル名ハッシュを返却します.
    //-------------------------------------------------------------------------
    uint64_t GetMaterialHash(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンリソースを取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     ボーンリソースを返却します.
    //-------------------------------------------------------------------------
    ResBone GetBone(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュバッチ数を取得します.
    //! 
    //! @return     メッシュバッチ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshBatchCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュバッチリソースを取得します.
    //! 
    //! @param[in]      ind4ex      メッシュバッチ番号.
    //! @return     メッシュバッチリソースを返却します.
    //-------------------------------------------------------------------------
    ResMeshBatch GetMeshBatch(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      ハッシュテーブル数を取得します.
    //! 
    //! @return     ハッシュテーブル数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetHashStringCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ハッシュテーブルを取得します.
    //! 
    //! @param[in]      index       ハッシュテーブル番号.
    //! @return     ハッシュテーブルを返却します.
    //-------------------------------------------------------------------------
    ResHashString GetHashString(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      名前を検索します.
    //! 
    //! @param[in]      hash        名前のハッシュ.
    //! @return     名前を返却します. 
    //-------------------------------------------------------------------------
    StringView FindName(uint64_t hash) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>            m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx

