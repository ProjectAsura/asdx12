#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>
#include <fnd/asdxMath.h>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxStringView.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResMesh structure
///////////////////////////////////////////////////////////////////////////////
struct ResMesh
{
    StringView          Name;
    uint32_t            MaterialId;
    ArrayView<Vector3>  Positions;
    ArrayView<Vector3>  Normals;
    ArrayView<Vector4>  Tangents;
    ArrayView<Unorm4>   Colors;
    ArrayView<Vector2>  TexCoords;
    ArrayView<Uint4>    BoneIndices;
    ArrayView<Vector4>  BoneWeights;
    ArrayView<uint32_t> VertexIndices;
    BoundingSphere3     BoundingSphere;
};

///////////////////////////////////////////////////////////////////////////////
// ResBone structure
///////////////////////////////////////////////////////////////////////////////
struct ResBone
{
    StringView      Name;
    Matrix          OffsetMatrix;
};

///////////////////////////////////////////////////////////////////////////////
// ModelBinary class
///////////////////////////////////////////////////////////////////////////////
class ModelBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリア数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号.
    //! @return     メッシュを返却します.
    //-------------------------------------------------------------------------
    ResMesh GetMesh(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを取得します.
    //! 
    //! @return     ボーンを返却します.
    //-------------------------------------------------------------------------
    ResBone GetBone(uint32_t boneIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル名を取得します.
    //! 
    //! @param[in]      materialIndex       マテリアル番号.
    //! @return     マテリアル名を返却します.
    //-------------------------------------------------------------------------
    const char* GetMaterial(uint32_t materialIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      バウンディングスフィアを取得します.
    //! 
    //! @return     バウンディングスフィアを返却します.
    //-------------------------------------------------------------------------
    BoundingSphere3 GetBoundingSphere() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを検索します.
    //! 
    //! @param[in]      name            ボーン名です.
    //! @param[out]     bone            ボーンの格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindBone(const char* name, ResBone& bone) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>    m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx

