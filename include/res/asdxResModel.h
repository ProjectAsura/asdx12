#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <fnd/asdxMath.h>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxBlob.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ModelBinary class
///////////////////////////////////////////////////////////////////////////////
class ModelBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      バイナリをロードします.
    //! 
    //! @param[in]      path        ファイルパスです.
    //! @retval true    ロードに成功.
    //! @retval false   ロードに失敗.
    //-------------------------------------------------------------------------
    bool LoadA(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      バイナリをロードします.
    //! 
    //! @param[in]      path        ファイルパスです.
    //! @retval true    ロードに成功.
    //! @retval false   ロードに失敗.
    //-------------------------------------------------------------------------
    bool LoadW(const wchar_t* path);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      ルート変換行列を取得します.
    //! 
    //! @return     ルート変換行列を返却します.
    //-------------------------------------------------------------------------
    const Matrix* GetRootTransform() const;

    //-------------------------------------------------------------------------
    //! @brief      逆ルート変換行列を取得します.
    //! 
    //! @return     逆ルート変換行列を返却します.
    //-------------------------------------------------------------------------
    const Matrix* GetInverseRootTransform() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュ名を取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     メッシュ名を返却します.
    //-------------------------------------------------------------------------
    const char* GetMeshName(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル名を取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     マテリアル名を返却します.
    //-------------------------------------------------------------------------
    const char* GetMaterialName(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      位置座標を取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     位置座標を返却します.
    //------------------------------------------------------------------------
    ArrayView<Vector3> GetPositions(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      法線ベクトルを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     法線ベクトルを返却します.
    //-------------------------------------------------------------------------
    ArrayView<Vector3> GetNormals(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      接線ベクトルを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     接線ベクトルを返却します.
    //-------------------------------------------------------------------------
    ArrayView<Vector4> GetTangents(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャ座標を取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     テクスチャ座標を返却します.
    //-------------------------------------------------------------------------
    ArrayView<Vector2> GetTexCoords(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      頂点カラーを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     頂点カラーを返却します.
    //-------------------------------------------------------------------------
    ArrayView<Unorm4> GetColors(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンの重みを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     ボーンの重みを返却します.
    //-------------------------------------------------------------------------
    ArrayView<Vector4> GetBoneWeights(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン番号を取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     ボーン番号を返却します.
    //-------------------------------------------------------------------------
    ArrayView<Uint4> GetBoneIndices(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      頂点インデックスを取得します.
    //! 
    //! @param[in]      meshIndex       メッシュ番号です.
    //! @return     頂点インデックスを返却します.
    //-------------------------------------------------------------------------
    ArrayView<uint32_t> GetVertexIndices(uint32_t meshIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン名を取得します.
    //! 
    //! @param[in]      boneIndex       ボーン番号です.
    //! @return     ボーン名を返却します.
    //-------------------------------------------------------------------------
    const char* GetBoneName(uint32_t boneIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンオフセット行列を取得します.
    //! 
    //! @param[in]      boneIndex       ボーン番号です.
    //! @return     ボーンオフセット行列を返却します.
    //-------------------------------------------------------------------------
    const Matrix* GetBoneOffsetMatrix(uint32_t boneIndex) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    IBlob* m_pBlob = nullptr;     //!< バイナリデータです.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx

