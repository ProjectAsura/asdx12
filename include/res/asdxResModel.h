#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>
#include <fnd/asdxMath.h>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxStringView.h>
#include <res/asdxResBone.h>
#include <res/asdxResMesh.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResMeshInstance structure
///////////////////////////////////////////////////////////////////////////////
struct ResMeshInstance
{
    ArrayView<Matrix4x3>    Transform;
    ArrayView<uint32_t>     Meshes;
};


///////////////////////////////////////////////////////////////////////////////
// ResModel structure
///////////////////////////////////////////////////////////////////////////////
struct ResModel
{
    ArrayView<ResMesh>          Meshes;
    ArrayView<StringView>       Materials;
    ArrayView<ResBone>          Bones;
    ArrayView<ResMeshInstance>  MeshInstances;
};


///////////////////////////////////////////////////////////////////////////////
// ModelBinary class
///////////////////////////////////////////////////////////////////////////////
class ModelBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      モデルリソースを取得します.
    //! 
    //! @return     モデルリソースを返却します.
    //-------------------------------------------------------------------------
    ResModel GetResource() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>            m_Blob;
    std::vector<ResMesh>            m_Meshes;
    std::vector<StringView>         m_Materials;
    std::vector<ResBone>            m_Bones;
    std::vector<ResMeshInstance>    m_Instances;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx

