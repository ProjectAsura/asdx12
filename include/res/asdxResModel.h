///////////////////////////////////////////////////////////////////////////////
// AlphaMode enum
///////////////////////////////////////////////////////////////////////////////
enum AlphaMode : uint8_t
{
    Opaque,     //!< 不透明.
    Mask,       //!< アルファテスト.
    Blend,      //!< アルファブレンド.
};

///////////////////////////////////////////////////////////////////////////////
// ModelBinary class
///////////////////////////////////////////////////////////////////////////////
class ModelBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリア数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      バッチ数を取得します.
    //! 
    //! @return     バッチ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBatchCount() const;

    //-------------------------------------------------------------------------
    //! @brief      総インスタンス数を取得します.
    //! 
    //! @return     総インスタンス数を返却します.
    //-------------------------------------------------------------------------
    uint64_t GetTotalInstanceCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを取得します.
    //! 
    //! @param[in]      index       メッシュ番号.
    //! @return     メッシュを返却します.
    //-------------------------------------------------------------------------
    const res::Mesh& GetMesh(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     ボーンを返却します.
    //-------------------------------------------------------------------------
    const res::Bone& GetBone(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを取得します.
    //! 
    //! @param[in]      index       マテリアル番号.
    //! @return     マテリアルを返却します.
    //-------------------------------------------------------------------------
    const res::Material& GetMaterial(uint32_t materialIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      バッチを取得します.
    //! 
    //! @param[in]      index       バッチ番号.
    //! @return     バッチを返却します.
    //-------------------------------------------------------------------------
    const res::ModelBatch& GetBatch(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      バウンディングスフィアを取得します.
    //! 
    //! @return     バウンディングスフィアを返却します.
    //-------------------------------------------------------------------------
    BoundingSphere3 GetSphere() const;

    //-------------------------------------------------------------------------
    //! @brief      バウンディングボックスを取得します.
    //! 
    //! @return     バウンディングボックスを返却します.
    //-------------------------------------------------------------------------
    BoundingBox3 GetBox() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを検索します.
    //! 
    //! @param[in]      name        ボーン名です.
    //! @param[out]     index       ボーンの格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindBone(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを検索します.
    //! 
    //! @param[in]      name        マテリアル名です.
    //! @param[out]     index       マテリアル番号の格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindMaterial(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを検索します.
    //! 
    //! @param[in]      name        メッシュ名です.
    //! @param[out]     index       メッシュ番号の格納先です.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindMesh(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      インスタンスを検索します.
    //! 
    //! @param[in]      name            インスタンス名です.
    //! @param[out]     batchIndex      バッチ番号.
    //! @param[out]     instanceIndex   インスタンス番号.
    //! @retval true    検索にヒット.
    //! @retval false   見つかりませんでした.
    //-------------------------------------------------------------------------
    bool FindInstance(const char* name, uint32_t& bachIndex, uint32_t& instanceIndex) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t>    m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

