#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>
#include <fnd/asdxStringView.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResMeshMaterial structure
///////////////////////////////////////////////////////////////////////////////
struct ResMeshMaterial
{
    StringView  Name;   //!< メッシュマテリアル名.
    StringView  Path;   //!< マテリアルバイナリファイルパス.
};

///////////////////////////////////////////////////////////////////////////////
// ModelPrefabBInary class
///////////////////////////////////////////////////////////////////////////////
class ModelPrefabBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelPrefabBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelPrefabBinary();

    //-------------------------------------------------------------------------
    //! @brief      ロード処理を行います.
    //! 
    //! @param[in]      blob        バイナリデータ.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      モデルのバイナリファイルパスを取得します.
    //! 
    //! @return     モデルのバイナリファイルパスを返却します.
    //-------------------------------------------------------------------------
    StringView GetModelPath() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリアル数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを取得します.
    //! 
    //! @param[in]      index       マテリアル番号.
    //! @return     マテリアルを返却します.
    //-------------------------------------------------------------------------
    ResMeshMaterial GetMaterial(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを検索します.
    //! 
    //! @param[in]      name        マテリアル名.
    //! @param[out]     index       マテリアル番号.
    //! @retval true    検索に成功.
    //! @retval false   検索に失敗.
    //-------------------------------------------------------------------------
    bool FindMaterial(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを検索します.
    //! 
    //! @param[in]      name        マテリアル名.
    //! @param[out]     result      マテリアルの格納先.
    //! @retval true    検索に成功.
    //! @retval false   検索に失敗.
    //-------------------------------------------------------------------------
    bool FindMaterial(const char* name, ResMeshMaterial& result) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t> m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
