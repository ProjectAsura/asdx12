#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <dxgiformat.h>
#include <fnd/asdxBlob.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResFontBound structure
///////////////////////////////////////////////////////////////////////////////
struct ResFontBound
{
    float Left      = 0.0f;     // 左.
    float Right     = 0.0f;     // 右.
    float Top       = 0.0f;     // 上.
    float Bottom    = 0.0f;     // 下.
};

///////////////////////////////////////////////////////////////////////////////
// ResGlyph structure
///////////////////////////////////////////////////////////////////////////////
struct ResGlyph
{
    uint32_t        Unicode     = 0;        //!< ユニコード.
    float           Advance     = 0.0f;     //!< 文字送り横幅.
    ResFontBound    AtlasBound  = {};       //!< テクスチャ座標算出用領域.
    ResFontBound    PlaneBound  = {};       //!< 文字出力用領域.
};

///////////////////////////////////////////////////////////////////////////////
// FontBinary class
///////////////////////////////////////////////////////////////////////////////
class FontBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    FontBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~FontBinary();

    //-------------------------------------------------------------------------
    //! @brief      ファイルからロードします.
    //! 
    //! @param[in]      path        ファイルパスです.
    //! @retval true    ロードに成功.
    //! @retval false   ロードに失敗.
    //-------------------------------------------------------------------------
    bool LoadA(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      ファイルからロードします.
    //! 
    //! @param[in]      path        ファイルパスです.
    //! @retval true    ロードに成功.
    //! @retval false   ロードに失敗.
    //-------------------------------------------------------------------------
    bool LoadW(const wchar_t* path);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      ピクセル距離範囲を取得します.
    //! 
    //! @return     ピクセル距離範囲を返却します.
    //-------------------------------------------------------------------------
    float GetDistanceRange() const;

    //-------------------------------------------------------------------------
    //! @brief      フォントサイズを取得します.
    //! 
    //! @return     フォントサイズを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetFontSize() const;

    //-------------------------------------------------------------------------
    //! @brief      1行あたりの縦幅を取得します.
    //! 
    //! @return     1行あたりの縦幅を取得します.
    //-------------------------------------------------------------------------
    float GetLineHeight() const;

    //-------------------------------------------------------------------------
    //! @brief      mean lineよりも上側を取得します
    //! 
    //! @return     mean lineよりも上側を返却します.
    //-------------------------------------------------------------------------
    float GetAscender() const;

    //-------------------------------------------------------------------------
    //! @brief      mean lineよりも下側を取得します.
    //! 
    //! @return     mean lineよりも下側を取得します.
    //-------------------------------------------------------------------------
    float GetDescender() const;

    //-------------------------------------------------------------------------
    //! @brief      Y方向を反転するかどうかチェックします.
    //! 
    //! @retval true    Y方向を反転.
    //! @retval false   反転の必要性なし.
    //-------------------------------------------------------------------------
    bool IsFlipY() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャの横幅を取得します.
    //! 
    //! @return     テクスチャの横幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetWidth() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャの縦幅を取得します.
    //! 
    //! @return     テクスチャの縦幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetHeight() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャの1行あたりのサイズを取得します.
    //! 
    //! @return     テクスチャの１行あたりのサイズを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetRowPitch() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャのスライスサイズを取得します.
    //! 
    //! @return     テクスチャのスライスサイズを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetSlicePitch() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャフォーマットを取得します.
    //! 
    //! @return     テクスチャフォーマットを返却します.
    //-------------------------------------------------------------------------
    DXGI_FORMAT GetFormat() const;

    //-------------------------------------------------------------------------
    //! @brief      テクセルデータを取得します.
    //! 
    //! @return     テクセルデータを返却します.
    //-------------------------------------------------------------------------
    const uint8_t* GetTexels() const;

    //-------------------------------------------------------------------------
    //! @brief      グリフを検索します.
    //! 
    //! @param[in]      unicode     ユニコード.
    //! @param[out]     result      グリフの格納先.
    //! @retval true    検索にヒット.
    //! @retval false   見つからなかった.
    //-------------------------------------------------------------------------
    bool FindGlyph(uint32_t unicode, ResGlyph& result) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    IBlob* m_pBlob = nullptr;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      pBinary         バイナリデータです.
    //! @param[in]      binarySize      バイナリサイズです.
    //! @retval true    ロードに成功.
    //! @retval false   ロードに失敗.
    //-------------------------------------------------------------------------
    bool LoadFromMemory(void* pBinary, size_t binarySize);
};

} // namespace asdx
