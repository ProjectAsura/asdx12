#include <vector>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxMath.h>
#include <fnd/asdxStringView.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// TILE_FLAGS enumeration
///////////////////////////////////////////////////////////////////////////////
enum TILE_FLAGS : uint8_t
{
    TILE_FLAG_NONE      = 0x0,        //!< フラグ指定なし.
    TILE_FLAG_COLLISION = 0x1 << 0,   //!< 衝突判定あり.
    TILE_FLAG_EVENT     = 0x1 << 1,   //!< イベントあり.
    TILE_FLAG_DAMAGE    = 0x1 << 2,   //!< ダメージあり.
    TILE_FLAG_TOL       = 0x1 << 3,   //!< 離着陸可能 (TOL: Take Off and Landing).
};

///////////////////////////////////////////////////////////////////////////////
// ResTileProp structure
///////////////////////////////////////////////////////////////////////////////
struct ResTileProp
{
    uint16_t     Flags;           //!< フラグ.
    uint16_t     EventId;         //!< イベントID.
};

///////////////////////////////////////////////////////////////////////////////
// ResChipFrame structure
///////////////////////////////////////////////////////////////////////////////
struct ResChipFrame
{
    uint32_t    Id;             //!< タイル番号.
    float       Duration;       //!< 継続時間(ミリ秒).
};

///////////////////////////////////////////////////////////////////////////////
// ResMapLayer structure
///////////////////////////////////////////////////////////////////////////////
struct ResMapLayer
{
    StringView          Name;       //!< 名前.
    ArrayView<uint16_t> Tiles;      //!< タイルデータ.
};

///////////////////////////////////////////////////////////////////////////////
// ResTileCoord structure
///////////////////////////////////////////////////////////////////////////////
struct ResTileCoord
{
    Vector2 Uv0;    //!< 左上のテクスチャ座標.
    Vector2 Uv1;    //!< 右下のテクスチャ座標.
};

///////////////////////////////////////////////////////////////////////////////
// MapChipBinary class
///////////////////////////////////////////////////////////////////////////////
class MapChipBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MapChipBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MapChipBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      行数を取得します.
    //! 
    //! @return     行数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMapRows() const;

    //-------------------------------------------------------------------------
    //! @brief      列数を取得します.
    //! 
    //! @return     列数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMapColumns() const;

    //-------------------------------------------------------------------------
    //! @brief      マップチップの行数を取得します.
    //! 
    //! @return     マップチップの行数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetChipRows() const;

    //-------------------------------------------------------------------------
    //! @brief      マップチップの列数を取得します.
    //!
    //! @return     マップチップの列数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetChipColumns() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルの横幅を取得します.
    //! 
    //! @return     タイルを横幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetChipWidth() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルの縦幅を取得します.
    //! 
    //! @return     タイルの縦幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetChipHeight() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャの横幅を取得します.
    //! 
    //! @return     テクスチャの横幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTextureWidth() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャの縦幅を取得します.
    //! 
    //! @return     テクスチャの縦幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTextureHeight() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャのパスを取得します.
    //! 
    //! @return     テクスチャのパスを返却します.
    //-------------------------------------------------------------------------
    StringView GetTexturePath() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルの最初のIDを取得します.
    //! 
    //! @return     タイルの最初のIDを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetFirstChipId() const;

    //-------------------------------------------------------------------------
    //! @brief      レイヤー数を取得します.
    //! 
    //! @return     レイヤー数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetLayerCount() const;

    //-------------------------------------------------------------------------
    //! @brief      レイヤーを取得します.
    //! 
    //! @param[in]      index      レイヤー番号.
    //! @return     指定されたレイヤーを返却します.
    //-------------------------------------------------------------------------
    ResMapLayer GetLayer(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      指定タイルのテクスチャ座標を取得します.
    //! 
    //! @param[in]      index       タイル番号.
    //! @return     指定タイルのテクスチャ座標を返却します.
    //-------------------------------------------------------------------------
    ResTileCoord GetCoord(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      指定タイルのプロパティを取得します.
    //! 
    //! @param[in]      index       タイル番号.
    //! @return     指定タイルのプロパティを返却します.
    //-------------------------------------------------------------------------
    ResTileProp GetTileProp(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      タイル番号を求めます.
    //! 
    //! @param[in]      x       タイルX.
    //! @param[in]      y       タイルY.
    //! @param[in]      repeat  繰り返しする場合は true.
    //! @return     タイル番号を返却します.
    //-------------------------------------------------------------------------
    uint32_t CalcTileIndex(uint32_t x, uint32_t y, bool repeat = true) const;

private:
    //=========================================================================
    // private varaibles.
    //=========================================================================
    std::vector<uint8_t>    m_Blob; //!< バイナリデータ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
