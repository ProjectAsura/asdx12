#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <vector>
#include <fnd/asdxArrayView.h>
#include <fnd/asdxMath.h>
#include <res/asdxResTexture.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ResTileSet structure
///////////////////////////////////////////////////////////////////////////////
struct ResTileSet
{
    uint32_t    FirstChipId;
    uint32_t    Columns;
    uint32_t    TileCount;
    uint32_t    TileWidth;
    uint32_t    TileHeight;
};

///////////////////////////////////////////////////////////////////////////////
// ResTileMapLayer structure
///////////////////////////////////////////////////////////////////////////////
struct ResTileMapLayer
{
    uint32_t            Id;
    uint32_t            Rows;
    uint32_t            Columns;
    ArrayView<uint16_t> Data;
};

///////////////////////////////////////////////////////////////////////////////
// ResTileCoord structure
///////////////////////////////////////////////////////////////////////////////
struct ResTileCoord
{
    Vector2 Uv0;
    Vector2 Uv1;
};

///////////////////////////////////////////////////////////////////////////////
// MapChipBinary class
///////////////////////////////////////////////////////////////////////////////
class MapChipBinary
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MapChipBinary();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MapChipBinary();

    //-------------------------------------------------------------------------
    //! @brief      メモリからロードします.
    //! 
    //! @param[in]      blob        バイナリラージオブジェクト.
    //-------------------------------------------------------------------------
    void Load(std::vector<uint8_t>&& blob);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      行数を取得します.
    //! 
    //! @return     行数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetRows() const;

    //-------------------------------------------------------------------------
    //! @brief      列数を取得します.
    //! 
    //! @return     列数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetColumns() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルの横幅を取得します.
    //! 
    //! @return     タイルを横幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTileWidth() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルの縦幅を取得します.
    //! 
    //! @return     タイルの縦幅を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTileHeight() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルセット数を取得します.
    //! 
    //! @return     タイルセット数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTileSetCount() const;

    //-------------------------------------------------------------------------
    //! @brief      タイルセットを取得します.
    //! 
    //! @param[in]      tileSetIndex        タイルセット番号.
    //! @return     指定されたタイルセットを返却します.
    //-------------------------------------------------------------------------
    ResTileSet GetTileSet(uint32_t tileSetIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      マップチップを取得します.
    //! 
    //! @param[in]      tileSetIndex        タイルセット番号.
    //! @return     指定されたマップチップを返却します.
    //-------------------------------------------------------------------------
    ResTexture GetMapChip(uint32_t tileSetIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      レイヤー数を取得します.
    //! 
    //! @return     レイヤー数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetLayerCount() const;

    //-------------------------------------------------------------------------
    //! @brief      レイヤーを取得します.
    //! 
    //! @param[in]      layerIndex      レイヤー番号.
    //! @return     指定されたレイヤーを返却します.
    //-------------------------------------------------------------------------
    ResTileMapLayer GetLayer(uint32_t layerIndex) const;

    //-------------------------------------------------------------------------
    //! @brief      指定タイルのテクスチャ座標を取得します.
    //! 
    //! @param[in]      tileSetIndex    タイルセット番号.
    //! @param[in]      tileId          タイル番号.
    //! @return     指定タイルのテクスチャ座標を返却します.
    //-------------------------------------------------------------------------
    ResTileCoord GetCoord(uint32_t tileSetIndex, uint32_t tileId) const;

private:
    //=========================================================================
    // private varaibles.
    //=========================================================================
    std::vector<uint8_t>    m_Blob;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
