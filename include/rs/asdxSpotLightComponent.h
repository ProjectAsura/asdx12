#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <fnd/asdxList.h>
#include <fnd/asdxMath.h>
#include <rs/asdxSceneComponent.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// SpotLightComponent class
///////////////////////////////////////////////////////////////////////////////
class SpotLightComponent final
 : public SceneComponent
 , public List<SpotLightComponent>::Node
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SpotLightComponent() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SpotLightComponent() = default;

    //-------------------------------------------------------------------------
    //! @brief      ライトの照射方向を設定します.
    //! 
    //! @param[in]      value       設定する照射方向.
    //-------------------------------------------------------------------------
    void SetForward(const Vector3& value);

    //-------------------------------------------------------------------------
    //! @brief      ライトの照射方向を取得します.
    //! 
    //! @return     ライトの照射方向を返却します.
    //-------------------------------------------------------------------------
    const Vector3& GetForward() const;

    //-------------------------------------------------------------------------
    //! @brief      カラーを設定します.
    //! 
    //! @param[in]      value       設定するカラー.
    //-------------------------------------------------------------------------
    void SetColor(const Vector3& value);

    //-------------------------------------------------------------------------
    //! @brief      カラーを取得します.
    //! 
    //! @return     カラーを返却します.
    //-------------------------------------------------------------------------
    const Vector3& GetColor() const;

    //-------------------------------------------------------------------------
    //! @brief      ライト強度を設定します.
    //! 
    //! @param[in]      value       設定するライト強度.
    //-------------------------------------------------------------------------
    void SetIntensity(float value);

    //-------------------------------------------------------------------------
    //! @brief      ライト強度を取得します.
    //! 
    //! @return     ライト強度を返却します.
    //-------------------------------------------------------------------------
    float GetIntensity() const;

    //-------------------------------------------------------------------------
    //! @brief      半径を設定します.
    //! 
    //! @param[in]      value       設定する半径(単位：メートル).
    //-------------------------------------------------------------------------
    void SetRadius(float value);

    //-------------------------------------------------------------------------
    //! @brief      半径を取得します.
    //! 
    //! @return     半径を返却します(単位：メートル).
    //-------------------------------------------------------------------------
    float GetRadius() const;

    //-------------------------------------------------------------------------
    //! @brief      内角を設定します.
    //! 
    //! @param[in]      rad         設定する内角(単位：ラジアン).
    //-------------------------------------------------------------------------
    void SetInnerAngle(float rad);

    //-------------------------------------------------------------------------
    //! @brief      内角を取得します.
    //! 
    //! @return     内角を返却します(単位：ラジアン).
    //-------------------------------------------------------------------------
    float GetInnerAngle() const;

    //-------------------------------------------------------------------------
    //! @brief      外角を設定します.
    //! 
    //! @param[in]      rad         設定する外角(単位：ラジアン).
    //-------------------------------------------------------------------------
    void SetOuterAngle(float rad);

    //-------------------------------------------------------------------------
    //! @brief      外角を取得します.
    //! 
    //! @return     外角を返却します(単位：ラジアン).
    //-------------------------------------------------------------------------
    float GetOuterAngle() const;

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを設定します.
    //! 
    //! @param[in]      value       影を投影する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetCastShadow(bool value);

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを取得します.
    //! 
    //! @retval true    影あり.
    //! @retval false   影なし.
    //-------------------------------------------------------------------------
    bool IsCastShadow() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    Vector3     m_Forward       = Vector3(0.0f, 0.0f, 1.0f);
    Vector3     m_Color         = Vector3(1.0f, 1.0f, 1.0f);
    float       m_Radius        = 1.0f;
    float       m_Intensity     = 1.0f;
    float       m_InnerAngle    = ToRadian(30.0f);
    float       m_OuterAngle    = ToRadian(60.0f);
    bool        m_CastShadow    = false;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
