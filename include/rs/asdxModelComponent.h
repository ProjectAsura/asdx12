#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <fnd/asdxMath.h>
#include <fnd/asdxList.h>
#include <gfx/asdxModelManager.h>
#include <rs/asdxSceneComponent.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ModelComponent class
///////////////////////////////////////////////////////////////////////////////
class ModelComponent
: public SceneComponent
, public List<ModelComponent>::Node
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public mehtods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelComponent() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelComponent();

    //-------------------------------------------------------------------------
    //! @brief      モデルを設定します.
    //! 
    //! @param[in]      model       設定するモデル.
    //-------------------------------------------------------------------------
    void SetModelHolder(ModelHolder&& model);

    //-------------------------------------------------------------------------
    //! @brief      モデルを取得します.
    //! 
    //! @return     モデルを返却します.
    //-------------------------------------------------------------------------
    const ModelHolder& GetModelHolder() const;

    //-------------------------------------------------------------------------
    //! @brief      モデルを解放します.
    //-------------------------------------------------------------------------
    void ResetModel();

    //-------------------------------------------------------------------------
    //! @brief      モデルを持っているかどうかチェックします.
    //! 
    //! @retval true    モデルを持っています.
    //! @retval false   モデルを持っていません.
    //-------------------------------------------------------------------------
    bool HasModel() const;

    //-------------------------------------------------------------------------
    //! @brief      可視フラグを設定します.
    //! 
    //! @param[in]      value       表示設定する場合は true を指定します.
    //-------------------------------------------------------------------------
    void SetVisible(bool value);

    //-------------------------------------------------------------------------
    //! @brief      可視フラグを取得します.
    //! 
    //! @retval true    表示.
    //! @retval false   非表示.
    //-------------------------------------------------------------------------
    bool IsVisible() const;

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを設定します.
    //! 
    //! @param[in]      value       影を投影する場合は true を指定します.
    //-------------------------------------------------------------------------
    void SetCastShadow(bool value);

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを取得します.
    //! 
    //! @retval true    影あり.
    //! @retval false   影なし.
    //-------------------------------------------------------------------------
    bool IsCastShadow() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    ModelHolder     m_Model         = {};
    bool            m_Visible       = true;
    bool            m_CastShadow    = true;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
