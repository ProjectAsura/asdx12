#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <fnd/asdxList.h>
#include <fnd/asdxMath.h>
#include <rs/asdxSceneComponent.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// PointLightComponent class
///////////////////////////////////////////////////////////////////////////////
class PointLightComponent final
: public SceneComponent
, public List<PointLightComponent>::Node
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    PointLightComponent() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~PointLightComponent() = default;

    //-------------------------------------------------------------------------
    //! @brief      カラーを設定します.
    //! 
    //! @param[in]      value       設定するカラー.
    //-------------------------------------------------------------------------
    void SetColor(const Vector3& value);

    //-------------------------------------------------------------------------
    //! @brief      カラーを取得します.
    //! 
    //! @return     カラーを返却します.
    //-------------------------------------------------------------------------
    const Vector3& GetColor() const;

    //-------------------------------------------------------------------------
    //! @brief      ライト強度を設定します.
    //! 
    //! @param[in]      value       設定するライト強度.
    //-------------------------------------------------------------------------
    void SetIntensity(float value);

    //-------------------------------------------------------------------------
    //! @brief      ライト強度を取得します.
    //! 
    //! @return     ライト強度を返却します.
    //-------------------------------------------------------------------------
    float GetIntensity() const;

    //-------------------------------------------------------------------------
    //! @brief      半径を設定します.
    //! 
    //! @param[in]      value       設定する半径(単位：メートル).
    //-------------------------------------------------------------------------
    void SetRadius(float value);

    //-------------------------------------------------------------------------
    //! @brief      半径を取得します.
    //! 
    //! @return     半径を返却します.
    //-------------------------------------------------------------------------
    float GetRadius() const;

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを設定します.
    //! 
    //! @param[in]      value       影を投影する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetCastShadow(bool value);

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを取得します.
    //! 
    //! @retval true    影あり.
    //! @retval false   影なし.
    //-------------------------------------------------------------------------
    bool IsCastShadow() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    Vector3     m_Color         = Vector3(1.0f, 1.0f, 1.0f);
    float       m_Intensity     = 1.0f;
    float       m_Radius        = 1.0f;
    bool        m_CastShadow    = false;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
