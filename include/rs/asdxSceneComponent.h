#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <string>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class SceneNode;


///////////////////////////////////////////////////////////////////////////////
// SceneComponent class
///////////////////////////////////////////////////////////////////////////////
class SceneComponent
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend class SceneNode;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~SceneComponent() = default;

    //-------------------------------------------------------------------------
    //! @brief      有効フラグを設定します.
    //! 
    //! @param[in]      value       有効にする場合は true を指定.
    //-------------------------------------------------------------------------
    void SetEnable(bool value)
    { m_Enable = value; }

    //-------------------------------------------------------------------------
    //! @brief      有効フラグを取得します.
    //! 
    //! @retval true    有効です.
    //! @retval false   無効です.
    //-------------------------------------------------------------------------
    bool IsEnable() const
    { return m_Enable; }

    //-------------------------------------------------------------------------
    //! @brief      ノードを取得します.
    //! 
    //! @return     ノードを返却します.
    //-------------------------------------------------------------------------
    SceneNode* GetNode() const
    { return m_pNode; }

    //-------------------------------------------------------------------------
    //! @brief      名前を設定します.
    //! 
    //! @param[in]      value       設定する名前.
    //-------------------------------------------------------------------------
    void SetName(const std::string& value)
    { m_Name = value; }

    //-------------------------------------------------------------------------
    //! @brief      名前を設定します.
    //! 
    //! @param[in]      value       設定する名前.
    //-------------------------------------------------------------------------
    void SetName(const char* value)
    { m_Name = value; }

    //-------------------------------------------------------------------------
    //! @brief      名前を取得します.
    //! 
    //! @return     名前を返却します.
    //-------------------------------------------------------------------------
    const std::string& GetName() const
    { return m_Name; }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    SceneNode*      m_pNode     = nullptr;
    std::string     m_Name      = {};
    bool            m_Enable    = true;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
