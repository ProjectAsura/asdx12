#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
struct IXAudio2SourceVoice;


namespace asdx {

//-----------------------------------------------------------------------------
// Constants.
//-----------------------------------------------------------------------------
static const uint32_t kSoundLoopInfinite = 255;     //!< 無限ループ (SoundBufferDesc.LoopCountに指定).
static const uint32_t kSoundEndOfStream  = 0x40;    //!< ストリームの最後まで再生(SoundBufferDesc.Flagsに指定).


///////////////////////////////////////////////////////////////////////////////
// SoundBufferDesc structure
///////////////////////////////////////////////////////////////////////////////
struct SoundBufferDesc
{
    const uint8_t*  pAudioData  = nullptr;
    uint32_t        AudioBytes  = 0;
    uint32_t        PlayBegin   = 0;
    uint32_t        PlayLength  = 0;
    uint32_t        LoopBegin   = 0;
    uint32_t        LoopLength  = 0;
    uint32_t        LoopCount   = 0;
    uint32_t        Flags       = 0;
};

///////////////////////////////////////////////////////////////////////////////
// WaveFormat structure
///////////////////////////////////////////////////////////////////////////////
#pragma pack (1)
struct WaveFormat
{
    uint16_t    FormatTag;
    uint16_t    ChannelCount;
    uint32_t    SamplePerSec;
    uint32_t    AvgBytesPerSec;
    uint16_t    BlockAlign;
    uint16_t    BitPerSample;
    uint16_t    ExtraSize;
};
#pragma pack()

///////////////////////////////////////////////////////////////////////////////
// SoundData structure
///////////////////////////////////////////////////////////////////////////////
struct SoundData
{
    std::vector<uint8_t>    FormatData  = {};
    std::vector<uint8_t>    AudioData   = {};
};

//-----------------------------------------------------------------------------
//! @brief      db(デシベル)からボリューム値に変換します.
//! 
//! @param[in]      db      変換するデシベル値.
//-----------------------------------------------------------------------------
float DbToVolume(float db);

//-----------------------------------------------------------------------------
//! @brief      ボリューム値から db(デシベル)に変換します.
//! 
//! @param[in]      volume  変換するボリューム値.
//-----------------------------------------------------------------------------
float VolumeToDb(float volume);


///////////////////////////////////////////////////////////////////////////////
// SoundResource class
///////////////////////////////////////////////////////////////////////////////
class SoundResource
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SoundResource();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SoundResource();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      data        音源データです.
    //! @param[in]      desc        サウンドバッファの設定です.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const SoundData& data, const SoundBufferDesc& desc);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      再生処理を行います.
    //-------------------------------------------------------------------------
    void Play();

    //-------------------------------------------------------------------------
    //! @brief      一時停止を行います.
    //-------------------------------------------------------------------------
    void Pause();

    //-------------------------------------------------------------------------
    //! @brief      停止処理を行います.
    //! 
    //! @note       即時停止のブツ切りとなります. 
    //-------------------------------------------------------------------------
    void Stop();

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを取得します.
    //! 
    //! @retval true    ループ再生です.
    //! @retval false   非ループ再生です.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生を終了します.
    //-------------------------------------------------------------------------
    void ExitLoop();

    //-------------------------------------------------------------------------
    //! @brief      再生完了済みかどうかチェックします.
    //! 
    //! @retval true    再生完了.
    //! @retval false   再生中.
    //-------------------------------------------------------------------------
    bool IsFinished() const;

    //-------------------------------------------------------------------------
    //! @brief      音量を設定します.
    //! 
    //! @param[in]      value       設定する音量です.
    //-------------------------------------------------------------------------
    void SetVolume(float value);

    //-------------------------------------------------------------------------
    //! @brief      音量を取得します.
    //! 
    //! @return     音量を返却します.
    //-------------------------------------------------------------------------
    float GetVolume() const;

    //-------------------------------------------------------------------------
    //! @brief      再生ピッチを設定します.
    //! 
    //! @param[in]      value       再生速度[0.0f, 2.0f]
    //-------------------------------------------------------------------------
    void SetPitch(float value);

    //-------------------------------------------------------------------------
    //! @brief      再生ピッチを取得します.
    //! 
    //! @return     再生ピッチを返却します.
    //-------------------------------------------------------------------------
    float GetPitch() const;

    //-------------------------------------------------------------------------
    //! @brief      ソースボイスを取得します.
    //! 
    //! @return     ソースボイスを返却します.
    //-------------------------------------------------------------------------
    IXAudio2SourceVoice* GetSourceVoice() const;

    //-------------------------------------------------------------------------
    //! @brief      バッファを再設定します.
    //! 
    //! @param[in]      desc        サウンドバッファ設定.
    //-------------------------------------------------------------------------
    void ResetBuffer(const SoundBufferDesc& desc);

    //-------------------------------------------------------------------------
    //! @brief      オーディオデータを取得します.
    //! 
    //! @return     オーディオデータを返却します.
    //-------------------------------------------------------------------------
    const std::vector<uint8_t>& GetAudioData() const;

    //-------------------------------------------------------------------------
    //! @brief      波形フォーマットを取得します.
    //! 
    //! @return     波形フォーマットを返却します.
    //-------------------------------------------------------------------------
    const WaveFormat* GetWaveFormat() const;

    //-------------------------------------------------------------------------
    //! @brief      サウンドバッファ設定を取得します.
    //! 
    //! @return     サウンドバッファ設定を返却します.
    //-------------------------------------------------------------------------
    const SoundBufferDesc& GetDesc() const;

    //-------------------------------------------------------------------------
    //! @brief      音量フェードを行います.
    //! 
    //! @param[in]      targetVolume    ターゲットボリューム値.
    //! @param[in       targetSec       フェード時間(単位:秒).
    //-------------------------------------------------------------------------
    void Fade(float targetVolume, float targetSec);

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec        差分時間(単位:秒).
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    SoundData            m_SounData         = {};
    SoundBufferDesc      m_Desc             = {};
    float                m_ElapsedSec       = 0.0f;
    float                m_FadeStartVolume  = 0.0f;
    float                m_FadeTargetVolume = 0.0f;
    float                m_FadeSec          = 0.0f;
    bool                 m_Loop             = false;
    IXAudio2SourceVoice* m_pSourceVoice     = nullptr;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

//-----------------------------------------------------------------------------
//! @brief      wavファイルからサウンドデータをロードします.
//! 
//! @param[in]      path        ファイルパスです.
//! @param[out]     result      サウンドデータの格納先です.
//! @retval true    ロードに成功.
//! @retval false   ロードに失敗.
//-----------------------------------------------------------------------------
bool LoadFromWav(const char* path, SoundData& result);

//-----------------------------------------------------------------------------
//! @brief      oggファイルからサウンドデータをロードします.
//! 
//! @param[in]      path        ファイルパスです.
//! @param[out]     result      サウンドデータの格納先です.
//! @retval true    ロードに成功.
//! @retval fasle   ロードに失敗.
//-----------------------------------------------------------------------------
bool LoadFromOgg(const char* path, SoundData& result);

} // namespace asdx
