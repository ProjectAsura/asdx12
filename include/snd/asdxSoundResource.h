#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
struct IXAudio2SourceVoice;


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// SoundData structure
///////////////////////////////////////////////////////////////////////////////
struct SoundData
{
    std::vector<uint8_t>    FormatData  = {};
    std::vector<uint8_t>    AudioData   = {};
    bool                    Loop        = false;
};

///////////////////////////////////////////////////////////////////////////////
// SoundResource class
///////////////////////////////////////////////////////////////////////////////
class SoundResource
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SoundResource();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SoundResource();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      data        音源データです.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const SoundData& data);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      再生処理を行います.
    //-------------------------------------------------------------------------
    void Play();

    //-------------------------------------------------------------------------
    //! @brief      停止処理を行います.
    //-------------------------------------------------------------------------
    void Stop();

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを取得します.
    //! 
    //! @retval true    ループ再生です.
    //! @retval false   非ループ再生です.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生を終了します.
    //-------------------------------------------------------------------------
    void ExitLoop();

    //-------------------------------------------------------------------------
    //! @brief      再生完了済みかどうかチェックします.
    //! 
    //! @retval true    再生完了.
    //! @retval false   再生中.
    //-------------------------------------------------------------------------
    bool IsFinished() const;

    //-------------------------------------------------------------------------
    //! @brief      音量を設定します.
    //! 
    //! @param[in]      value       設定する音量です.
    //-------------------------------------------------------------------------
    void SetVolume(float value);

    //-------------------------------------------------------------------------
    //! @brief      音量を取得します.
    //! 
    //! @return     音量を返却します.
    //-------------------------------------------------------------------------
    float GetVolume() const;

    //-------------------------------------------------------------------------
    //! @brief      ソースボイスを取得します.
    //! 
    //! @return     ソースボイスを返却します.
    //-------------------------------------------------------------------------
    IXAudio2SourceVoice* GetSourceVoice() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint8_t> m_AudioData    = {};
    bool                 m_Loop         = false;
    IXAudio2SourceVoice* m_pSourceVoice = nullptr;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      バッファを再設定します.
    //-------------------------------------------------------------------------
    void ResetBuffer();
};

//-----------------------------------------------------------------------------
//! @brief      wavファイルからサウンドデータをロードします.
//! 
//! @param[in]      path        ファイルパスです.
//! @param[out]     result      サウンドデータの格納先です.
//! @retval true    ロードに成功.
//! @retval false   ロードに失敗.
//-----------------------------------------------------------------------------
bool LoadFromWav(const char* path, SoundData& result);

//-----------------------------------------------------------------------------
//! @brief      oggファイルからサウンドデータをロードします.
//! 
//! @param[in]      path        ファイルパスです.
//! @param[out]     result      サウンドデータの格納先です.
//! @retval true    ロードに成功.
//! @retval fasle   ロードに失敗.
//-----------------------------------------------------------------------------
bool LoadFromOgg(const char* path, SoundData& result);

} // namespace asdx
