#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <unordered_map>
#include <fnd/asdxSpinLock.h>
#include <fnd/asdxResHolder.h>
#include <gfx/asdxMaterial.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class MaterialManager;

//-----------------------------------------------------------------------------
// Type Alias.
//-----------------------------------------------------------------------------
using MaterialHolder = ResHolder<Material, MaterialManager>;


///////////////////////////////////////////////////////////////////////////////
// MaterialManager class
///////////////////////////////////////////////////////////////////////////////
class MaterialManager
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインタンスを取得します
    //! 
    //! @return     シングルトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static MaterialManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功 または 初期化済み.
    //! @retval false   初期化に失敗. 
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを生成または取得します.
    //! 
    //! @param[in]      path        ファイルパス(フルパス).
    //! @return     マテリアルホルダーを返却します.
    //-------------------------------------------------------------------------
    MaterialHolder GetOrCreate(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを削除します.
    //! 
    //! @param[in]      holder      マテリアルホルダー.
    //-------------------------------------------------------------------------
    void Remove(MaterialHolder& holder);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static MaterialManager                  s_Instance;
    SpinLock                                m_SpinLock;
    std::unordered_map<uint64_t, Material*> m_Materials;
    bool                                    m_Initialized = false;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MaterialManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MaterialManager();

    MaterialManager             (const MaterialManager&) = delete;
    MaterialManager& operator = (const MaterialManager&) = delete;
};

} // namespace asdx
