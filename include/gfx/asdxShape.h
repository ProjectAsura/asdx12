class ShapeParams
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ShapeParams();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ShapeParams();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //-------------------------------------------------------------------------
    bool Init(uint32_t count);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      ワールド行列を設定します.
    //! 
    //! @param[in]      index       番号.
    //! @param[in]      value       設定する値.
    //-------------------------------------------------------------------------
    void SetWorld(uint32_t index, const asdx::Matrix& value);

    //-------------------------------------------------------------------------
    //! @brief      カラーを設定します.
    //!
    //! @param[in]      index       番号.
    //! @param[in]      value       設定する値.
    //-------------------------------------------------------------------------
    void SetColor(uint32_t index, const asdx::Vector4& value);

    //-------------------------------------------------------------------------
    //! @brief      ワールド行列を取得します.
    //! 
    //! @param[in]      index       番号.
    //! @return     ワールド行列を返却します.
    //-------------------------------------------------------------------------
    const asdx::Matrix& GetWorld(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      カラーを取得します.
    //! 
    //! @param[in]      index       番号.
    //! @return     カラーを返却します.
    //-------------------------------------------------------------------------
    const asdx::Vector4& GetColor(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @return     コマンドリストに設定するためのGPU仮想アドレスを返却します.
    //-------------------------------------------------------------------------
    D3D12_GPU_VIRTUAL_ADDRESS Update();

private:
    ///////////////////////////////////////////////////////////////////////////
    // Param structure
    ///////////////////////////////////////////////////////////////////////////
    struct Param
    {
        Matrix  World;
        Vector4 Color;
    };

    //=========================================================================
    // private variables.
    //=========================================================================
    asdx::RefPtr<ID3D12Resource>        m_ParamBuffer;
    std::vector<Param>                  m_Params;
    AllocationHolder                    m_AllocationPB;
    uint8_t                             m_BufferIndex;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

