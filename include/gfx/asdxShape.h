///////////////////////////////////////////////////////////////////////////////
// ShapeStates class
///////////////////////////////////////////////////////////////////////////////
class ShapeStates
{
    // ルートシグニチャのレイアウトは下記のとおりです.
    // [0] : CBV register = 0, D3D12_SHADER_VISIBILITY_ALL
    // [1] : CBV register = 1, D3D12_SHADER_VISIBILITY_ALL
    // [2] : CBV register = 2, D3D12_SHADER_VISIBILITY_ALL
    // [3] : Constants register = 3, count = 4, D3D12_SHADER_VISIBILITY_ALL
    // [4] : SRV Buffer register = 0, D3D12_SHADER_VISIBILITY_ALL
    // [5] : SRV Buffer register = 1, D3D12_SHADER_VISIBILITY_ALL

    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    static const uint32_t CBV0         = 0;
    static const uint32_t CBV1         = 1;
    static const uint32_t CBV2         = 2;
    static const uint32_t Constants3   = 3;
    static const uint32_t SRV0         = 4;
    static const uint32_t SRV1         = 5;

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ShapeStates();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ShapeStates();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //-------------------------------------------------------------------------
    bool Init(DXGI_FORMAT colorFormat, DXGI_FORMAT depthFormat);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      ビュー行列と射影行列を設定します.
    //! 
    //! @param[in]      view        ビュー行列
    //! @param[in]      proj        射影行列
    //! @note       内部でダブルバッファリングのバッファ番号入れ替えが行われますので，
    //!             1フレームに1回のみ呼び出してください.
    //-------------------------------------------------------------------------
    void SetViewProj(const asdx::Matrix& view, const asdx::Matrix& proj);

    //-------------------------------------------------------------------------
    //! @brief      不透明ステートを適用します.
    //! 
    //! @param[in]      pCmd        コマンドリストです.
    //-------------------------------------------------------------------------
    void ApplyOpaqueState(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      半透明ステートを適用します.
    //! 
    //! @param[in]      pCmd        コマンドリストです.
    //-------------------------------------------------------------------------
    void ApplyTranslucentState(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      ワイヤーフレームステートを適用します.
    //! 
    //! @param[in]      pCmd        コマンドリストです.
    //-------------------------------------------------------------------------
    void ApplyWireframeState(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      カメラ定数バッファのGPU仮想アドレスを取得します.
    //-------------------------------------------------------------------------
    D3D12_GPU_VIRTUAL_ADDRESS GetBufferAddress() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    asdx::RefPtr<ID3D12RootSignature>   m_RootSignature;
    asdx::RefPtr<ID3D12PipelineState>   m_OpaqueState;
    asdx::RefPtr<ID3D12PipelineState>   m_TranslucentState;
    asdx::RefPtr<ID3D12PipelineState>   m_WireframeState;
    asdx::RefPtr<ID3D12Resource>        m_CameraBuffer;
    AllocationHolder                    m_CameraBufferAllocation;
    uint8_t                             m_BufferIndex = 0;
    asdx::Matrix                        m_View;
    asdx::Matrix                        m_Proj;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

