///////////////////////////////////////////////////////////////////////////////
// ShapeStates class
///////////////////////////////////////////////////////////////////////////////
class ShapeStates
{
    // ルートシグニチャのレイアウトは下記のとおりです.
    // [0] : CBV register = 0, D3D12_SHADER_VISIBILITY_ALL
    // [1] : CBV register = 1, D3D12_SHADER_VISIBILITY_ALL
    // [2] : CBV register = 2, D3D12_SHADER_VISIBILITY_ALL
    // [3] : Constants register = 3, count = 4, D3D12_SHADER_VISIBILITY_ALL
    // [4] : SRV Buffer register = 0, D3D12_SHADER_VISIBILITY_ALL
    // [5] : SRV Buffer register = 1, D3D12_SHADER_VISIBILITY_ALL

    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    static const uint32_t CBV0 = 0;     // ビュー行列・射影行列設定用.
    static const uint32_t CBV1 = 1;     // 汎用.
    static const uint32_t CBV2 = 2;     // 汎用.
    static const uint32_t CBV3 = 3;     // パラメータ番号設定用.
    static const uint32_t SRV0 = 4;     // StructuedBuffer用(ワールド行列・カラー行列用).
    static const uint32_t SRV1 = 5;     // 汎用.

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ShapeStates();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ShapeStates();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //-------------------------------------------------------------------------
    bool Init(DXGI_FORMAT colorFormat, DXGI_FORMAT depthFormat);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      ビュー行列と射影行列を設定します.
    //! 
    //! @param[in]      view        ビュー行列
    //! @param[in]      proj        射影行列
    //! @note       内部処理でダブルバッファ更新が行われます.
    //-------------------------------------------------------------------------
    void SetViewProj(const Matrix& view, const Matrix& proj);

    //-------------------------------------------------------------------------
    //! @brief      不透明ステートを適用します.
    //! 
    //! @param[in]      pCmd        コマンドリストです.
    //-------------------------------------------------------------------------
    void ApplyOpaqueState(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      半透明ステートを適用します.
    //! 
    //! @param[in]      pCmd        コマンドリストです.
    //-------------------------------------------------------------------------
    void ApplyTranslucentState(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      ワイヤーフレームステートを適用します.
    //! 
    //! @param[in]      pCmd        コマンドリストです.
    //-------------------------------------------------------------------------
    void ApplyWireframeState(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      カメラ定数バッファのGPU仮想アドレスを取得します.
    //-------------------------------------------------------------------------
    D3D12_GPU_VIRTUAL_ADDRESS GetBufferAddress() const;

    //-------------------------------------------------------------------------
    //! @brief      ビュー行列を取得します.
    //! 
    //! @return     ビュー行列を返却します.
    //-------------------------------------------------------------------------
    const Matrix& GetView() const;

    //-------------------------------------------------------------------------
    //! @brief      射影行列を取得します.
    //! 
    //! @return     射影行列を返却します.
    //-------------------------------------------------------------------------
    const Matrix& GetProj() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature> m_RootSignature;
    RefPtr<ID3D12PipelineState> m_OpaqueState;
    RefPtr<ID3D12PipelineState> m_TranslucentState;
    RefPtr<ID3D12PipelineState> m_WireframeState;
    RefPtr<ID3D12Resource>      m_CameraBuffer;
    AllocationHolder            m_CameraBufferAllocation;
    uint8_t                     m_BufferIndex = 0;
    Matrix                      m_View;
    Matrix                      m_Proj;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

