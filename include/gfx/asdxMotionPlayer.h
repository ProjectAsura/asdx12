namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class Model;
class MotionPlayer;


///////////////////////////////////////////////////////////////////////////////
// IMotionEventListener interface
///////////////////////////////////////////////////////////////////////////////
struct IMotionEventListener
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~IMotionEventListener()
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      コールバック時の処理です.
    //! 
    //! @param[in]      player      対象のモーションプレイヤー.
    //-------------------------------------------------------------------------
    virtual void OnExecute(MotionPlayer& player) = 0;
};

///////////////////////////////////////////////////////////////////////////////
// MotionUpdater
///////////////////////////////////////////////////////////////////////////////
class MotionUpdater
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MotionUpdater();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MotionUpdater();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      pModel      モデル.
    //! @param[in]      pClip       モーションクリップ.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const Model* pModel, const res::MotionClip* pClip);

    //-------------------------------------------------------------------------
    //! @brief      終了処理処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @retval true    再生が完了した
    //! @retval false   再生中.
    //-------------------------------------------------------------------------
    bool Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      トラックがあるかどうかチェックします.
    //! 
    //! @return     トラックがある場合は true を返却します.
    //-------------------------------------------------------------------------
    bool HasTrack(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      スケール値を取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     スケール値を返却します.
    //-------------------------------------------------------------------------
    Vector3 GetScaleKey(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      回転値を取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     回転値を返却します.
    //-------------------------------------------------------------------------
    Quaternion GetRotationKey(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      平行移動値を取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     平行移動値を返却します.
    //-------------------------------------------------------------------------
    Vector3 GetTranslationKey(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      現在時間を設定します.
    //! 
    //! @param[in]      value       設定する時間.
    //-------------------------------------------------------------------------
    void SetTimeInTicks(float value);

    //-------------------------------------------------------------------------
    //! @brief      再生速度を設定します.
    //! 
    //! @param[in]      value       再生速度.
    //-------------------------------------------------------------------------
    void SetPlaySpeed(float value);

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを設定します.
    //! 
    //! @param[in]      value       ループ再生する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetLoop(bool value);

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを設定します.
    //! 
    //! @param[in]      value       一時停止する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetPause(bool value);

    //-------------------------------------------------------------------------
    //! @brief      再生速度を取得します.
    //! 
    //! @return     再生速度を返却します.
    //-------------------------------------------------------------------------
    float GetPlaySpeed() const;

    //-------------------------------------------------------------------------
    //! @brief      現在時間を取得します.
    //! 
    //! @return     現在時間を返却します.
    //-------------------------------------------------------------------------
    float GetTimeInTicks() const;

    //-------------------------------------------------------------------------
    //! @brief      1秒あたりの Tick 数を取得します.
    //! 
    //! @return     1秒あたりの Tick 数を返却します.
    //-------------------------------------------------------------------------
    float GetTickPerSecond() const;

    //-------------------------------------------------------------------------
    //! @brief      再生所要時間を取得します.
    //! 
    //! @return     再生所要時間を返却します.
    //-------------------------------------------------------------------------
    float GetDuration() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを取得します.
    //! 
    //! @retval true    ループ再生です.
    //! @retval false   非ループ再生です.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを取得します.
    //! 
    //! @retval true    一時停止中です.
    //! @retval false   再生中です.
    //-------------------------------------------------------------------------
    bool IsPause() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    float   m_TimeInTicks = 0.0f;
    float   m_PlaySpeed   = 1.0f;
    bool    m_Loop        = true;
    bool    m_Pause       = false;

    const res::MotionClip*               m_pClip   = nullptr;
    std::vector<const res::MotionTrack*> m_pTracks = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};


///////////////////////////////////////////////////////////////////////////////
// MotionPlayer class
///////////////////////////////////////////////////////////////////////////////
class MotionPlayer
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MotionPlayer();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MotionPlayer();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      pModel      モデルです.
    //-------------------------------------------------------------------------
    void Init(const Model* pModel);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      クリップを設定します.
    //! 
    //! @param[in]      pClip       モーションクリップ.
    //-------------------------------------------------------------------------
    void SetClip(const res::MotionClip* pClip);

    //-------------------------------------------------------------------------
    //! @brief      次のクリップを設定します.
    //! 
    //! @param[in]      pClip               次のモーションクリップ.
    //! @param[in]      loop                ループ再生フラグ.
    //! @param[in]      transitionSec       遷移時間(単位:秒).
    //! @param[in]      timeInheritance     現在時間を次のクリップに引き継ぐ場合は true.
    //-------------------------------------------------------------------------
    void NextClip(
        const res::MotionClip*  pClip,
        bool                    loop,
        float                   transitionSec,
        bool                    timeInheritance = true);

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec            経過時間(秒).
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void Update(float deltaSec, const Transform3x4& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      ローカル変換行列を取得します.
    //! 
    //! @return     ローカル変換行列を返却します.
    //--------------------------------------------------------------------------
    const std::vector<Transform3x4>& GetLocalTransforms() const;

    //-------------------------------------------------------------------------
    //! @brief      ワールド変換行列を取得します.
    //!
    //! @return     ワールド変換行列を返却します.
    //-------------------------------------------------------------------------
    const std::vector<Transform3x4>& GetWorldTransforms() const;

    //-------------------------------------------------------------------------
    //! @brief      行列パレットを取得します.
    //! 
    //! @return     行列パレットを返却します.
    //-------------------------------------------------------------------------
    const std::vector<Transform3x4>& GetMatrixPalettes() const;

    //-------------------------------------------------------------------------
    //! @brief      現在の再生時間を取得します.
    //! 
    //! @return     現在の再生時間を返却します.
    //-------------------------------------------------------------------------
    float GetTimeInTicks() const;

    //-------------------------------------------------------------------------
    //! @brief      再生所要時間を取得します.
    //! 
    //! @return     再生所要時間を返却します.
    //-------------------------------------------------------------------------
    float GetDuration() const;

    //-------------------------------------------------------------------------
    //! @brief      1秒あたりのTick数を取得します.
    //! 
    //! @return     1秒あたりのTick数を返却します.
    //-------------------------------------------------------------------------
    float GetTicksPerSecond() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを取得します.
    //! 
    //! @return     ループ再生フラグを返却します.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを設定します.
    //! 
    //! @param[in]      value       ループ再生する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetLoop(bool value);

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを設定します.
    //! 
    //! @param[in]      value       設定する再生スピード.
    //-------------------------------------------------------------------------
    void SetPlaySpeed(float value);

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを取得します.
    //! 
    //! @return     再生スピードを返却します.
    //-------------------------------------------------------------------------
    float GetPlaySpeed() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを取得します.
    //! 
    //! @return     一時停止フラグを取得します.
    //-------------------------------------------------------------------------
    bool IsPause() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを設定します.
    //! 
    //! @param[in]      value       一時停止する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetPause(bool value);

    //-------------------------------------------------------------------------
    //! @brief       フレーム先頭に戻します.
    //-------------------------------------------------------------------------
    void Cue();

    //-------------------------------------------------------------------------
    //! @brief      1フレーム進めます.
    //! 
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void FrameAdvance(const Transform3x4& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      再生完了イベントリスナーを登録します.
    //! 
    //! @param[in]      listener        イベントリスナー.
    //-------------------------------------------------------------------------
    void AddFinishListener(IMotionEventListener* listener);

    //-------------------------------------------------------------------------
    //! @brief      再生完了イベントリスナーの登録を解除します.
    //! 
    //! @param[in]      listenr         イベントリスナー.
    //-------------------------------------------------------------------------
    void RemoveFinishListener(IMotionEventListener* listener);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    const Model*                m_pModel            = nullptr;
    std::vector<Transform3x4>   m_LocalTransforms   = {};
    std::vector<Transform3x4>   m_WorldTransforms   = {};
    std::vector<Transform3x4>   m_MatrixPalettes    = {};
    MotionUpdater               m_Updater[2]        = {};
    uint8_t                     m_CurrIndex         = 0;
    uint8_t                     m_NextIndex         = 1;
    float                       m_BlendDuration     = 0.0f;
    float                       m_BlendDelta        = 0.0f;
    bool                        m_Finish            = false;

    std::list<IMotionEventListener*> m_FinishListener = {};

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      ローカル変換行列を更新します.
    //-------------------------------------------------------------------------
    void UpdateLocalTransform(bool blend);

    //-------------------------------------------------------------------------
    //! @brief      ワールド変換行列を更新します.
    //! 
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void UpdateWorldTransform(const Transform3x4& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      行列パレットを更新します.
    //-------------------------------------------------------------------------
    void UpdateMatrixPalette();
};

} // namespace asdx
