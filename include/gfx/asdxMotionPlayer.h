#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <res/asdxResMotion.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class Model;


///////////////////////////////////////////////////////////////////////////////
// MotionPlayer class
///////////////////////////////////////////////////////////////////////////////
class MotionPlayer
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MotionPlayer();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MotionPlayer();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      pModel      モデルです.
    //-------------------------------------------------------------------------
    void Init(const Model* pModel);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      クリップを設定します.
    //! 
    //! @param[in]      pClip       モーションクリップ.
    //-------------------------------------------------------------------------
    void SetClip(const res::MotionClip* pClip);

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec            経過時間(秒).
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void Update(float deltaSec, const Matrix& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      ローカル変換行列を取得します.
    //! 
    //! @return     ローカル変換行列を返却します.
    //--------------------------------------------------------------------------
    const std::vector<Matrix>& GetLocalTransforms() const;

    //-------------------------------------------------------------------------
    //! @brief      ワールド変換行列を取得します.
    //!
    //! @return     ワールド変換行列を返却します.
    //-------------------------------------------------------------------------
    const std::vector<Matrix>& GetWorldTransforms() const;

    //-------------------------------------------------------------------------
    //! @brief      行列パレットを取得します.
    //! 
    //! @return     行列パレットを返却します.
    //-------------------------------------------------------------------------
    const std::vector<Matrix>& GetMatrixPalettes() const;

    //-------------------------------------------------------------------------
    //! @brief      現在の再生時間を取得します.
    //! 
    //! @return     現在の再生時間を返却します.
    //-------------------------------------------------------------------------
    float GetTimeInTicks() const;

    //-------------------------------------------------------------------------
    //! @brief      再生所要時間を取得します.
    //! 
    //! @return     再生所要時間を返却します.
    //-------------------------------------------------------------------------
    float GetDuration() const;

    //-------------------------------------------------------------------------
    //! @brief      1秒あたりのTick数を取得します.
    //! 
    //! @return     1秒あたりのTick数を返却します.
    //-------------------------------------------------------------------------
    float GetTicksPerSecond() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを取得します.
    //! 
    //! @return     ループ再生フラグを返却します.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生フラグを設定します.
    //! 
    //! @param[in]      value       ループ再生する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetLoop(bool value);

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを設定します.
    //! 
    //! @param[in]      value       設定する再生スピード.
    //-------------------------------------------------------------------------
    void SetPlaySpeed(float value);

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを取得します.
    //! 
    //! @return     再生スピードを返却します.
    //-------------------------------------------------------------------------
    float GetPlaySpeed() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを取得します.
    //! 
    //! @return     一時停止フラグを取得します.
    //-------------------------------------------------------------------------
    bool IsPause() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを設定します.
    //! 
    //! @param[in]      value       一時停止する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetPause(bool value);

    //-------------------------------------------------------------------------
    //! @brief       フレーム先頭に戻します.
    //-------------------------------------------------------------------------
    void Cue();

    //-------------------------------------------------------------------------
    //! @brief      1フレーム進めます.
    //! 
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void FrameAdvance(const Matrix& rootTransform);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    const Model*            m_pModel            = nullptr;
    float                   m_TimeInTicks       = 0.0f;
    const res::MotionClip*  m_pMotionClip       = nullptr;
    std::vector<Matrix>     m_LocalTransforms   = {};
    std::vector<Matrix>     m_WorldTransforms   = {};
    std::vector<Matrix>     m_MatrixPalettes    = {};
    bool                    m_Loop              = true;
    float                   m_PlaySpeed         = 1.0f;
    bool                    m_Pause             = false;

    std::vector<const res::MotionTrack*> m_Tracks = {};

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      ローカル変換行列を更新します.
    //! 
    //! @param[in]      deltaSec            経過時間(秒).
    //-------------------------------------------------------------------------
    void UpdateLocalTransform(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      ワールド変換行列を更新します.
    //! 
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void UpdateWorldTransform(const Matrix& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      行列パレットを更新します.
    //--------------------------------------------------------------------------
    void UpdateMatrixPalette();
};

} // namespace asdx
