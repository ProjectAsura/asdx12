#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <res/asdxResMotion.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class Model;


///////////////////////////////////////////////////////////////////////////////
// MotionPlayer class
///////////////////////////////////////////////////////////////////////////////
class MotionPlayer
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MotionPlayer();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MotionPlayer();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      pModel      モデルです.
    //-------------------------------------------------------------------------
    void Init(const Model* pModel);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      クリップを設定します.
    //! 
    //! @param[in]      pClip       モーションクリップ.
    //-------------------------------------------------------------------------
    void SetClip(const res::MotionClip* pClip);

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec            経過時間(秒).
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void Update(float deltaSec, const Matrix& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      ローカル変換行列を取得します.
    //! 
    //! @return     ローカル変換行列を返却します.
    //--------------------------------------------------------------------------
    const std::vector<Matrix>& GetLocalTransforms() const;

    //-------------------------------------------------------------------------
    //! @brief      ワールド変換行列を取得します.
    //!
    //! @return     ワールド変換行列を返却します.
    //-------------------------------------------------------------------------
    const std::vector<Matrix>& GetWorldTransforms() const;

    //-------------------------------------------------------------------------
    //! @brief      行列パレットを取得します.
    //! 
    //! @return     行列パレットを返却します.
    //--------------------------------------------------------------------------
    const std::vector<Matrix>& GetMatrixPalettes() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    const Model*            m_pModel            = nullptr;
    float                   m_CurrentTime       = 0.0f;
    const res::MotionClip*  m_pMotionClip       = nullptr;
    std::vector<uint32_t>   m_TrackIds          = {};
    std::vector<Matrix>     m_LocalTransforms   = {};
    std::vector<Matrix>     m_WorldTransforms   = {};
    std::vector<Matrix>     m_MatrixPalettes    = {};

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      ローカル変換行列を更新します.
    //! 
    //! @param[in]      deltaSec            経過時間(秒).
    //-------------------------------------------------------------------------
    void UpdateLocalTransform(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      ワールド変換行列を更新します.
    //! 
    //! @param[in]      rootTransform       ルート変換行列.
    //-------------------------------------------------------------------------
    void UpdateWorldTransform(const Matrix& rootTransform);

    //-------------------------------------------------------------------------
    //! @brief      行列パレットを更新します.
    //--------------------------------------------------------------------------
    void UpdateMatrixPalette();
};

} // namespace asdx
