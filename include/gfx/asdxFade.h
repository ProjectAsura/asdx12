#pragma once

//-----------------------------------------------------------------------------
// Include
//-----------------------------------------------------------------------------
#include <d3d12.h>
#include <fnd/asdxRef.h>
#include <fnd/asdxMath.h>
#include <gfx/asdxTexture.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Fade class
///////////////////////////////////////////////////////////////////////////////
class Fade
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングルトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static Fade& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリストです.
    //! @param[in]      rtvFormat   レンダーターゲットフォーマットです.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(ID3D12GraphicsCommandList* pCmd, DXGI_FORMAT rtvFormat);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec    差分時間(秒)です.
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      描画処理を行います.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリストです.
    //! @param[in]      handleSRV   テクスチャハンドルです.
    //-------------------------------------------------------------------------
    void Draw(ID3D12GraphicsCommandList* pCmd, D3D12_GPU_DESCRIPTOR_HANDLE handleSRV);

    //-------------------------------------------------------------------------
    //! @brief      描画処理を行います.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリストです.
    //-------------------------------------------------------------------------
    void Draw(ID3D12GraphicsCommandList* pCmd);

    //-------------------------------------------------------------------------
    //! @brief      カラー0を設定します.
    //! 
    //! @param[in]      value       設定するカラーです.
    //-------------------------------------------------------------------------
    void SetColor0(const asdx::Vector4& value);

    //-------------------------------------------------------------------------
    //! @brief      カラー1を設定します.
    //! 
    //! @param[in]      value       設定するカラーです.
    //-------------------------------------------------------------------------
    void SetColor1(const asdx::Vector4& value);

    //-------------------------------------------------------------------------
    //! @brief      切り替え時間を設定します.
    //! 
    //! @param[in]      value       切り替え時間(秒)
    //-------------------------------------------------------------------------
    void SetChangeSec(float value);

    //-------------------------------------------------------------------------
    //! @brief      カラー0を取得します.
    //! 
    //! @return     カラー0を返却します.
    //-------------------------------------------------------------------------
    const asdx::Vector4& GetColor0() const;

    //-------------------------------------------------------------------------
    //! @brief      カラー1を取得します.
    //! 
    //! @return     カラー1を返却します.
    //-------------------------------------------------------------------------
    const asdx::Vector4& GetColor1() const;

    //-------------------------------------------------------------------------
    //! @brief      切り替え時間を取得します.
    //! 
    //! @return     切り替え時間を返却します.
    //-------------------------------------------------------------------------
    float GetChangeSec() const;

    //-------------------------------------------------------------------------
    //! @brief      ステートをリセットします.
    //-------------------------------------------------------------------------
    void ResetState();

    //-------------------------------------------------------------------------
    //! @brief      完了済みかどうかチェックします.
    //! 
    //! @retval true    完了済みです.
    //! @retval false   未完了です.
    //-------------------------------------------------------------------------
    bool IsComplete() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static Fade                 s_Instance;         //!< シングルトンインスタンスです.
    RefPtr<ID3D12RootSignature> m_RootSig;          //!< ルートシグニチャです.
    RefPtr<ID3D12PipelineState> m_PipelineState;    //!< パイプラインステートです.
    Texture                     m_WhiteTexture;     //!< テクスチャ.
    asdx::Vector4               m_Color0;           //!< カラー0です.
    asdx::Vector4               m_Color1;           //!< カラー1です.
    float                       m_ChangeSec;        //!< 切り替え時間(秒)です.
    float                       m_ElapsedSec;       //!< 経過時間(秒)です.
    bool                        m_Complete;         //!< 完了フラグ.

    //========================================================================
    // private methods.
    //========================================================================

    //------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //------------------------------------------------------------------------
    Fade();

    //------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //------------------------------------------------------------------------
    ~Fade();

    Fade             (const Fade&) = delete;
    Fade& operator = (const Fade&) = delete;
};

} // namespace asdx
