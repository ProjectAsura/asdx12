#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <unordered_map>
#include <fnd/asdxRef.h>
#include <fnd/asdxList.h>
#include <res/asdxResMesh.h>
#include <res/asdxResModel.h>
#include <gfx/asdxMesh.h>
#include <gfx/asdxMaterial.h>
#include <gfx/asdxSkeleton.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Model class
///////////////////////////////////////////////////////////////////////////////
class Model final : public IReference
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
     //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      生成処理を行います.
    //! 
    //! @param[in]      res         モデルリソース.
    //! @param[out]     ppModel     モデルの格納先.
    //! @retval true    生成に成功.
    //! @retval false   生成に失敗.
    //-------------------------------------------------------------------------
    static bool Create(const ResModel& res, Model** ppModel);

    //-------------------------------------------------------------------------
    //! @brief      参照カウントを上げます.
    //-------------------------------------------------------------------------
    void AddRef() override;

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //-------------------------------------------------------------------------
    void Release() override;

    //-------------------------------------------------------------------------
    //! @brief      参照カウントを取得します.
    //! 
    //! @return     参照カウントを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetRefCount() const override;

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    size_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリアル数を返却します.
    //-------------------------------------------------------------------------
    size_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュインスタンス数を取得します.
    //! 
    //! @return     メッシュインスタンス数を返却します.
    //-------------------------------------------------------------------------
    size_t GetMeshInstanceCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを取得します.
    //! 
    //! @param[in]      index       メッシュ番号.
    //! @return     メッシュを返却します.
    //-------------------------------------------------------------------------
    const Mesh& GetMesh(size_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル名を取得します.
    //! 
    //! @param[in]      index       マテリアル番号.
    //! @return     マテリアル名を返却します.
    //-------------------------------------------------------------------------
    const String& GetMaterial(size_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      スケルトンを取得します.
    //! 
    //! @return     スケルトンを返却します.
    //-------------------------------------------------------------------------
    const Skeleton& GetSkeleton() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュインタンスを取得します.
    //! 
    //! @param[in]      index       メッシュインスタンス番号.
    //! @return     メッシュインタンスを返却します.
    //-------------------------------------------------------------------------
    ResMeshInstance GetMeshInstance(size_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを検索します.
    //! 
    //! @param[in]      name        メッシュ名.
    //! @param[out]     index       メッシュ番号.
    //! @retval true    検索に成功.
    //! @retval false   検索に失敗.
    //-------------------------------------------------------------------------
    bool FindMesh(const char* name, size_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル名を検索します.
    //! 
    //! @param[in]      name        マテリアル名.
    //! @retval true    検索に成功.
    //! @retval false   検索に失敗.
    //-------------------------------------------------------------------------
    bool FindMaterial(const char* name, size_t& index) const;

private:
    ///////////////////////////////////////////////////////////////////////////
    // MeshInstance structure
    ///////////////////////////////////////////////////////////////////////////
    struct MeshInstance
    {
        std::vector<uint32_t>   Meshes;
        std::vector<Matrix4x3>  Transforms;
    };

    //=========================================================================
    // private variables.
    //=========================================================================
    std::atomic<uint32_t>       m_RefCount = {};
    std::vector<Mesh>           m_Meshes;
    std::vector<String>         m_Materials;
    std::vector<MeshInstance>   m_MeshInstances;
    Skeleton                    m_Skeleton;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Model();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Model();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      res        モデルリソース.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const ResModel& res);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    Model             (const Model&) = delete;
    Model& operator = (const Model&) = delete;
};

} // namespace asdx
