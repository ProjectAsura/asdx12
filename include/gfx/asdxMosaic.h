///////////////////////////////////////////////////////////////////////////////
// MosaicCS class
///////////////////////////////////////////////////////////////////////////////
class MosaicCS
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Param structure
    ///////////////////////////////////////////////////////////////////////////
    struct Param
    {
        D3D12_GPU_DESCRIPTOR_HANDLE HandleSRV   = {};
        D3D12_GPU_DESCRIPTOR_HANDLE HandleUAV   = {};
        uint32_t                    SrvWidth    = 0;
        uint32_t                    SrvHeight   = 0;
        uint32_t                    UavWidth    = 0;
        uint32_t                    UavHeight   = 0;
        float                       Scale       = 1.0f;
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    MosaicCS();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~MosaicCS();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      コンピュートシェーダを用いてエフェクトを適用します.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリストです.
    //! @param[in]      param       パラメータです.
    //-------------------------------------------------------------------------
    void Dispatch(ID3D12GraphicsCommandList* pCmd, const Param& param);

    //-------------------------------------------------------------------------
    //! @brief      ルートシグニチャを取得します.
    //! 
    //! @return     ルートシグニチャを返却します.
    //-------------------------------------------------------------------------
    ID3D12RootSignature* GetRootSignature() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature> m_RootSignature;
    RefPtr<ID3D12PipelineState> m_PipelineState;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};


