///////////////////////////////////////////////////////////////////////////////
// TARGET_FLAGS enum
///////////////////////////////////////////////////////////////////////////////
enum TARGET_FLAGS
{
    TARGET_FLAG_NONE                = 0,            //!< フラグ設定なし.
    TARGET_FLAG_CREATE_MIP_RTV      = 0x1 << 0,     //!< RTVに対して各ミップごとのディスクリプタを生成する.
    TARGET_FLAG_CREATE_MIP_DSV      = 0x1 << 1,     //!< DSVに対して各ミップごとのディスクリプタを生成する.
    TARGET_FLAG_CREATE_MIP_UAV      = 0x1 << 2,     //!< UAVに対して各ミップごとのディスクリプタを生成する.
    TARGET_FLAG_NO_SRV              = 0x1 << 3,     //!< SRVを作成しない.
    TARGET_FLAG_ALIASING_RESOURCE   = 0x1 << 4,     //!< エイリアシングリソースとして作成します.
    TARGET_FLAG_ALLOW_RTV           = 0x1 << 5,     //!< RTVを許可します (TARGET_FLAG_ALIASING_RESOURCE 有効時のみ).
    TARGET_FLAG_ALLOW_DSV           = 0x1 << 6,     //!< DSVを許可します (TARGET_FLAG_ALIASING_RESOURCE 有効時のみ).
    TARGET_FLAG_ALLOW_UAV           = 0x1 << 7,     //!< UAVを許可します (TARGET_FLAG_ALIASING_RESOURCE 有効時のみ).
};

///////////////////////////////////////////////////////////////////////////////
// TargetDesc2D structure
///////////////////////////////////////////////////////////////////////////////
struct TargetDesc
{
    D3D12_RESOURCE_DIMENSION    Dimension           = D3D12_RESOURCE_DIMENSION_UNKNOWN;     //!< 次元です.
    uint64_t                    Alignment           = 0;                                    //!< アライメントです.
    uint64_t                    Width               = 0;                                    //!< 横幅です.
    uint32_t                    Height              = 1;                                    //!< 縦幅です.
    uint16_t                    DepthOrArraySize    = 1;                                    //!< 奥行 または 配列サイズです.
    uint16_t                    MipLevels           = 1;                                    //!< ミップレベル数です.
    DXGI_FORMAT                 Format              = DXGI_FORMAT_UNKNOWN;                  //!< フォーマットです.
    DXGI_SAMPLE_DESC            SampleDesc          = { 1, 0 };                             //!< サンプル設定です.
    D3D12_RESOURCE_STATES       InitState           = D3D12_RESOURCE_STATE_COMMON;          //!< 初期ステート.
    uint32_t                    Flags               = TARGET_FLAG_NONE;                     //!< ターゲットフラグです.
    uint64_t                    HeapSize            = 0;
    uint64_t                    HeapOffset          = 0;
};

///////////////////////////////////////////////////////////////////////////////
// BaseTarget class
///////////////////////////////////////////////////////////////////////////////
class BaseTarget
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend class ColorTarget;
    friend class DepthTarget;
    friend class ComputeTarget;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    BaseTarget() = default;

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    virtual ~BaseTarget();

    //-------------------------------------------------------------------------
    //! @brief      リソースを取得します.
    //!
    //! @return     リソースを返却します.
    //-------------------------------------------------------------------------
    ID3D12Resource* GetResource() const;

    //-------------------------------------------------------------------------
    //! @brief      構成設定を取得します.
    //!
    //! @return     構成設定を返却します.
    //-------------------------------------------------------------------------
    TargetDesc GetDesc() const;

    //-------------------------------------------------------------------------
    //! @brief      デバッグ名を設定します.
    //!
    //! @param[in]      tag     タグ名.
    //-------------------------------------------------------------------------
    void SetName(LPCWSTR tag);

#if ASDX_ENABLE_SINGLE_THREAD
    //-------------------------------------------------------------------------
    //! @brief      ステート遷移を行います.
    //! 
    //! @param[in]      pCmdList    コマンドリスト.
    //! @param[in]      nextState   遷移後のステート.
    //-------------------------------------------------------------------------
    void ChangeState(ID3D12GraphicsCommandList* pCmdList, D3D12_RESOURCE_STATES nextState)
    {
        if (nextState == m_PrevState)
        { return; }

        D3D12_RESOURCE_BARRIER barrier = {};
        barrier.Type                    = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
        barrier.Transition.pResource    = m_pResource.GetPtr();
        barrier.Transition.Subresource  = 0;
        barrier.Transition.StateBefore  = m_PrevState;
        barrier.Transition.StateAfter   = nextState;

        pCmdList->ResourceBarrier(1, &barrier);

        m_PrevState = nextState;
    }

    //-------------------------------------------------------------------------
    //! @brief      ステートを取得します.
    //! 
    //! @return     ステートを返却します.
    //-------------------------------------------------------------------------
    D3D12_RESOURCE_STATES GetState() const { return m_PrevState; }
#endif

protected:
    //=========================================================================
    // protected variables.
    //=========================================================================
    RefPtr<ID3D12Resource>          m_pResource;
    RefPtr<ID3D12Heap>              m_pHeap;
    AllocationHolder                m_HolderAlloc;
    TargetDesc                      m_Desc;
    D3D12_RESOURCE_STATES           m_PrevState = D3D12_RESOURCE_STATE_COMMON;

    //=========================================================================
    // protected methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// ColorTarget class
///////////////////////////////////////////////////////////////////////////////
class ColorTarget final : public BaseTarget
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ColorTarget();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ColorTarget();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //!
    //! @param[in]      pDesc       構成設定です.
    //! @retval true    初期化成功.
    //! @retval false   初期化失敗.
    //-------------------------------------------------------------------------
    bool Init(const TargetDesc* pDesc);

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //!
    //! @param[in]      pSwapChain          スワップチェインです.
    //! @param[in]      backbufferIndex     バックバッファ番号です.
    //! @param[in]      sRGB                sRGBが適用可能な場合にsRGBフォーマットにする場合は true.
    //! @retval true    初期化成功.
    //! @retval false   初期化失敗.
    //-------------------------------------------------------------------------
    bool Init(IDXGISwapChain* pSwapChain, uint32_t backbufferIndex, bool sRGB);

    //-------------------------------------------------------------------------
    //! @brief      エイリアシングリソースとして初期化します.
    //! 
    //! @param[in]      pDesc       構成設定です.
    //! @param[in]      target      ベースターゲット.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool InitAliasing(const TargetDesc* pDesc, const BaseTarget& target);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      リサイズ処理を行います.
    //! 
    //! @param[in]      width       横幅
    //! @param[in]      height      縦幅.
    //! @retval true    リサイズに成功.
    //! @retval false   リサイズに失敗.
    //-------------------------------------------------------------------------
    bool Resize(uint32_t width, uint32_t height);

    //-------------------------------------------------------------------------
    //! @brief      CPUディスクリプタハンドルを取得します(RTV用).
    //! 
    //! @return     CPUディスクリプタハンドルを返却します(RTV用).
    //-------------------------------------------------------------------------
    D3D12_CPU_DESCRIPTOR_HANDLE GetCpuHandleRTV(uint32_t index = 0) const;

    //-------------------------------------------------------------------------
    //! @brief      バインドレスインデックスを取得します(SRV用).
    //!
    //! @return     バインドレスインデックスを返却します(SRV用).
    //-------------------------------------------------------------------------
    uint32_t GetBindlessIndexSRV() const;

    //-------------------------------------------------------------------------
    //! @brief      CPUディスクリプタハンドルを取得します(SRV用).
    //! 
    //! @return     CPUディスクリプタハンドルを返却します(SRV用).
    //-------------------------------------------------------------------------
    D3D12_CPU_DESCRIPTOR_HANDLE GetCpuHandleSRV() const;

    //-------------------------------------------------------------------------
    //! @brief      GPUディスクリプタハンドルを取得します(SRV用).
    //! 
    //! @return     GPUディスクリプタハンドルを返却します(SRV用).
    //-------------------------------------------------------------------------
    D3D12_GPU_DESCRIPTOR_HANDLE GetGpuHandleSRV() const;

    //-------------------------------------------------------------------------
    //! @brief      sRGBフラグを取得します.
    //! 
    //! @return     sRGBフラグを返却します.
    //-------------------------------------------------------------------------
    bool IsSRGB() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<DescriptorHolder>   m_HolderRTV;
    DescriptorHolder                m_HolderSRV;

    //=========================================================================
    // private methods.
    //=========================================================================
 
    //-------------------------------------------------------------------------
    //! @brief      ビューの初期化を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool InitView();
};


