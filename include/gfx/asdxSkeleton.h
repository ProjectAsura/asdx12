#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <vector>
#include <fnd/asdxString.h>
#include <res/asdxResBone.h>


namespace asdx {

class ModelBinary;

///////////////////////////////////////////////////////////////////////////////
// Skeleton class
///////////////////////////////////////////////////////////////////////////////
class Skeleton
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Skeleton();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Skeleton();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      bones       ボーン配列.
    //-------------------------------------------------------------------------
    void Init(const ArrayView<ResBone>& bones);

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      binary      binary
    //-------------------------------------------------------------------------
    void Init(const ModelBinary& binary);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      ボーンを持つかどうかチェックします.
    //! 
    //! @retval true    ボーンを持ちます.
    //! @retval false   ボーンを持ちません.
    //-------------------------------------------------------------------------
    bool HasBone() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    size_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     ボーンを返却します.
    //-------------------------------------------------------------------------
    ResBone GetBone(size_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン名を検索します.
    //! 
    //! @param[in]      name        ボーン名.
    //! @param[out]     index       ボーン番号.
    //! @retval true    検索に成功.
    //! @retval false   検索に失敗.
    //-------------------------------------------------------------------------
    bool FindBone(const char* name, size_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン名を検索します.
    //! 
    //! @param[in]      hash        ボーン名ハッシュ.
    //! @param[out]     index       ボーン番号.
    //! @retval true    検索に成功.
    //! @retval false   検索に失敗.
    //-------------------------------------------------------------------------
    bool FindBone(uint64_t hash, size_t& index) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<uint64_t>               m_Hashes;           //!< ボーン名ハッシュ.
    std::vector<BoneId>                 m_Parents;          //!< 親ボーンID.
    std::vector<Matrix4x3>              m_BindPoses;        //!< バインドポーズ行列.
    std::vector<Matrix4x3>              m_InvBindPoses;     //!< 逆バインドポーズ行列.
    std::vector<std::vector<BoneId>>    m_Children;         //!< 子ボーンID.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
