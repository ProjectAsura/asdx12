#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <d3d12.h>
#include <fnd/asdxRef.h>
#include <fnd/asdxMath.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ColorCorrectionEffect class
///////////////////////////////////////////////////////////////////////////////
class ColorCorrectionEffect
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ColorCorrectionEffect();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ColorCorrectionEffect();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      rtvFormat       レンダーターゲットビューのフォーマット.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(DXGI_FORMAT rtvFormat);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      描画処理を行います.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      handleSRV   入力SRV
    //-------------------------------------------------------------------------
    void Draw(ID3D12GraphicsCommandList* pCmd, D3D12_GPU_DESCRIPTOR_HANDLE handleSRV);

    //-------------------------------------------------------------------------
    //! @brief      コンピュートシェーダを起動します
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      width       UAVの横幅.
    //! @param[in]      height      UAVの縦幅.
    //! @param[in]      handleUAV   出力先UAV.
    //! @param[in]      handleSRV   入力SRV.
    //-------------------------------------------------------------------------
    void Dispatch(
        ID3D12GraphicsCommandList*  pCmd,
        uint32_t                    width,
        uint32_t                    height,
        D3D12_GPU_DESCRIPTOR_HANDLE handleUAV,
        D3D12_GPU_DESCRIPTOR_HANDLE handleSRV);

    //-------------------------------------------------------------------------
    //! @brief      明度調整値を設定します.
    //-------------------------------------------------------------------------
    void SetBrightness(float value);

    //-------------------------------------------------------------------------
    //! @brief      彩度調整値を設定します.
    //-------------------------------------------------------------------------
    void SetSaturation(float value);

    //-------------------------------------------------------------------------
    //! @brief      彩度調整値を設定します.
    //-------------------------------------------------------------------------
    void SetSaturation(const Vector3& value);

    //-------------------------------------------------------------------------
    //! @brief      コントラスト調整値を設定します.
    //-------------------------------------------------------------------------
    void SetContrast(float value);

    //-------------------------------------------------------------------------
    //! @brief      色相調整値を設定します.
    //-------------------------------------------------------------------------
    void SetHueDegree(float value);

    //-------------------------------------------------------------------------
    //! @brief      セピアトーン調整値を設定します.
    //-------------------------------------------------------------------------
    void SetSepiaTone(float value);

    //-------------------------------------------------------------------------
    //! @brief      グレースケール調整値を設定します.
    //-------------------------------------------------------------------------
    void SetGrayScale(float value);

    //-------------------------------------------------------------------------
    //! @brief      色反転フラグを設定します.
    //-------------------------------------------------------------------------
    void SetReverse(bool value);

    //-------------------------------------------------------------------------
    //! @brief      明度調整値を取得します.
    //-------------------------------------------------------------------------
    float GetBrightness() const;

    //-------------------------------------------------------------------------
    //! @brief      彩度調整値を取得します.
    //-------------------------------------------------------------------------
    const Vector3& GetSaturation() const;

    //-------------------------------------------------------------------------
    //! @brief      コントラスト調整値を取得します
    //-------------------------------------------------------------------------
    float GetContrast() const;

    //-------------------------------------------------------------------------
    //! @brief      色相調整値を取得します.
    //-------------------------------------------------------------------------
    float GetHueDegree() const;

    //-------------------------------------------------------------------------
    //! @brief      セピアトーン調整値を取得します.
    //-------------------------------------------------------------------------
    float GetSepiaTone() const;

    //-------------------------------------------------------------------------
    //! @brief      グレースケール調整値を取得します.
    //-------------------------------------------------------------------------
    float GetGrayScale() const;

    //-------------------------------------------------------------------------
    //! @brief      色反転フラグを取得します.
    //-------------------------------------------------------------------------
    bool IsReverse() const;

    //-------------------------------------------------------------------------
    //! @brief      調整値をリセットします.
    //-------------------------------------------------------------------------
    void ResetValues();

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature> m_RootSignature;
    RefPtr<ID3D12PipelineState> m_GraphicsPSO;
    RefPtr<ID3D12PipelineState> m_ComputePSO;
    Vector3                     m_Saturation    = Vector3(1.0f, 1.0f, 1.0f);
    Vector3                     m_AddColor      = Vector3(0.0f, 0.0f, 0.0f);
    Vector3                     m_MulColor      = Vector3(1.0f, 1.0f, 1.0f);
    float                       m_Brightness    = 1.0f;
    float                       m_Contrast      = 1.0f;
    float                       m_HueDegree     = 0.0f;
    float                       m_SepiaTone     = 0.0f;
    float                       m_GrayScale     = 0.0f;
    bool                        m_Reverse       = false;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      カラー行列を計算します.
    //! 
    //! @return     カラー行列を返却します.
    //-------------------------------------------------------------------------
    Matrix CalcColorMatrix() const;
};

} // namespace asdx
