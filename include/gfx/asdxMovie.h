    //-------------------------------------------------------------------------
    //! @brief      総フレーム数を取得します.
    //! 
    //! @return     総フレーム数を返却します.
    //-------------------------------------------------------------------------
    uint64_t GetFrameCount() const;

    //-------------------------------------------------------------------------
    //! @brief      現在のフレーム番号を取得します.
    //! 
    //! @return     現在のフレーム番号を返却します.
    //-------------------------------------------------------------------------
    uint64_t GetFrameIndex() const;

    //-------------------------------------------------------------------------
    //! @brief      再生の一時停止を設定します.
    //! 
    //! @param[in]      pause       一時停止する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetPause(bool puase);

    //-------------------------------------------------------------------------
    //! @brief      ループ再生設定を行います.
    //! 
    //! @param[in]      loop        ループ再生を行う場合は true を指定.
    //! @note       ループ再生を有効にした場合は, IsFinished() メソッドは true を返さなくなるので注意してください.
    //-------------------------------------------------------------------------
    void SetLoop(bool loop);

    //-------------------------------------------------------------------------
    //! @brief      一時停止中かどうかチェックします.
    //! 
    //! @retval true    一時停止中です.
    //! @retval false   再生中です.
    //-------------------------------------------------------------------------
    bool IsPause() const;

    //-------------------------------------------------------------------------
    //! @brief      ループ再生設定かどうかチェックします.
    //! 
    //! @retval true    ループ再生です.
    //! @retval false   非ループ再生です.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      再生が終了したかどうかチェックします.
    //! 
    //! @retval true    完了状態です.
    //! @retval false   未完了状態です.
    //! @note       ループ再生設定が行われている場合，この関数は常に false を返却します.
    //-------------------------------------------------------------------------
    bool IsFinished() const;

private:
