#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <d3d12.h>
#include <fnd/asdxRef.h>
#include <fnd/asdxMath.h>
#include <gfx/asdxTarget.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// GaussianBlurEffect class
///////////////////////////////////////////////////////////////////////////////
class GaussianBlurEffect
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    GaussianBlurEffect();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~GaussianBlurEffect();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      width       横幅.
    //! @param[in]      height      縦幅.
    //! @param[in]      uavFormat   UAVフォーマットです.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(uint32_t width, uint32_t height, DXGI_FORMAT uavFormat);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      コンピュートシェーダを起動します.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      strength    ブラーの強さ.
    //-------------------------------------------------------------------------
    void Dispatch(
        ID3D12GraphicsCommandList*  pCmd,
        uint32_t                    srvWidth,
        uint32_t                    srvHeigh,
        D3D12_GPU_DESCRIPTOR_HANDLE handleSRV);

    //-------------------------------------------------------------------------
    //! @brief      GPUディスクリプタハンドルを取得します.
    //! 
    //! @return     GPUディスクリプタハンドルを返却します.
    //-------------------------------------------------------------------------
    D3D12_GPU_DESCRIPTOR_HANDLE GetHandleGPU() const;

    //-------------------------------------------------------------------------
    //! @brief      構成設定を取得します.
    //! 
    //! @return     構成設定を返却します.
    //-------------------------------------------------------------------------
    TargetDesc GetDesc() const;

    //-------------------------------------------------------------------------
    //! @brief      ターゲットをリサイズします.
    //! 
    //! @param[in]      width       横幅.
    //! @param[in]      height      縦幅.
    //! @retval true    リサイズに成功.
    //! @retval false   リサイズに失敗.
    //-------------------------------------------------------------------------
    bool Resize(uint32_t width, uint32_t height);

    //-------------------------------------------------------------------------
    //! @brief      ブラーの強さを設定します.
    //! 
    //! @param[in]      value       設定する値.
    //-------------------------------------------------------------------------
    void SetBlurStrength(float value);

    //-------------------------------------------------------------------------
    //! @brief      ブラーの強さを取得します.
    //! 
    //! @return     ブラーの強さを返却します.
    //-------------------------------------------------------------------------
    float GetBlurStrength() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature> m_RootSignature;
    RefPtr<ID3D12PipelineState> m_PipelineState;
    ComputeTarget               m_ComputeTarget[2];
    D3D12_RESOURCE_STATES       m_State = D3D12_RESOURCE_STATE_COMMON;
    float                       m_BlurStrength = 3.0f;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
