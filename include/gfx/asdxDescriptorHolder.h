#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <d3d12.h>
#include <fnd/asdxOffsetAllocator.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// DescriptorHolder class
///////////////////////////////////////////////////////////////////////////////
class DescriptorHolder
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // HEAP_TYPE enum
    ///////////////////////////////////////////////////////////////////////////
    enum HEAP_TYPE
    {
        HEAP_NONE,  //!< None.
        HEAP_RTV,   //!< Render Target View.
        HEAP_DSV,   //!< Depth Stencil View.
        HEAP_RES,   //!< Resource (CBV, SRV, UAV).
        HEAP_SMP,   //!< Sampler.
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    DescriptorHolder();

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //-------------------------------------------------------------------------
    explicit DescriptorHolder(HEAP_TYPE heapType, OffsetHandle handle);

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~DescriptorHolder();

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      CPUディスクリプタハンドルを取得します.
    //-------------------------------------------------------------------------
    D3D12_CPU_DESCRIPTOR_HANDLE GetHandleCPU(uint32_t offset = 0) const;

    //-------------------------------------------------------------------------
    //! @brief      GPUディスクリプタハンドルを取得します.
    //-------------------------------------------------------------------------
    D3D12_GPU_DESCRIPTOR_HANDLE GetHandleGPU(uint32_t offset = 0) const;

    //-------------------------------------------------------------------------
    //! @brief      バインドレス用インデックスを取得します.
    //-------------------------------------------------------------------------
    uint32_t GetIndex(uint32_t offset = 0) const;

    //-------------------------------------------------------------------------
    //! @brief      有効かどうか判定します.
    //-------------------------------------------------------------------------
    bool IsValid() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    HEAP_TYPE       m_HeapType = HEAP_NONE;
    OffsetHandle    m_Handle   = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx