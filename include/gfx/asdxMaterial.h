#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <vector>
#include <gfx/asdxBuffer.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Decalarations.
//-----------------------------------------------------------------------------
class Texture;


///////////////////////////////////////////////////////////////////////////////
// Material class
///////////////////////////////////////////////////////////////////////////////
class Material
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Material();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Material();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      bufferSize      定数バッファサイズ.
    //! @param[in]      textureCount    テクスチャ数.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(uint64_t bufferSize, uint32_t textureCount);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      定数バッファを取得します.
    //! 
    //! @return     定数バッファを返却します.
    //-------------------------------------------------------------------------
    ConstantBuffer& GetBuffer();

    //-------------------------------------------------------------------------
    //! @brief      定数バッファを取得します.
    //! 
    //! @return     定数バッファを返却します.
    //-------------------------------------------------------------------------
    const ConstantBuffer& GetBuffer() const;

    //-------------------------------------------------------------------------
    //! @brief      定数バッファのGPU仮想アドレスを取得します.
    //! 
    //! @return     定数バッファのGPU仮想アドレスを返却します.
    //-------------------------------------------------------------------------
    D3D12_GPU_VIRTUAL_ADDRESS GetGpuAddress() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャを設定します.
    //! 
    //! @param[in]      index       テクスチャ番号.
    //! @param[in]      pTexture    設定するテクスチャ.
    //-------------------------------------------------------------------------
    void SetTexture(uint32_t index, const Texture* pTexture);

    //-------------------------------------------------------------------------
    //! @brief      テクスチャ数を取得します.
    //! 
    //! @return     テクスチャ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTextureCount() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャを取得します.
    //! 
    //! @param[in]      index       テクスチャ番号.
    //! @return     テクスチャを返却します.
    //-------------------------------------------------------------------------
    const Texture* GetTexture(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      GPUディスクリプタハンドルを取得します.
    //! 
    //! @param[in]      index       テクスチャ番号.
    //! @return     GPUディスクリプタハンドルを返却します.
    //-------------------------------------------------------------------------
    D3D12_GPU_DESCRIPTOR_HANDLE GetGpuHandleSRV(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      バインドレスインデックスを取得します.
    //! 
    //! @param[in]      index       テクスチャ番号.
    //! @return     バインドレスインデックスを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBindlessIndexSRV(uint32_t index) const;

private:
    //=========================================================================
    // private variables;
    //=========================================================================
    ConstantBuffer              m_Buffer;       //!< 定数バッファ.
    std::vector<const Texture*> m_Textures;     //!< テクスチャリスト.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
