#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <vector>
#include <fnd/asdxRef.h>
#include <fnd/asdxString.h>
#include <res/asdxResMaterial.h>
#include <gfx/asdxBuffer.h>
#include <gfx/asdxTextureManager.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// Material class
///////////////////////////////////////////////////////////////////////////////
class Material final : public IReference
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを生成します.
    //! 
    //! @param[in]      desc            マテリアル設定です.
    //! @param[out]     ppMaterial      マテリアルの格納先.
    //! @retval true    生成に成功.
    //! @retval false   生成に失敗.
    //-------------------------------------------------------------------------
    static bool Create(const ResMaterial& res, Material** ppMaterial);

    //-------------------------------------------------------------------------
    //! @brief      参照カウンタを上げます.
    //-------------------------------------------------------------------------
    void AddRef() override;

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //-------------------------------------------------------------------------
    void Release() override;

    //-------------------------------------------------------------------------
    //! @brief      参照カウンタを取得します.
    //! 
    //! @return     参照カウンタを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetRefCount() const;

    //-------------------------------------------------------------------------
    //! @brief      シェーダ名を取得します.
    //! 
    //! @return     シェーダ名を返却します.
    //-------------------------------------------------------------------------
    StringView GetShader() const;

    //-------------------------------------------------------------------------
    //! @brief      定数バッファを取得します.
    //! 
    //! @return     定数バッファを返却します.
    //-------------------------------------------------------------------------
    const ConstantBuffer& GetBuffer() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャ数を取得します.
    //! 
    //! @return     テクスチャ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetTextureCount() const;

    //-------------------------------------------------------------------------
    //! @brief      テクスチャを取得します.
    //! 
    //! @param[in]      index       インデックス.
    //! @return     テクスチャを返却します.
    //-------------------------------------------------------------------------
    const TextureHolder& GetTexture(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      カリングモードを設定します.
    //! 
    //! @param[in]      value       設定するカリングモード.
    //-------------------------------------------------------------------------
    void SetCullMode(CullMode value);

    //-------------------------------------------------------------------------
    //! @brief      カリングモードを取得します.
    //! 
    //! @return     カリングモードを返却します.
    //-------------------------------------------------------------------------
    CullMode GetCullMode() const;

    //-------------------------------------------------------------------------
    //! @brief      アルファモードを取得します.
    //! 
    //! @param[in]      value       設定するアルファモード.
    //-------------------------------------------------------------------------
    void SetAlphaMode(AlphaMode value);

    //-------------------------------------------------------------------------
    //! @brief      アルファモードを取得します.
    //! 
    //! @return     アルファモードを返却します.
    //-------------------------------------------------------------------------
    AlphaMode GetAlphaMode() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::atomic<uint32_t>       m_RefCount  = {};                   //!< 参照カウンタ.
    String                      m_Shader;                           //!< シェーダ名です.
    ConstantBuffer              m_Buffer;                           //!< 定数バッファ.
    std::vector<TextureHolder>  m_Textures;                         //!< テクスチャ.
    AlphaMode                   m_AlphaMode = AlphaMode::Opaque;    //!< アルファモード.
    CullMode                    m_CullMode  = CullMode::Back;       //!< カルモード.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Material();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Material();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      res             リソースマテリアル.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const ResMaterial& res);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    Material             (const Material&) = delete;
    Material& operator = (const Material&) = delete;
};

} // namespace asdx
