#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <vector>
#include <list>
#include <d3d12.h>
#include <fnd/asdxOffsetAllocator.h>
#include <fnd/asdxRef.h>
#include <fnd/asdxSpinLock.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// DescriptorHeap class
///////////////////////////////////////////////////////////////////////////////
class DescriptorHeap final
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend class GraphicsSystem;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    DescriptorHeap();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~DescriptorHeap();

    //-------------------------------------------------------------------------
    //! @brief      ディスクリプタを割り当てます.
    //! 
    //! @param[in]      count       割り当てるディスクリプタ数です.
    //! @return     割り当てたディスクリプタのオフセットハンドルを返却します.
    //-------------------------------------------------------------------------
    OffsetHandle Alloc(uint32_t count);

    //-------------------------------------------------------------------------
    //! @brief      ディスクリプタを解放します.
    //! 
    //! @param[in]      handle      解放するディスクリプタのオフセットハンドルです.
    //-------------------------------------------------------------------------
    void Free(OffsetHandle& handle);

    //-------------------------------------------------------------------------
    //! @brief      CPUディスクリプタハンドルを取得します.
    //! 
    //! @param[in]      handle      オフセットハンドルです.
    //! @return     CPUディスクリプタハンドルを返却します.
    //-------------------------------------------------------------------------
    D3D12_CPU_DESCRIPTOR_HANDLE GetHandleCPU(const OffsetHandle& handle, uint32_t offset = 0) const;

    //-------------------------------------------------------------------------
    //! @brief      GPUディスクリプタハンドルを取得します.
    //!
    //! @param[in]      handle      オフセットハンドルです.
    //! @return     GPUディスクリプタハンドルを返却します.
    //-------------------------------------------------------------------------
    D3D12_GPU_DESCRIPTOR_HANDLE GetHandleGPU(const OffsetHandle& handle, uint32_t offset = 0) const;

    //-------------------------------------------------------------------------
    //! @brief      使用中のハンドル数を取得します.
    //! 
    //! @return     使用中のハンドル数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetUsedCount() const;

    //-------------------------------------------------------------------------
    //! @brief      使用可能なハンドル数を取得します.
    //! 
    //! @return     使用可能なハンドル数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetFreeCount() const;

    //-------------------------------------------------------------------------
    //! @brief      フレーム同期を行います.
    //-------------------------------------------------------------------------
    void FrameSync();

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12DescriptorHeap>            m_Heap;
    uint32_t                                m_IncrementSize = 0;
    ThreadSafeOffsetAllocator               m_Allocator;
    std::vector<std::list<OffsetHandle>>    m_DisposeList;
    SpinLock                                m_SpinLock;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      pDevice     デバイス.
    //! @param[in]      pDesc       ヒープの設定です.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(ID3D12Device* pDevice, const D3D12_DESCRIPTOR_HEAP_DESC* pDesc);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();
};

} // namespace asdx
