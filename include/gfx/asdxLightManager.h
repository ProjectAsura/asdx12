///////////////////////////////////////////////////////////////////////////////
// SpotLight class
///////////////////////////////////////////////////////////////////////////////
class SpotLight final
: public Light
, public List<SpotLight>::Node
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      lm          ライト強度(単位：ルーメン).
    //! @param[in]      innerAngle  内角(単位:ラジアン).
    //! @param[in]      outerAngle  外角(単位:ラジアン).
    //-------------------------------------------------------------------------
    explicit SpotLight(
        float lm         = 1520.0f,
        float innerAngle = ToRadian(30.0f),
        float outerAngle = ToRadian(60.0f));

    //-------------------------------------------------------------------------
    //! @brief      強度をカンデラ単位で取得します.
    //! 
    //! @return     強度を返却します(単位：カンデラ).
    //-------------------------------------------------------------------------
    float GetCandela() const;

    //-------------------------------------------------------------------------
    //! @brief      強度をルーメン単位で取得します.
    //! 
    //! @return     強度を返却します(単位：ルーメン).
    //-------------------------------------------------------------------------
    float GetLumen() const;

    //-------------------------------------------------------------------------
    //! @brief      内角を取得します.
    //! 
    //! @return     内角を返却します(単位：ラジアン).
    //-------------------------------------------------------------------------
    float GetInnerAngle() const;

    //-------------------------------------------------------------------------
    //! @brief      外角を取得します.
    //! 
    //! @return     外角を返却します(単位：ラジアン).
    //-------------------------------------------------------------------------
    float GetOuterAngle() const;

    //-------------------------------------------------------------------------
    //! @brief      内角を設定します.
    //! 
    //! @param[in]      rad     設定する角度(単位：ラジアン).
    //-------------------------------------------------------------------------
    void SetInnerAngle(float rad);

    //-------------------------------------------------------------------------
    //! @brief      外角を設定します.
    //! 
    //! @param[in]      rad     設定する角度(単位：ラジアン).
    //-------------------------------------------------------------------------
    void SetOuterAngle(float rad);

    //-------------------------------------------------------------------------
    //! @brief      強度をカンデラ単位で設定します.
    //! 
    //! @param[in]      cd      設定するカンデラ.
    //-------------------------------------------------------------------------
    void SetCandela(float cd);

    //-------------------------------------------------------------------------
    //! @brief      強度をルーメン単位で設定します.
    //! 
    //! @param[in]      lm      設定するルーメン.
    //-------------------------------------------------------------------------
    void SetLumen(float lm);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    float m_InnerAngle = ToRadian(30.0f);
    float m_OuterAngle = ToRadian(60.0f);

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      円錐角を有効範囲に収めます.
    //-------------------------------------------------------------------------
    void ValidateCone();
};

