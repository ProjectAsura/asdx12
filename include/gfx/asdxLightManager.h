///////////////////////////////////////////////////////////////////////////////
// PhotometricUnit enum
///////////////////////////////////////////////////////////////////////////////
enum PhotometricUnit : uint8_t
{
    Candela,    //!< カンデラ[cd]
    Lumen,      //!< ルーメン[lm]
    Lux,        //!< ルクス[lx]
};

///////////////////////////////////////////////////////////////////////////////
// LightType enum
///////////////////////////////////////////////////////////////////////////////
enum LightType : uint8_t
{
    Point,          //!< ポイントライト.
    Spot,           //!< スポットライト.
    Directional,    //!< ディレクショナルライト.
    ImageBased,     //!< イメージベースドライト.
};

///////////////////////////////////////////////////////////////////////////////
// Light class
///////////////////////////////////////////////////////////////////////////////
class Light
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~Light() = default;

    //-------------------------------------------------------------------------
    //! @brief      ライトタイプを取得します
    //!
    //! @return     ライトタイプを返却します.
    //-------------------------------------------------------------------------
    LightType GetType() const;

    //-------------------------------------------------------------------------
    //! @brief      測光単位を取得します.
    //! 
    //! @return     測光単位を返却します.
    //-------------------------------------------------------------------------
    PhotometricUnit GetUnit() const;

    //-------------------------------------------------------------------------
    //! @brief      カラーを設定します.
    //! 
    //! @param[in]      value       設定する色です.
    //-------------------------------------------------------------------------
    void SetColor(const Unorm3& value);

    //-------------------------------------------------------------------------
    //! @brief      カラーを取得します.
    //! 
    //! @return     カラーを返却します.
    //-------------------------------------------------------------------------
    const Unorm3& GetColor() const;

    //-------------------------------------------------------------------------
    //! @brief      強度を設定します.
    //! 
    //! @param[in]      value       設定する強度.
    //-------------------------------------------------------------------------
    void SetIntensity(float value);

    //-------------------------------------------------------------------------
    //! @brief      強度を取得します.
    //! 
    //! @return     強度を返却します.
    //-------------------------------------------------------------------------
    float GetIntensity() const;

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを設定します
    //! 
    //! @param[in]      value       シャドウを落とす場合は true を指定.
    //-------------------------------------------------------------------------
    void SetCastShadow(bool value);

    //-------------------------------------------------------------------------
    //! @brief      シャドウキャストフラグを取得します.
    //! 
    //! @retval true    シャドウを落とします.
    //! @retval false   シャドウ無し.
    //-------------------------------------------------------------------------
    bool IsCastShadow() const;

protected:
    //=========================================================================
    // protected variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // protected methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      type        ライトタイプ.
    //! @param[in]      unit        測光単位.
    //! @param[in]      intensity   強度.
    //-------------------------------------------------------------------------
    Light(LightType type, PhotometricUnit unit, float intensity);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    LightType           m_Type          = LightType::Point;
    PhotometricUnit     m_Unit          = PhotometricUnit::Lux;
    Unorm3              m_Color         = Unorm3(1.0f, 1.0f, 1.0f);
    float               m_Intensity     = 1.0f;
    bool                m_CastShadow    = false;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

