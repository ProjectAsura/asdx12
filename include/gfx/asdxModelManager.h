#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <unordered_map>
#include <fnd/asdxSpinLock.h>
#include <fnd/asdxResHolder.h>
#include <gfx/asdxModel.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class ModelManager;

//-----------------------------------------------------------------------------
// Type Alias
//-----------------------------------------------------------------------------
using ModelHolder = ResHolder<Model, ModelManager>;


///////////////////////////////////////////////////////////////////////////////
// ModelManager class
///////////////////////////////////////////////////////////////////////////////
class ModelManager
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static ModelManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功 または 初期化済み.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      モデルを生成または取得します.
    //! 
    //! @param[in]      path        ファイルパス(フルパス).
    //! @return     モデルホルダーを返却します.
    //-------------------------------------------------------------------------
    ModelHolder GetOrCreate(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      モデルを削除します.
    //! 
    //! @param[in]      holder      モデルホルダー.
    //-------------------------------------------------------------------------
    void Remove(ModelHolder& holder);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static ModelManager                     s_Instance;
    SpinLock                                m_SpinLock;
    std::unordered_map<uint64_t, Model*>    m_Models;
    bool                                    m_Initialized = false;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelManager();

    ModelManager             (const ModelManager&) = delete;
    ModelManager& operator = (const ModelManager&) = delete;
};

} // namespace asdx
