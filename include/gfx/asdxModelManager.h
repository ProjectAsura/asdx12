#include <cstdint>
#include <unordered_map>
#include <fnd/asdxSpinLock.h>
#include <gfx/asdxModel.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ModelHolder class
///////////////////////////////////////////////////////////////////////////////
class ModelHolder
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend class ModelManager;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //! 
    //! @note       内部で TextureManager::Remove() を呼び出します.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      有効かどうかチェックします.
    //! 
    //! @retval true    有効です.
    //! @retval false   無効です.
    //-------------------------------------------------------------------------
    bool IsValid() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアル数を取得します.
    //! 
    //! @return     マテリアル数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMaterialCount() const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを取得します.
    //! 
    //! @param[in]      index       マテリアル番号.
    //! @return     マテリアルを返却します.
    //-------------------------------------------------------------------------
    const Material* GetMaterial(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      リソースマテリアルを取得します.
    //! 
    //! @param[in]      index       マテリアル番号
    //! @return     リソースマテリアルを返却します.
    //-------------------------------------------------------------------------
    const res::Material& GetResMaterial(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを持つかどうかチェックします.
    //! 
    //! @retval true    ボーンを持ちます.
    //! @retval false   ボーンを持ちません.
    //-------------------------------------------------------------------------
    bool HasBone() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーン数を取得します.
    //! 
    //! @return     ボーン数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBoneCount() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを取得します.
    //! 
    //! @param[in]      index       ボーン番号.
    //! @return     指定されたボーンを返却します.
    //-------------------------------------------------------------------------
    const res::Bone& GetBone(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュ数を取得します.
    //! 
    //! @return     メッシュ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetMeshCount() const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを取得します.
    //! 
    //! @param[in]      index       メッシュ番号.
    //! @return     指定されたメッシュを返却します.
    //-------------------------------------------------------------------------
    const Mesh* GetMesh(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを取得します.
    //! 
    //! @param[in]      index       メッシュ番号.
    //! @return     指定されたメッシュを返却します.
    //-------------------------------------------------------------------------
    Mesh* GetMesh(uint32_t index);

    //-------------------------------------------------------------------------
    //! @brief      リソースメッシュを取得します.
    //! 
    //! @param[in]      index       メッシュ番号.
    //! @return     指定されたリソースメッシュを返却します.
    //-------------------------------------------------------------------------
    const res::Mesh& GetResMesh(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      バッチ数を取得します.
    //! 
    //! @return     バッチ数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBatchCount() const;

    //-------------------------------------------------------------------------
    //! @brief      バッチを取得します.
    //! 
    //! @param[in]      index       バッチ番号.
    //! @return     インスタンスを返却します.
    //-------------------------------------------------------------------------
    const res::ModelBatch& GetBatch(uint32_t index) const;

    //-------------------------------------------------------------------------
    //! @brief      総インスタンス数を取得します.
    //! 
    //! @return     総インスタンス数を返却します.
    //-------------------------------------------------------------------------
    uint64_t GetTotalInstanceCount() const;

    //-------------------------------------------------------------------------
    //! @brief      バウンディングスフィアを取得します.
    //! 
    //! @return     バウンディングスフィアを返却します.
    //-------------------------------------------------------------------------
    const BoundingSphere3& GetSphere() const;

    //-------------------------------------------------------------------------
    //! @brief      バウンディングボックスを取得します.
    //! 
    //! @return     バウンディングボックスを返却します.
    //-------------------------------------------------------------------------
    const BoundingBox3& GetBox() const;

    //-------------------------------------------------------------------------
    //! @brief      可視フラグを設定します.
    //! 
    //! @param[in]      value       表示する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetVisibility(bool value);

    //-------------------------------------------------------------------------
    //! @brief      可視フラグを取得します.
    //! 
    //! @retval true    表示.
    //! @retval false   非表示.
    //-------------------------------------------------------------------------
    bool IsVisible() const;

    //-------------------------------------------------------------------------
    //! @brief      ユーザーデータを設定します.
    //! 
    //! @param[in]      value       設定するユーザーデータ.
    //-------------------------------------------------------------------------
    void SetUserData(void* value);

    //-------------------------------------------------------------------------
    //! @brief      ユーザーデータを取得します.
    //! 
    //! @return     ユーザーデータを返却します.
    //-------------------------------------------------------------------------
    void* GetUserData() const;

    //-------------------------------------------------------------------------
    //! @brief      ボーンを検索します.
    //! 
    //! @param[in]      name        検索するボーン名.
    //! @param[out]     index       ボーンデータの格納先.
    //! @retval true    検索にヒット.
    //! @retval false   見つからなかった.
    //-------------------------------------------------------------------------
    bool FindBone(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      マテリアルを検索します.
    //! 
    //! @param[in]      name        検索するマテリアル名.
    //! @param[out]     index       マテリアル番号の格納先.
    //! @retval true    検索にヒット.
    //! @retval false   見つからなかった.
    //-------------------------------------------------------------------------
    bool FindMaterial(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      メッシュを検索します.
    //! 
    //! @param[in]      name        検索するメッシュ名.
    //! @param[out]     index       メッシュ番号の格納先.
    //! @retval true    検索にヒット.
    //! @retval false   見つからなかった.
    //-------------------------------------------------------------------------
    bool FindMesh(const char* name, uint32_t& index) const;

    //-------------------------------------------------------------------------
    //! @brief      インスタンスを検索します.
    //! 
    //! @param[in]      name        検索するインスタンス名.
    //! @param[out]     index       インスタンス番号の格納先.
    //! @retval true    検索にヒット.
    //! @retval false   見つからなかった.
    //-------------------------------------------------------------------------
    bool FindInstance(const char* name, uint32_t& index) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    Model*      m_pModel    = nullptr;  //!< モデル.
    uint64_t    m_Hash      = 0;        //!< ファイルパスハッシュ.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      pModel      モデル.
    //! @param[in]      hash        ファイルパスハッシュ.
    //-------------------------------------------------------------------------
    ModelHolder(Model* pModel, uint64_t hash);
};

///////////////////////////////////////////////////////////////////////////////
// ModelManager class
///////////////////////////////////////////////////////////////////////////////
class ModelManager
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static ModelManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功 または 初期化済み.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      モデルを生成または取得します.
    //! 
    //! @param[in]      path        ファイルパス(フルパス).
    //! @return     モデルホルダーを返却します.
    //-------------------------------------------------------------------------
    ModelHolder GetOrCreate(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      モデルを削除します.
    //! 
    //! @param[in]      holder      モデルホルダー.
    //-------------------------------------------------------------------------
    void Remove(ModelHolder& holder);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static ModelManager                     s_Instance;
    SpinLock                                m_SpinLock;
    std::unordered_map<uint64_t, Model*>    m_Models;
    bool                                    m_Initialized = false;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelManager();

    ModelManager             (const ModelManager&) = delete;
    ModelManager& operator = (const ModelManager&) = delete;
};

} // namespace asdx
