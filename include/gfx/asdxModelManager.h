#include <cstdint>
#include <unordered_map>
#include <fnd/asdxSpinLock.h>
#include <gfx/asdxModel.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ModelHolder class
///////////////////////////////////////////////////////////////////////////////
class ModelHolder
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend class ModelManager;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //! 
    //! @note       内部で TextureManager::Remove() を呼び出します.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      有効かどうかチェックします.
    //! 
    //! @retval true    有効です.
    //! @retval false   無効です.
    //-------------------------------------------------------------------------
    bool IsValid() const;

    //-------------------------------------------------------------------------
    //! @brief      モデルを取得します.
    //! 
    //! @return     モデルを返却します.
    //-------------------------------------------------------------------------
    const Model* GetModel() const;

    //-------------------------------------------------------------------------
    //! @brief      アロー演算子です.
    //! 
    //! @return     モデルをを返却します.
    //-------------------------------------------------------------------------
    const Model* operator -> () const;

    //-------------------------------------------------------------------------
    //! @brief      入れ替えます.
    //! 
    //! @param[in]      value       入れ替える値.
    //-------------------------------------------------------------------------
    void Swap(ModelHolder& value);

    //-------------------------------------------------------------------------
    //! @brief      入れ替えます.
    //! 
    //! @param[in]      value       入れ替える値.
    //-------------------------------------------------------------------------
    void Swap(ModelHolder&& value);

    //-------------------------------------------------------------------------
    //! @brief      等価比較演算子です.
    //! 
    //! @retval true    等価です.
    //! @retval false   非等価です.
    //-------------------------------------------------------------------------
    bool operator == (const ModelHolder& value) const;

    //-------------------------------------------------------------------------
    //! @brief      非等価比較演算子です.
    //! 
    //! @retval true    非等価です.
    //! @retval false   等価です.
    //-------------------------------------------------------------------------
    bool operator != (const ModelHolder& value) const;

    //-------------------------------------------------------------------------
    //! @brief      代入演算子です.
    //! 
    //! @param[in]      value       代入する値.
    //-------------------------------------------------------------------------
    ModelHolder& operator = (const ModelHolder& value);

    //-------------------------------------------------------------------------
    //! @brief      ムーブ代入演算子です.
    //! 
    //! @parm[in]       value       ムーブする値.
    //-------------------------------------------------------------------------
    ModelHolder& operator = (ModelHolder&& value);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    Model*      m_pModel    = nullptr;  //!< モデル.
    uint64_t    m_Hash      = 0;        //!< ファイルパスハッシュ.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      pModel      モデル.
    //! @param[in]      hash        ファイルパスハッシュ.
    //-------------------------------------------------------------------------
    ModelHolder(Model* pModel, uint64_t hash);
};

///////////////////////////////////////////////////////////////////////////////
// ModelManager class
///////////////////////////////////////////////////////////////////////////////
class ModelManager
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static ModelManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功 または 初期化済み.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      モデルを生成または取得します.
    //! 
    //! @param[in]      path        ファイルパス(フルパス).
    //! @return     モデルホルダーを返却します.
    //-------------------------------------------------------------------------
    ModelHolder GetOrCreate(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      モデルを削除します.
    //! 
    //! @param[in]      holder      モデルホルダー.
    //-------------------------------------------------------------------------
    void Remove(ModelHolder& holder);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static ModelManager                     s_Instance;
    SpinLock                                m_SpinLock;
    std::unordered_map<uint64_t, Model*>    m_Models;
    bool                                    m_Initialized = false;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ModelManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ModelManager();

    ModelManager             (const ModelManager&) = delete;
    ModelManager& operator = (const ModelManager&) = delete;
};

} // namespace asdx
