#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <fnd/asdxMath.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// CameraEvent struct
///////////////////////////////////////////////////////////////////////////////
struct CameraEvent
{
    ///////////////////////////////////////////////////////////////////////////
    // EVENT_TYPE enum
    ///////////////////////////////////////////////////////////////////////////
    enum EVENT_TYPE
    {
        EVENT_ROTATE  = 0x000001 << 0,     //!< ターゲットを中心に回転.
        EVENT_DOLLY   = 0x000001 << 1,     //!< ドリー.
        EVENT_TRUCK   = 0x000001 << 2,     //!< 平行移動.
        EVENT_TWIST   = 0x000001 << 3,     //!< ツイスト.
        EVENT_PANTILT = 0x000001 << 4,     //!< パン・チルト.
        EVENT_RESET   = 0x000001 << 5,     //!< リセット.
    };

    Vector2   Rotate    = Vector2(0.0f, 0.0f);          //!< 回転角です.
    Vector2   PanTilt   = Vector2(0.0f, 0.0f);          //!< パン・チルト角.
    Vector3   Truck     = Vector3(0.0f, 0.0f, 0.0f);    //!< トラック量です.
    float     Twist     = 0.0f;                         //!< ツイスト角です.
    float     Dolly     = 0.0f;                         //!< ドリー量です.
    uint32_t  Flags     = 0;                            //!< フラグです.
};


///////////////////////////////////////////////////////////////////////////////
// Camera class
///////////////////////////////////////////////////////////////////////////////
class Camera
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables
    //=========================================================================
    struct Param
    {
        Vector3 Position    = Vector3(0.0f, 0.0f, 10.0f);   //!< カメラの位置です.
        Vector3 Target      = Vector3(0.0f, 0.0f, 0.0f);    //!< カメラの注視点です.
        Vector3 Upward      = Vector3(0.0f, 0.0f, 1.0f);    //!< カメラの上向きベクトルです.
        Vector2 Rotate      = Vector2(0.0f, 0.0f);          //!< 回転角です.
        Vector2 PanTilt     = Vector2(0.0f, 0.0f);          //!< パン・チルト角です.
        float   Twist       = 0.0f;                         //!< ツイスト角です.
        float   MinDist     = 1e-4f;                        //!< ターゲットとの最小距離です.
        float   MaxDist     = 1000.0f;                      //!< ターゲットとの最大距離です.
    };

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Camera();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Camera();

    //-------------------------------------------------------------------------
    //! @brief      カメラ位置を設定します.
    //!
    //! @param [in]     position        設定するカメラ位置です.
    //-------------------------------------------------------------------------
    void SetPosition(const asdx::Vector3& position);

    //-------------------------------------------------------------------------
    //! @brief      カメラ注視点を設定します.
    //!
    //! @param [in]     target          設定するカメラ注視点です.
    //-------------------------------------------------------------------------
    void SetTarget(const asdx::Vector3& target);

    //-------------------------------------------------------------------------
    //! @brief      カメラ上向きベクトルを設定します.
    //!
    //! @param [in]     upward          設定するカメラ上向きベクトルです.
    //-------------------------------------------------------------------------
    void SetUpward(const asdx::Vector3& upward);

    //-------------------------------------------------------------------------
    //! @brief      ツイスト角を設定します.
    //!
    //! @param [in]     twist           設定するツイスト角です.
    //-------------------------------------------------------------------------
    void SetTwist( const float twist );

    //-------------------------------------------------------------------------
    //! @brief      可動距離範囲を設定します.
    //!
    //! @param [in]     minDist         設定するカメラ注視点との最小距離.
    //! @param [in]     maxDist         設定するカメラ注視点との最大距離.
    //-------------------------------------------------------------------------
    void SetRange(float minDist, float maxDist);

    //-------------------------------------------------------------------------
    //! @brief      カメラパラメータを記憶します.
    //-------------------------------------------------------------------------
    void Preset();

    //-------------------------------------------------------------------------
    //! @brief      カメラパラメータをリセットします.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      ビュー行列を更新します.
    //-------------------------------------------------------------------------
    void Update();

    //-------------------------------------------------------------------------
    //! @brief      カメライベントを基にビュー行列を更新します.
    //-------------------------------------------------------------------------
    void UpdateByEvent(const CameraEvent& camEvent);

    //-------------------------------------------------------------------------
    //! @brief      ビュー行列を取得します.
    //!
    //! @return     ビュー行列を返却します.
    //-------------------------------------------------------------------------
    const asdx::Matrix& GetView() const;

    //-------------------------------------------------------------------------
    //! @brief      カメラ位置を取得します.
    //!
    //! @return     カメラ位置を返却します.
    //-------------------------------------------------------------------------
    const asdx::Vector3& GetPosition() const;

    //-------------------------------------------------------------------------
    //! @brief      カメラ注視点を取得します.
    //!
    //! @return     カメラ注視点を返却します.
    //-------------------------------------------------------------------------
    const asdx::Vector3& GetTarget() const;

    //-------------------------------------------------------------------------
    //! @brief      カメラ上向きベクトルを取得します.
    //!
    //! @return     カメラ上向きベクトルを返却します.
    //-------------------------------------------------------------------------
    const asdx::Vector3& GetUpward() const;

    //-------------------------------------------------------------------------
    //! @brief      ツイスト角を取得します.
    //!
    //! @return     ツイスト角を返却します.
    //-------------------------------------------------------------------------
    float GetTwist() const;

    //-------------------------------------------------------------------------
    //! @brief      可動最小距離(カメラ注視点との最小距離)を取得します.
    //!
    //! @return     可動最小距離を返却します.
    //-------------------------------------------------------------------------
    float GetMinDist() const;

    //-------------------------------------------------------------------------
    //! @brief      可動最大距離(カメラ注視点との最大距離)を取得します.
    //!
    //! @return     可動最大距離を返却します.
    //-------------------------------------------------------------------------
    float GetMaxDist() const;

    //-------------------------------------------------------------------------
    //! @brief      カメラ基底ベクトルのX軸を取得します.
    //!
    //! @return     カメラ基底ベクトルのX軸を返却します.
    //-------------------------------------------------------------------------
    asdx::Vector3 GetAxisX() const;

    //-------------------------------------------------------------------------
    //! @brief      カメラ基底ベクトルのY軸を取得します.
    //!
    //! @return     カメラ基底ベクトルのY軸を返却します.
    //-------------------------------------------------------------------------
    asdx::Vector3 GetAxisY() const;

    //-------------------------------------------------------------------------
    //! @brief      カメラ基底ベクトルのZ軸を取得します.
    //!
    //! @return     カメラ基底ベクトルのZ軸を返却します.
    //-------------------------------------------------------------------------
    asdx::Vector3 GetAxisZ() const;

    //-------------------------------------------------------------------------
    //! @brief      パラメータを取得します.
    //! 
    //! @return     パラメータを返却します.
    //-------------------------------------------------------------------------
    const Param& GetParam() const;

    //-------------------------------------------------------------------------
    //! @brief      パラメータを設定します.
    //! 
    //! @param[in]      param       設定するパラメータ.
    //-------------------------------------------------------------------------
    void SetParam(const Param& param);

private:
    //=========================================================================
    // private variables
    //=========================================================================
    Param           m_Param;        //!< 計算用カメラパラメータです.
    Param           m_Preset;       //!< リセット用カメラパラメータです.
    asdx::Matrix    m_View;         //!< ビュー行列です.

    //=========================================================================
    // praviate methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      角度を計算します.
    //-------------------------------------------------------------------------
    void ComputeAngle();

    //-------------------------------------------------------------------------
    //! @brief      位置座標を計算します.
    //-------------------------------------------------------------------------
    void ComputePosition();

    //-------------------------------------------------------------------------
    //! @brief      注視点を計算します.
    //-------------------------------------------------------------------------
    void ComputeTarget();

    //-------------------------------------------------------------------------
    //! @brief      可動距離範囲内に制限します.
    //-------------------------------------------------------------------------
    void ClampDist();
};

} // namespace asdx

