#include <cstdint>
#include <fnd/asdxMath.h>
#include <fnd/asdxArrayView.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class SpriteRenderer;


///////////////////////////////////////////////////////////////////////////////
// SpriteKeyFrame structure
///////////////////////////////////////////////////////////////////////////////
struct SpriteKeyFrame
{
    float   time;   //!< 時刻.
    Vector2 uv0;    //!< 左上のテクスチャ座標.
    Vector2 uv1;    //!< 右下のテクスチャ座標.
};

///////////////////////////////////////////////////////////////////////////////
// SpriteAnimationTarck structure
///////////////////////////////////////////////////////////////////////////////
struct SpriteAnimationTrack
{
    float                     DurationSec;  //!< 再生所要時間(単位：秒).
    Int2                      Size;         //!< スプライトサイズ.
    ArrayView<SpriteKeyFrame> Frames;       //!< キーフレームデータ.
};

///////////////////////////////////////////////////////////////////////////////
// SpriteMoveData structure
///////////////////////////////////////////////////////////////////////////////
struct SpriteMoveData
{
    Vector2 SrcPos;     //!< 移動元座標.
    Vector2 DstPos;     //!< 移動先座標.
    float   TimeSec;    //!< 遷移時間(単位：秒).
};

///////////////////////////////////////////////////////////////////////////////
// SpriteAnimationPlayer class
///////////////////////////////////////////////////////////////////////////////
class SpriteAnimationPlayer
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Flag enum
    ///////////////////////////////////////////////////////////////////////////
    enum Flag : uint8_t
    {
        NONE   = 0,
        FLIP_X = 0x1 << 0,  //!< 水平方向に反転します.
        FLIP_Y = 0x1 << 1,  //!< 垂直方向に反転します.
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SpriteAnimationPlayer();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SpriteAnimationPlayer();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      アニメーショントラックを設定します.
    //! 
    //! @param[in]      pTrack      設定するアニメーショントラック.
    //-------------------------------------------------------------------------
    void SetTrack(const SpriteAnimationTrack* pTrack);

    //-------------------------------------------------------------------------
    //! @brief      アニメーショントラックを取得します.
    //! 
    //! @return     アニメーショントラックを返却します.
    //-------------------------------------------------------------------------
    const SpriteAnimationTrack* GetTrack() const;

    //-------------------------------------------------------------------------
    //! @brief      ループフラグを設定します.
    //! 
    //! @param[in]      value       ループ再生する場合は true.
    //-------------------------------------------------------------------------
    void SetLoop(bool value);

    //-------------------------------------------------------------------------
    //! @brief      ループフラグを取得します.
    //! 
    //! @return     ループフラグを返却します.
    //-------------------------------------------------------------------------
    bool IsLoop() const;

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを設定します.
    //! 
    //! @param[in]      value       設定する再生スピード.
    //-------------------------------------------------------------------------
    void SetPlaySpeed(float value);

    //-------------------------------------------------------------------------
    //! @brief      再生スピードを取得します.
    //! 
    //! @return     再生スピードを返却します.
    //-------------------------------------------------------------------------
    float GetPlaySpeed() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを設定します.
    //! 
    //! @param[in]      value       一時停止する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetPause(bool value);

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを取得します.
    //! 
    //! @return     一時停止フラグを返却します.
    //-------------------------------------------------------------------------
    bool IsPause() const;

    //-------------------------------------------------------------------------
    //! @brief      再生完了したかどうかチェックします.
    //! 
    //! @retval true    再生完了済み.
    //! @retval false   再生中.
    //! @note       ループフラグが設定されている場合は常に false を返却します.
    //-------------------------------------------------------------------------
    bool IsFinished() const;

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      描画処理を行います.
    //! 
    //! @param[in]      x       左上のX座標.
    //! @param[in]      y       左上のY座標.
    //! @param[in]      w       横幅.
    //! @param[in]      h       縦幅.
    //! @param[in]      flag    描画フラグ.
    //-------------------------------------------------------------------------
    void Draw(SpriteRenderer& renderer, int x, int y, uint8_t flags = Flag::NONE);

    //-------------------------------------------------------------------------
    //! @brief      フレーム番号を取得します.
    //-------------------------------------------------------------------------
    uint32_t GetFrameIndex() const;

    //-------------------------------------------------------------------------
    //! @brief      再生時間を取得します.
    //-------------------------------------------------------------------------
    float GetTimeSec() const;

    //-------------------------------------------------------------------------
    //! @brief      フレーム先頭に戻します.
    //-------------------------------------------------------------------------
    void Cue();

    //-------------------------------------------------------------------------
    //! @brief      1フレーム進めます.
    //-------------------------------------------------------------------------
    void FrameAdvance();

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    float       m_TimeSec       = 0.0f;     //!< 再生時間.
    uint32_t    m_FrameIndex    = 0;        //!< フレーム番号.
    bool        m_Loop          = false;    //!< ループフラグ.
    bool        m_Pause         = false;    //!< 一時停止フラグ.
    float       m_PlaySpeed     = 1.0f;     //!< 再生速度.

    const SpriteAnimationTrack* m_pTrack = nullptr; //!< アニメーショントラック.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      最も近いフレームを検索します.
    //! 
    //! @param[in]      timeSec     再生時間.
    //! @return     最も近いフレーム番号を返却します.
    //-------------------------------------------------------------------------
    uint32_t FindFrame(float timeSec);
};


///////////////////////////////////////////////////////////////////////////////
// SpriteMover class
///////////////////////////////////////////////////////////////////////////////
class SpriteMover
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SpriteMover() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SpriteMover() = default;

    //-------------------------------------------------------------------------
    //! @brief      移動データを設定します.
    //-------------------------------------------------------------------------
    void SetData(const SpriteMoveData* pMove);

    //-------------------------------------------------------------------------
    //! @brief      移動データを取得します.
    //! 
    //! @return     移動データを返却します.
    //-------------------------------------------------------------------------
    const SpriteMoveData* GetData() const;

    //-------------------------------------------------------------------------
    //! @brief      リセット処理を行います.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec        差分時間(単位：秒).
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      位置座標を取得します.
    //! 
    //! @return     位置座標を返却します.
    //-------------------------------------------------------------------------
    Int2 GetPos() const;

    //-------------------------------------------------------------------------
    //! @brief      経過時間を取得します.
    //! 
    //! @return     経過時間を返却します.
    //-------------------------------------------------------------------------
    float GetTimeSec() const;

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを設定します.
    //! 
    //! @param[in]      value       一時停止する場合は true を指定.
    //-------------------------------------------------------------------------
    void SetPause(bool value);

    //-------------------------------------------------------------------------
    //! @brief      一時停止フラグを取得します.
    //! 
    //! @return     一時停止フラグを返却します.
    //-------------------------------------------------------------------------
    bool IsPause() const;

    //-------------------------------------------------------------------------
    //! @brief      再生速度を設定します.
    //! 
    //! @param[in]      value       設定する再生速度.
    //-------------------------------------------------------------------------
    void SetPlaySpeed(float value);

    //-------------------------------------------------------------------------
    //! @brief      再生速度を取得します.
    //! 
    //! @return     再生速度を返却します.
    //-------------------------------------------------------------------------
    float GetPlaySpeed() const;

    //-------------------------------------------------------------------------
    //! @brief      移動が完了したかどうかチェックします.
    //! 
    //! @retval true    移動完了.
    //! @retval false   移動中.
    //-------------------------------------------------------------------------
    bool IsComplete() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    float   m_TimeSec   = 0.0f;         //!< 経過時間.
    float   m_PlaySpeed = 1.0f;         //!< 再生速度.
    bool    m_Pause     = false;        //!< 一時停止フラグ.

    const SpriteMoveData* m_pData = nullptr;    //!< 移動データ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
