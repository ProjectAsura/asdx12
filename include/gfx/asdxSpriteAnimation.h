#include <cstdint>
#include <vector>
#include <fnd/asdxMath.h>


namespace asdx {

//-----------------------------------------------------------------------------
// Forward Declarations.
//-----------------------------------------------------------------------------
class SpriteRenderer;


///////////////////////////////////////////////////////////////////////////////
// SpriteAnimation
///////////////////////////////////////////////////////////////////////////////
class SpriteAnimation
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Flag enum
    ///////////////////////////////////////////////////////////////////////////
    enum Flag
    {
        FLIP_X = 0x1 << 0,  //!< 水平方向に反転します.
        FLIP_Y = 0x1 << 1,  //!< 垂直方向に反転します.
    };

    ///////////////////////////////////////////////////////////////////////////
    // Frame structure
    ///////////////////////////////////////////////////////////////////////////
    struct Frame
    {
        asdx::Vector2   uv0;    //!< 左上のUV座標.
        asdx::Vector2   uv1;    //!< 右下のUV座標.
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SpriteAnimation();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SpriteAnimation();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      w       スプライトの横幅.
    //! @param[in]      h       スプライトの縦幅.
    //! @param[in]      frames  スプライトのフレームデータ.
    //-------------------------------------------------------------------------
    void Init(int w, int h, const std::vector<Frame>& frames);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      次のフレームへ進めます.
    //-------------------------------------------------------------------------
    void NextFrame();

    //-------------------------------------------------------------------------
    //! @brief      次のフレームがあるかチェックします.
    //! 
    //! @retval true    次のフレームあり.
    //! @retval false   最終フレームです.
    //-------------------------------------------------------------------------
    bool HasNextFrame() const;

    //-------------------------------------------------------------------------
    //! @brief      時間に応じて次のフレームへ進めます.
    //! 
    //! @param[in]      changeSec       切り替え時間(秒).
    //! @param[in]      deltaSec        前フレームからの差分時間(秒).
    //! @param[in,out]  elapsedSec      経過時間(秒).
    //-------------------------------------------------------------------------
    void NextFrameByTime(float changeSec, float deltaSec, float& elapsedSec);

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //!
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //! @param[in]      layer       描画レイヤー
    //! @param[in]      flags       フラグ.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y, int layer, uint8_t flags);

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //!
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //! @param[in]      layer       描画レイヤー
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y, int layer)
    { Add(renderer, x, y, layer, 0); }

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //!
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //! @param[in]      flags       フラグ.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y, uint8_t flags)
    { Add(renderer, x, y, 0, flags); }

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //!
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y)
    { Add(renderer, x, y, 0, 0); }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    int                 m_SpriteW;      //!< スプライトの横幅.
    int                 m_SpriteH;      //!< スプライトの縦幅.
    uint32_t            m_FrameIndex;   //!< フレーム番号.
    std::vector<Frame>  m_Frames;       //!< フレームデータ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// TimerSpriteAnimation class
///////////////////////////////////////////////////////////////////////////////
class TimerSpriteAnimation
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // Alias.
    //=========================================================================
    using Frame = SpriteAnimation::Frame;

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    TimerSpriteAnimation();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~TimerSpriteAnimation();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      w           スプライトの横幅.
    //! @param[in]      h           スプライトの縦幅.
    //! @param[in]      changeSec   スプライトのフレーム切り替え時間(秒).
    //! @param[in]      frames      フレームデータ.
    //-------------------------------------------------------------------------
    void Init(int w, int h, float changeSec, const std::vector<Frame>& frames);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      更新処理を行います.
    //! 
    //! @param[in]      deltaSec    差分時間(秒)
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //! 
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //! @param[in]      layer       描画レイヤー.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y, int layer, uint8_t flags);

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //! 
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //! @param[in]      layer       描画レイヤー.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y, int layer)
    { Add(renderer, x, y, layer, 0); }

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //! 
    //! @param[in]      renderer    スプライトレンダラー.
    //! @param[in]      x           描画位置X成分.
    //! @param[in]      y           描画位置Y成分.
    //! @param[in]      layer       描画レイヤー.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y, uint8_t flags)
    { Add(renderer, x, y, 0, flags); }

    //-------------------------------------------------------------------------
    //! @brief      スプライトを追加します.
    //! 
    //! @param[in]      renderer        スプライトレンダラー.
    //! @param[in]      x               描画位置X成分.
    //! @param[in]      y               描画位置Y成分.
    //-------------------------------------------------------------------------
    void Add(SpriteRenderer& renderer, int x, int y)
    { Add(renderer, x, y, 0, 0); }

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    SpriteAnimation m_Animation;    //!< スプライトアニメーション.
    float           m_ChangeSec;    //!< 切り替え時間(秒).
    float           m_ElapsedSec;   //!< 経過時間(秒).

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
