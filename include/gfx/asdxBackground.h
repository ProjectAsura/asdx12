class BackgroundCube
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    BackgroundCube();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~BackgroundCube();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      キューブマップを描画します.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      width       描画ターゲットの横幅.
    //! @param[in]      height      描画ターゲットの縦幅.
    //! @param[in]      view        ビュー行列.
    //! @param[in]      proj        射影行列.
    //! @param[in]      target      描画ターゲット.
    //! @param[in]      cubeMap     キューブマップ委.
    //-------------------------------------------------------------------------
    void Draw(
        ID3D12GraphicsCommandList*  pCmd,
        uint32_t                    width,
        uint32_t                    height,
        Matrix&                     view,
        Matrix&                     proj,
        D3D12_GPU_DESCRIPTOR_HANDLE target,
        D3D12_GPU_DESCRIPTOR_HANDLE cubeMap);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature>   m_RootSignature;   //!< ルートシグニチャ.
    RefPtr<ID3D12PipelineState>   m_PipelineState;   //!< パイプラインステート.
    DoubledConstantBuffer         m_ConstantBuffer;  //!< 定数バッファ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};


