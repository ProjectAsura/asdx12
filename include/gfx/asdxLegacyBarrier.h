#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <d3d12.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// LegacyBarrier class
///////////////////////////////////////////////////////////////////////////////
class LegacyBarrier
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    LegacyBarrier() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~LegacyBarrier() = default;

    //-------------------------------------------------------------------------
    //! @brief      リセット処理を行います.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      遷移バリアを設定します.
    //! 
    //! @param[in]      pResource       リソース.
    //! @param[in]      before          遷移前のリソースステートです.
    //! @param[in]      after           遷移後のリソースステートです.
    //-------------------------------------------------------------------------
    void Transition(
        ID3D12Resource*         pResource,
        D3D12_RESOURCE_STATES   before,
        D3D12_RESOURCE_STATES   after);

    //-------------------------------------------------------------------------
    //! @brief      エイリアシングバリアを設定します.
    //! 
    //! @param[in]      pBefore     遷移前のリソース.
    //! @param[in]      pAfter      遷移後のリソース.
    //-------------------------------------------------------------------------
    void Aliasing(ID3D12Resource* pBefore, ID3D12Resource* pAfter);

    //-------------------------------------------------------------------------
    //! @brief      UAVバリアを設定します.
    //! 
    //! @param[in]      pResource       リソース.
    //-------------------------------------------------------------------------
    void UAV(ID3D12Resource* pResource);

    //-------------------------------------------------------------------------
    //! @brief      リソースバリアを適用します.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //-------------------------------------------------------------------------
    void Apply(ID3D12GraphicsCommandList* pCmd);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    UINT                   m_Count       = 0;
    D3D12_RESOURCE_BARRIER m_Barrier[16] = {};

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
