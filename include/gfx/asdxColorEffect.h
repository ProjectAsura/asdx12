///////////////////////////////////////////////////////////////////////////////
// ColorEffectCS class
///////////////////////////////////////////////////////////////////////////////
class ColorEffectCS
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Param structure
    ///////////////////////////////////////////////////////////////////////////
    struct Param
    {
        Vector3 Saturation      = Vector3(1.0f, 1.0f, 1.0f);    //!< 彩度.
        Vector3 AddColor        = Vector3(0.0f, 0.0f, 0.0f);    //!< 加算カラー.
        Vector3 MulColor        = Vector3(1.0f, 1.0f, 1.0f);    //!< 乗算カラー.
        float   Brightness      = 1.0f;                         //!< 明度.
        float   Contrast        = 0.0f;                         //!< コントラスト.
        float   HueDegree       = 0.0f;                         //!< 色相(単位：度).
        float   SepiaTone       = 0.0f;                         //!< セピアトーン.
        float   GrayScale       = 0.0f;                         //!< グレースケール.
        float   WhiteBalance    = 6504.0f;                      //!< ホワイトバランス.
        bool    BlackAndWhite   = false;                        //!< 白黒化.
        bool    Reverse         = false;                        //!< ネポジ反転

        D3D12_GPU_DESCRIPTOR_HANDLE HandleSRV = {};
        D3D12_GPU_DESCRIPTOR_HANDLE HandleUAV = {};
        uint32_t                    UavWidth  = 0;
        uint32_t                    UavHeight = 0;
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ColorEffectCS();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ColorEffectCS();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      コンピュートシェーダを起動します
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      width       UAVの横幅.
    //! @param[in]      height      UAVの縦幅.
    //! @param[in]      handleUAV   出力先UAV.
    //! @param[in]      handleSRV   入力SRV.
    //-------------------------------------------------------------------------
    void Dispatch(ID3D12GraphicsCommandList* pCmd, const Param& param);

    //-------------------------------------------------------------------------
    //! @brief      ルートシグニチャを取得します.
    //! 
    //! @return     ルートシグニチャを返却します.
    //-------------------------------------------------------------------------
    ID3D12RootSignature* GetRootSignature() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature> m_RootSignature;
    RefPtr<ID3D12PipelineState> m_PipelineState;

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};


