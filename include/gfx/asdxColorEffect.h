#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <d3d12.h>
#include <fnd/asdxRef.h>
#include <fnd/asdxMath.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// ColorEffect class
///////////////////////////////////////////////////////////////////////////////
class ColorEffect
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Param structure
    ///////////////////////////////////////////////////////////////////////////
    struct Param
    {
        Vector3 Saturation  = Vector3(1.0f, 1.0f, 1.0f);    //!< 彩度.
        Vector3 AddColor    = Vector3(0.0f, 0.0f, 0.0f);    //!< 加算カラー.
        Vector3 MulColor    = Vector3(1.0f, 1.0f, 1.0f);    //!< 乗算カラー.
        float   Brightness  = 1.0f;                         //!< 明度.
        float   Contrast    = 1.0f;                         //!< コントラスト.
        float   HueDegree   = 0.0f;                         //!< 色相(単位：度).
        float   SepiaTone   = 0.0f;                         //!< セピアトーン.
        float   GrayScale   = 0.0f;                         //!< グレースケール.
        bool    Reverse     = false;                        //!< ネポジ反転

        //---------------------------------------------------------------------
        //! @brief      パラメータをリセットします.
        //---------------------------------------------------------------------
        void Reset();
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ColorEffect();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ColorEffect();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      rtvFormat       レンダーターゲットビューのフォーマット.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(DXGI_FORMAT rtvFormat);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      描画処理を行います.
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      handleSRV   入力SRV
    //-------------------------------------------------------------------------
    void Draw(ID3D12GraphicsCommandList* pCmd, D3D12_GPU_DESCRIPTOR_HANDLE handleSRV);

    //-------------------------------------------------------------------------
    //! @brief      コンピュートシェーダを起動します
    //! 
    //! @param[in]      pCmd        グラフィックスコマンドリスト.
    //! @param[in]      width       UAVの横幅.
    //! @param[in]      height      UAVの縦幅.
    //! @param[in]      handleUAV   出力先UAV.
    //! @param[in]      handleSRV   入力SRV.
    //-------------------------------------------------------------------------
    void Dispatch(
        ID3D12GraphicsCommandList*  pCmd,
        uint32_t                    width,
        uint32_t                    height,
        D3D12_GPU_DESCRIPTOR_HANDLE handleUAV,
        D3D12_GPU_DESCRIPTOR_HANDLE handleSRV);

    //-------------------------------------------------------------------------
    //! @brief      制御パラメータを設定します.
    //! 
    //! @param[in]      value       設定するパラメータ.
    //-------------------------------------------------------------------------
    void SetParam(const Param& value);

    //-------------------------------------------------------------------------
    //! @brief      制御パラメータを取得します.
    //! 
    //! @return     制御パラメータを返却します.
    //-------------------------------------------------------------------------
    const Param& GetParam() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    RefPtr<ID3D12RootSignature> m_RootSignature;
    RefPtr<ID3D12PipelineState> m_GraphicsPSO;
    RefPtr<ID3D12PipelineState> m_ComputePSO;
    Param                       m_Param = {};

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      カラー行列を計算します.
    //! 
    //! @return     カラー行列を返却します.
    //-------------------------------------------------------------------------
    Matrix CalcColorMatrix() const;
};

} // namespace asdx
