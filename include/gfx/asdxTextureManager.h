#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <unordered_map>
#include <fnd/asdxSpinLock.h>
#include <gfx/asdxTexture.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// TextureHolder class
///////////////////////////////////////////////////////////////////////////////
class TextureHolder
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    friend class TextureManager;

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    TextureHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~TextureHolder() = default;

    //-------------------------------------------------------------------------
    //! @brief      解放処理を行います.
    //! 
    //! @note       内部で TextureManager::Remove() を呼び出します.
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    //! @brief      有効かどうかチェックします.
    //! 
    //! @retval true    有効です.
    //! @retval false   無効です.
    //-------------------------------------------------------------------------
    bool IsValid() const;

    //-------------------------------------------------------------------------
    //! @brief      リソース設定を取得します.
    //! 
    //! @return     リソース設定を返却します.
    //-------------------------------------------------------------------------
    D3D12_RESOURCE_DESC GetDesc() const;

    //-------------------------------------------------------------------------
    //! @brief      バインドレスインデックスを取得します.
    //! 
    //! @return     バインドレスインデックスを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetBindlessIndex() const;

    //-------------------------------------------------------------------------
    //! @brief      CPUディスクリプタハンドルを取得します.
    //! 
    //! @return     CPUディスクリプタハンドルを返却します.
    //-------------------------------------------------------------------------
    D3D12_CPU_DESCRIPTOR_HANDLE GetHandleCPU() const;

    //-------------------------------------------------------------------------
    //! @brief      GPUディスクリプタハンドルを取得します.
    //! 
    //! @return     GPUディスクリプタハンドルを返却します.
    //-------------------------------------------------------------------------
    D3D12_GPU_DESCRIPTOR_HANDLE GetHandleGPU() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    Texture* m_pTexture = nullptr;   //!< テクスチャ.
    uint64_t m_Hash     = 0;         //!< ファイルパスハッシュ.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      引数付きコンストラクタです.
    //! 
    //! @param[in]      pTexture        テクスチャ.
    //! @param[in]      hash            ファイルパスハッシュ.
    //-------------------------------------------------------------------------
    TextureHolder(Texture* pTexture, uint64_t hash);
};

///////////////////////////////////////////////////////////////////////////////
// TextureManager class
///////////////////////////////////////////////////////////////////////////////
class TextureManager
{
    //=========================================================================
    // list of friend classe and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングルトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static TextureManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      テクスチャを生成または取得します.
    //! 
    //! @param[in]      path        ファイルパス(フルパス).
    //! @return     テクスチャホルダーを返却します.
    //-------------------------------------------------------------------------
    TextureHolder GetOrCreate(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      テクスチャを削除します.
    //! 
    //! @param[in]      holder      テクスチャホルダー.
    //-------------------------------------------------------------------------
    void Remove(TextureHolder& holder);

    //-------------------------------------------------------------------------
    //! @brief      コマンドリストを入れ替えます.
    //! 
    //! @return     アップデートコマンドが登録されているコマンドリストを返却します.
    //-------------------------------------------------------------------------
    ID3D12GraphicsCommandList* Swap();

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static TextureManager                   s_Instance;
    SpinLock                                m_SpinLock;
    std::unordered_map<uint64_t, Texture*>  m_Textures;
    RefPtr<ID3D12GraphicsCommandList>       m_CmdList[2];
    RefPtr<ID3D12CommandAllocator>          m_CmdAllocator[2];
    uint8_t                                 m_BufferIndex = 0;
    bool                                    m_Initialized = false;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    TextureManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~TextureManager();

    TextureManager              (const TextureManager&) = delete;
    TextureManager& operator =  (const TextureManager&) = delete;
};

} // namespace asdx
