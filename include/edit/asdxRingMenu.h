#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <imgui.h>
#include <string>
#include <vector>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// RingMenu class
///////////////////////////////////////////////////////////////////////////////
class RingMenu
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Item structure
    ///////////////////////////////////////////////////////////////////////////
    struct Item
    {
        ImTextureID Icon;
        std::string Label;
    };

    ///////////////////////////////////////////////////////////////////////////
    // Category structure
    ///////////////////////////////////////////////////////////////////////////
    struct Category
    {
        std::string         Name;
        std::vector<Item>   Items;
    };

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    RingMenu();

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    int AddCategory(const std::string& name);

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    void AddItem(int category, ImTextureID icon, const std::string& label);

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    void Open();

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    void Close();

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    int GetCurrentCategory() const;

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    int GetSelectedIndex(int category) const;

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    void Draw();

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    std::vector<Category>   m_Categories;
    std::vector<int>        m_Selection;
    bool                    m_IsOpen            = false;
    int                     m_CurrentCategory   = 0;
    int                     m_TargetCategory    = 0;
    float                   m_AnimT             = 0.0f;
    bool                    m_CategoryChanging  = false;
    float                   m_CategoryAnimT     = 1.0f;
    float                   m_RadiusBase        = 160.0f;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    static float EaseOutBack(float t);

    //-------------------------------------------------------------------------
    //! @brief
    //-------------------------------------------------------------------------
    void DrawCategoryRing(
        ImDrawList* draw,
        ImVec2      center,
        float       radius,
        int         categoryIndex,
        float       scale);
};


} // namespace asdx
