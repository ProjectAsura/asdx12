// Includes
//-----------------------------------------------------------------------------
#include <atomic>
#include <thread>
#include <list>
#include <string>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// FileEventArgs structure
///////////////////////////////////////////////////////////////////////////////
struct FileEventArgs
{
    enum TYPE
    {
        Added           = 0x1,  //!< ディレクトリにファイルが追加された.
        Removed         = 0x2,  //!< ディレクトリからファイルが削除された.
        Modified        = 0x3,  //!< ファイルが変更された.
        RenamedOldName  = 0x4,  //!< ファイルがリネームされ，通知される古いファイル名
        RenamedNewName  = 0x5,  //!< ファイルがリネームされ，通知される新しいファイル名.
    };

    TYPE            Type;           //!< ファイルイベントタイプ.
    std::string     FullPath;       //!< フルパス.
};

///////////////////////////////////////////////////////////////////////////////
// IFileListener interface
///////////////////////////////////////////////////////////////////////////////
struct IFileListener
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~IFileListener()
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      ファイル変更の処理です.
    //-------------------------------------------------------------------------
    virtual void OnChanged(const std::vector<FileEventArgs>& args) = 0;
};


///////////////////////////////////////////////////////////////////////////////
// FileWatcher class
///////////////////////////////////////////////////////////////////////////////
class FileWatcher
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Desc structure
    ///////////////////////////////////////////////////////////////////////////
    struct Desc
    {
        size_t   BufferSize   = 4096;         //!< バッファサイズ.
        uint32_t WaitTimeMsec = 100;          //!< 1ループの待機時間(ミリ秒単位)

        std::vector<std::string>    Dirs;           //!< 監視ディレクトリ.
        std::list<IFileListener*>   pListeners;     //!< 変更通知先.
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    FileWatcher();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~FileWatcher();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理です.
    //!
    //! @param[in]      desc        設定です.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(Desc& desc);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

private:
    struct Worker;

    //=========================================================================
    // private variables.
    //=========================================================================
    Worker*                             m_pWorkers      = nullptr;
    size_t                              m_DirCount      = 0;
    DWORD                               m_WaitTimeMsec  = 0;
    std::vector<HANDLE>                 m_Events;
    std::vector<asdx::IFileListener*>   m_Listeners;
    std::atomic<bool>                   m_Finish  = {};       //!< 終了フラグ.
    std::thread*                        m_pThread = nullptr;  //!< 監視スレッド.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

} // namespace asdx
