#include <fnd/asdxList.h>
#include <fnd/asdxBlackboard.h>
#include <fnd/asdxSpinLock.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// IScene interface
///////////////////////////////////////////////////////////////////////////////
struct IScene : public List<IScene>::Node
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~IScene() = default;

    //-------------------------------------------------------------------------
    //! @brief      シーン開始時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnEnter()
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      シーン更新時の処理です.
    //! 
    //! @param[in]      deltaSec        前回から差分時間(単位:秒).
    //-------------------------------------------------------------------------
    virtual void OnUpdate(float /*deltaSec*/)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      シーン描画時の処理です.
    //! 
    //! @param[in]      pArgs           描画引数です.
    //-------------------------------------------------------------------------
    virtual void OnDraw(void* /*pArgs*/)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      シーン終了時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnExit() 
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      シーンIDを取得します.
    //! 
    //! @return     シーンIDを返却します.
    //-------------------------------------------------------------------------
    virtual uint32_t GetId() const = 0;
};

///////////////////////////////////////////////////////////////////////////////
// SceneManager class
///////////////////////////////////////////////////////////////////////////////
class SceneManager
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングルトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static SceneManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init();

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      シーンを切り替えます.
    //! 
    //! @param[in]      id      切り替え先シーンID.
    //! @retval true    切り替えに成功.
    //! @retval false   切り替えに失敗.
    //-------------------------------------------------------------------------
    bool ChangeScene(uint32_t id);

    //-------------------------------------------------------------------------
    //! @brief      アクティブシーンを更新します.
    //! 
    //! @param[in]      deltaSec    差分時間.
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      アクティブシーンを描画します.
    //! 
    //! @param[in]      pArgs       描画引数.
    //-------------------------------------------------------------------------
    void Draw(void* pArgs);

    //-------------------------------------------------------------------------
    //! @brief      アクティブシーンIDを取得します.
    //! 
    //! @return     アクティブシーンIDを返却します.
    //! @note       アクティブなシーンが無い場合は UINT32_MAX を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetActiveId() const;

    //-------------------------------------------------------------------------
    //! @brief      シーンを生成し、登録します.
    //! 
    //! @param[in]      args        生成引数.
    //! @retval true    生成に成功.
    //! @retval false   生成に失敗.
    //-------------------------------------------------------------------------
    template<typename T, class... Args>
    bool CreateScene(Args&&... args)
    {
        auto scene = new T (args...);
        if (scene == nullptr)
            return false;

        ScopedLock<SpinLock> lock(m_SpinLock);
        m_SceneList.push_back(scene);
        return true;
    }

    //-------------------------------------------------------------------------
    //! @brief      シーンを削除します.
    //! 
    //! @param[in]      id      削除するシーンID.
    //-------------------------------------------------------------------------
    void RemoveScene(uint32_t id);

    //-------------------------------------------------------------------------
    //! @brief      ブラックボードを取得します.
    //! 
    //! @return     ブラックボードを返却します.
    //-------------------------------------------------------------------------
    ThreadSafeBlackboard& GetBlackboard();

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static SceneManager     s_Instance;
    SpinLock                m_SpinLock;
    IScene*                 m_pActiveScene = nullptr;
    List<IScene>            m_SceneList;
    ThreadSafeBlackboard    m_Blackboard;

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    SceneManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~SceneManager();

    SceneManager             (const SceneManager&) = delete;
    SceneManager& operator = (const SceneManager&) = delete;
};

} // namespace asdx
