#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>


namespace asdx {

//-----------------------------------------------------------------------------
// Type Alias.
//-----------------------------------------------------------------------------
using SoundId = uint32_t;

///////////////////////////////////////////////////////////////////////////////
// SoundState enum
///////////////////////////////////////////////////////////////////////////////
enum SoundState
{
    Error,      //!< エラー状態.
    Play,       //!< 再生状態.
    Stop,       //!< 停止状態.
    Pause,      //!< 一時停止状態.
    Done,       //!< 再生完了状態.
};

///////////////////////////////////////////////////////////////////////////////
// ISoundManager interface
///////////////////////////////////////////////////////////////////////////////
struct ISoundManager
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~ISoundManager() {}

    //-------------------------------------------------------------------------
    //! @brief      サウンドデータを登録します.
    //! 
    //! @param[in]      id      登録ID.
    //! @param[in]      path    ファイルパスです.
    //! @retval true    登録に成功.
    //! @retval false   登録に失敗.
    //! @note       再生可能なフォーマットは wave, midi, mp3 です.
    //-------------------------------------------------------------------------
    virtual bool Open(SoundId id, const char* path) = 0;

    //-------------------------------------------------------------------------
    //! @brief      サウンドデータの登録を解除します.
    //! 
    //! @param[in]      id      登録ID.
    //-------------------------------------------------------------------------
    virtual void Close(SoundId id) = 0;

    //-------------------------------------------------------------------------
    //! @brief      登録済みのサウンドデータを再生します.
    //! 
    //! @param[in]      id          登録ID.
    //! @param[in]      loopCount   ループ再生数.
    //-------------------------------------------------------------------------
    virtual void Play(SoundId id, int loopCount) = 0;

    //-------------------------------------------------------------------------
    //! @brief      登録済みのサウンドデータを停止します.
    //! 
    //! @param[in]      id          登録ID.
    //-------------------------------------------------------------------------
    virtual void Stop(SoundId id) = 0;

    //-------------------------------------------------------------------------
    //! @brief      登録済みのサウンドデータを一時停止します.
    //! 
    //! @param[in]      id          登録ID.
    //-------------------------------------------------------------------------
    virtual void Pause(SoundId id) = 0;

    //-------------------------------------------------------------------------
    //! @brief      サウンドデータの再生を再開します.
    //-------------------------------------------------------------------------
    virtual void Resume(SoundId id) = 0;

    //-------------------------------------------------------------------------
    //! @brief      サウンドデータの状態を取得します.
    //! 
    //! @param[in]      id          登録ID.
    //! @return     サウンドデータの状態を返却します.
    //-------------------------------------------------------------------------
    virtual SoundState GetState(SoundId id) = 0;
};

//-----------------------------------------------------------------------------
//! @brief      サウンドマネージャを取得します.
//! 
//! @return     サウンドマネージャを返却します.
//-----------------------------------------------------------------------------
ISoundManager& GetSoundManager();

//-----------------------------------------------------------------------------
//! @brief      サウンドマネージャの初期化処理.
//! 
//! @param[in]      hWnd        ウィンドウハンドル.
//-----------------------------------------------------------------------------
void InitSoundMgr(uintptr_t hWnd);

//-----------------------------------------------------------------------------
//! @brief      サウンドマネージャの終了処理.
//-----------------------------------------------------------------------------
void TermSoundMgr();

//-----------------------------------------------------------------------------
//! @brief      サウンドマネージャのコールバック処理.
//! 
//! @param[in]      id      登録ID.
//! @param[in]      param   パラメータ.
//-----------------------------------------------------------------------------
void OnSoundMsg(SoundId id, uint32_t param);

} // namespace asdx