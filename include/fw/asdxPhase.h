//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>
#include <fnd/asdxBlackboard.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// IPhase interface
///////////////////////////////////////////////////////////////////////////////
struct IPhase
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~IPhase() = default;

    //-------------------------------------------------------------------------
    //! @brief      開始時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnStart()
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      更新時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnUpdate(float /*deltaSec*/)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      描画時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnDraw(void* /*pArgs*/)
    { /* DO_NOTHING */ }

    //-------------------------------------------------------------------------
    //! @brief      終了時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnEnd()
    { /* DO_NOTHING */ }
};

///////////////////////////////////////////////////////////////////////////////
// IPhaseFactory interface
///////////////////////////////////////////////////////////////////////////////
struct IPhaseFactory
{
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~IPhaseFactory() = default;

    //-------------------------------------------------------------------------
    //! @brief      フェーズを生成します.
    //! 
    //! @param[in]      phaseId     フェーズ番号.
    //! @return     作成されたフェーズを返却します.
    //-------------------------------------------------------------------------
    virtual IPhase* Create(uint64_t phaseId) = 0;

    //-------------------------------------------------------------------------
    //! @brief      フェーズを破棄します.
    //! 
    //! @param[in]      pPhase      破棄するフェーズ.
    //-------------------------------------------------------------------------
    virtual void Dispose(IPhase*& pPhase) = 0;
};

///////////////////////////////////////////////////////////////////////////////
// PhaseManager class
///////////////////////////////////////////////////////////////////////////////
class PhaseManager
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シングルトンインスタンスを取得します.
    //! 
    //! @return     シングルトンインスタンスを返却します.
    //-------------------------------------------------------------------------
    static PhaseManager& Instance();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      firstPhaseId        最初のフェーズ番号.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(IPhaseFactory* pFactory, uint64_t firstPhaseId);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      フェーズを変更処理を行います.
    //! 
    //! @param[in]      phaseId     フェーズ番号.
    //-------------------------------------------------------------------------
    void Change(uint64_t phaseId);

    //-------------------------------------------------------------------------
    //! @brief      フェーズの更新処理を行います.
    //! 
    //! @param[in]      deltaSec        差分時間(秒).
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      フェーズの描画処理を行います.
    //! 
    //! @param[in]      pArgs           描画引数.
    //-------------------------------------------------------------------------
    void Draw(void* pArgs);

    //-------------------------------------------------------------------------
    //! @brief      現在のフェーズをリスタートします.
    //-------------------------------------------------------------------------
    void Restart();

    //-------------------------------------------------------------------------
    //! @brief      フェーズ番号を取得します.
    //! 
    //! @return     フェーズ番号を返却します.
    //-------------------------------------------------------------------------
    uint64_t GetPhaseId() const;

    //-------------------------------------------------------------------------
    //! @brief      ブラックボードを取得します.
    //! 
    //! @return     ブラックボードを返却します.
    //-------------------------------------------------------------------------
    Blackboard& GetBlackboard();

    //-------------------------------------------------------------------------
    //! @brief      ブラックボードを取得します(const版).
    //! 
    //! @return     ブラックボードを返却します.
    //-------------------------------------------------------------------------
    const Blackboard& GetBlackboard() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    static PhaseManager s_Instance;                 //!< シングルトンインスタンス.
    IPhaseFactory*      m_pFactory = nullptr;       //!< フェーズファクトリー.
    uint64_t            m_PhaseId  = UINT64_MAX;    //!< 現在のフェーズ番号.
    IPhase*             m_pPhase   = nullptr;       //!< 現在のフェーズ.
    Blackboard          m_Blackboard;               //!< フェーズ間のデータ受け渡し用.

    //=========================================================================
    // private methods.
    //=========================================================================
 
    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    PhaseManager();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~PhaseManager();

    PhaseManager             (const PhaseManager&) = delete;    // アクセス禁止.
    PhaseManager& operator = (const PhaseManager&) = delete;    // アクセス禁止.
};

} // namespace asdx
