#include <string>
#include <fnd/asdxMacro.h>
#include <fnd/asdxList.h>


namespace asdx {

///////////////////////////////////////////////////////////////////////////////
// TaskBase class
///////////////////////////////////////////////////////////////////////////////
class TaskBase : public List<TaskBase>::Node
{
public:
    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~TaskBase() = default;

    //-------------------------------------------------------------------------
    //! @brief      生成時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnCreate() {}

    //-------------------------------------------------------------------------
    //! @brief      破棄時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnRemove() {}

    //-------------------------------------------------------------------------
    //! @brief      更新時の処理です.
    //!
    //! @param[in]      deltaSec   前フレームからの差分時間(単位：秒).
    //-------------------------------------------------------------------------
    virtual void OnUpdate(float deltaSec) {}

    //-------------------------------------------------------------------------
    //! @brief      描画時の処理です.
    //-------------------------------------------------------------------------
    virtual void OnDraw() {}

    //-------------------------------------------------------------------------
    //! @brief      完了フラグを取得します.
    //-------------------------------------------------------------------------
    virtual bool IsComplete() const { return false; }

    //-------------------------------------------------------------------------
    //! @brief      削除フラグを取得します.
    //-------------------------------------------------------------------------
    virtual bool IsDisposable() const { return false; }

#if ASDX_DEBUG
    //-------------------------------------------------------------------------
    //! @brief      デバッグ文字列を設定します.
    //-------------------------------------------------------------------------
    void SetDebugString(const std::string& value) { m_DebugString = value; }

    //-------------------------------------------------------------------------
    //! @brief      デバッグ文字列を取得します.
    //-------------------------------------------------------------------------
    const std::string& GetDebugString() const { return m_DebugString; }
#endif//ASDX_DEBUG

private:
    //=========================================================================
    // private variables.
    //=========================================================================
#if ASDX_DEBUG
    std::string m_DebugString;  //!< デバッグ文字列.
#endif//ASDX_DEBUG
};


///////////////////////////////////////////////////////////////////////////////
// TaskManagerBase class.
///////////////////////////////////////////////////////////////////////////////
class TaskManagerBase
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    TaskManagerBase();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    virtual ~TaskManagerBase();

    //-------------------------------------------------------------------------
    //! @brief      タスクを生成します.
    //-------------------------------------------------------------------------
    template<typename T, class... Args>
    T* CreateTask(Args&&... args)
    {
        auto buf = Alloc(sizeof(T));
        if (!buf)
            return nullptr;

        auto pTask = new (buf) T(std::forward<Args>(args)...);
        pTask->OnCreate();
        m_TaskList.push_back(pTask);
        return pTask;
    }

    //-------------------------------------------------------------------------
    //! @brief      タスクを削除します.
    //! 
    //! @param[in]      破棄するタスクへのポインタ.
    //-------------------------------------------------------------------------
    void RemoveTask(TaskBase*& ptr);

    //-------------------------------------------------------------------------
    //! @brief      更新処理です.
    //! 
    //! @param[in]      deltaSec        差分時間(秒).
    //-------------------------------------------------------------------------
    void Update(float deltaSec);

    //-------------------------------------------------------------------------
    //! @brief      描画処理です.
    //-------------------------------------------------------------------------
    void Draw();

    //-------------------------------------------------------------------------
    //! @brief      全てのタスクが完了したかチェックします.
    //! 
    //! @retval true    全タスク完了.
    //! @retval false   未完了.
    //-------------------------------------------------------------------------
    bool IsAllCompleted() const;

    //-------------------------------------------------------------------------
    //! @brief      破棄可能なタスクを削除します.
    //-------------------------------------------------------------------------
    void RemoveDisposable();

    //-------------------------------------------------------------------------
    //! @brief      反復処理を行います.
    //-------------------------------------------------------------------------
    template<typename Action>
    void ForEach(Action action)
    {
        for(auto& itr : m_TaskList)
            action(itr);
    }

protected:
    //=========================================================================
    // protected variables.
    //=========================================================================
    List<TaskBase> m_TaskList;

    //=========================================================================
    // protected methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      メモリを確保します.
    //-------------------------------------------------------------------------
    virtual void* Alloc(size_t size) = 0;

    //-------------------------------------------------------------------------
    //! @brief      メモリを解放します.
    //-------------------------------------------------------------------------
    virtual void Free(void* ptr) = 0;
};

} // namespace asdx
